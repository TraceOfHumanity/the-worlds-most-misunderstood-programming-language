// ==========================================================================
// INTERFACE VS TYPE — ДВА СПОСОБИ ОПИСАТИ ФОРМУ ДАНИХ
// ==========================================================================

// 0. ЗАГАЛЬНА ІДЕЯ
// -----------------------------------------------------
// interface і type alias — це ДВА РІЗНІ синтаксиси, які в БІЛЬШОСТІ
// повсякденних випадків роблять ОДНЕ Й ТЕ САМЕ: дають ІМ'Я формі
// об'єкта, щоб не переписувати її щоразу. Але це НЕ повні синоніми —
// у кожного є можливості, яких немає в іншого, і кілька важливих
// відмінностей у ПОВЕДІНЦІ (не лише в синтаксисі).


// ==========================================================================
// 1. БАЗОВИЙ СИНТАКСИС — ОДНАКОВИЙ РЕЗУЛЬТАТ, РІЗНИЙ ЗАПИС
// ==========================================================================

// interface — окрема конструкція мови (як class), СВОЄ ключове слово:
interface UserInterface {
  name: string;
  age: number;
}

// type alias — це просто ІМ'Я ДЛЯ БУДЬ-ЯКОГО типу (через знак =),
// об'єктна форма тут — лише ОДНЕ з можливих застосувань type:
type UserType = {
  name: string;
  age: number;
};

// ОБИДВА варіанти використовуються ІДЕНТИЧНО:
const userViaInterface: UserInterface = { name: "Олег", age: 30 };
const userViaType: UserType = { name: "Ірина", age: 25 };
console.log(userViaInterface.name, userViaType.name);


// ==========================================================================
// 2. ГОЛОВНА ВІДМІННІСТЬ: type МОЖЕ ОПИСАТИ БУДЬ-ЩО, interface — ЛИШЕ ФОРМУ ОБ'ЄКТА
// ==========================================================================

// type alias працює для БУДЬ-ЯКОГО типу — примітивів, union,
// intersection, tuples, функцій — не тільки "форми об'єкта":

type ID = number | string;                 // union (детально в union-and-intersection-types.ts)
type Coordinate = [number, number];         // tuple
type Callback = (value: number) => void;    // тип функції
type Status = "pending" | "done" | "error"; // literal union

// interface ЦЬОГО НЕ МОЖЕ — interface описує ЛИШЕ "форму" (набір
// властивостей/методів), його НЕ можна прирівняти до union/tuple/
// примітива напряму:
//   interface ID = number | string; // ❌ синтаксична помилка — так не пишуть

// АЛЕ interface МОЖЕ описувати функції й tuple-подібні речі через
// СВІЙ синтаксис — просто виглядає інакше:
interface CallbackInterface {
  (value: number): void; // "call signature" — interface, що описує функцію
}
const cb: CallbackInterface = (value) => console.log(value * 2);
cb(5); // 10


// ==========================================================================
// 3. РОЗШИРЕННЯ: extends (interface) VS & (type)
// ==========================================================================

// interface РОЗШИРЮЄТЬСЯ через ключове слово extends — синтаксис,
// що виглядає точно як наслідування класів:
interface Animal {
  name: string;
}
interface Dog extends Animal {
  breed: string;
}
const myDog: Dog = { name: "Рекс", breed: "Лабрадор" };

// type ДОСЯГАЄ ТОГО САМОГО через intersection (`&`) — детально
// розглянуто в union-and-intersection-types.ts:
type AnimalType = { name: string };
type DogType = AnimalType & { breed: string };
const myDogType: DogType = { name: "Барсик", breed: "Дворняга" };

// ОБИДВА ПІДХОДИ дають ІДЕНТИЧНИЙ результат для простих випадків.
// Різниця з'являється, коли РОЗШИРЕННЯ КОНФЛІКТУЄ (див. п. 5 нижче).


// ==========================================================================
// 4. НАЙВАЖЛИВІША ВІДМІННІСТЬ У ПОВЕДІНЦІ: DECLARATION MERGING
// ==========================================================================

// interface З ТИМ САМИМ ІМЕНЕМ, оголошений ДРУГИЙ РАЗ у тому самому
// скоупі, НЕ перезаписує перший — TS АВТОМАТИЧНО ОБ'ЄДНУЄ (merge) їх
// в ОДИН interface з УСІМА полями з обох оголошень:

interface Config {
  timeout: number;
}
interface Config { // ✅ НЕ помилка — це ДОПОВНЕННЯ, а не перезапис!
  retries: number;
}
// тепер Config МАЄ ОБИДВА поля:
const config: Config = { timeout: 5000, retries: 3 };
console.log(config);

// type З ТИМ САМИМ ІМЕНЕМ ДРУГИЙ РАЗ — це ЗАВЖДИ ПОМИЛКА КОМПІЛЯЦІЇ:
// type Settings = { timeout: number };
// type Settings = { retries: number }; // ❌ Duplicate identifier 'Settings'.

// ЦЕ ЗОВСІМ РІЗНА ПОВЕДІНКА, і саме вона найчастіше вирішує вибір:
//   - declaration merging КОРИСНИЙ для розширення типів ІЗ ЗОВНІШНІХ
//     бібліотек (наприклад, додати власні поля до Express.Request —
//     стандартний патерн у .d.ts файлах бібліотек);
//   - але В ЗВИЧАЙНОМУ коді ДОДАТКОВЕ, "непомітне" об'єднання типів
//     з однаковим іменем МОЖЕ бути НЕБАЖАНИМ побічним ефектом —
//     type тут "суворіший" і одразу ловить дублікат імені як помилку.


// ==========================================================================
// 5. КОНФЛІКТ ПРИ РОЗШИРЕННІ: extends ЛОВИТЬ ПОМИЛКУ, & ДАЄ never
// ==========================================================================

// Якщо interface РОЗШИРЮЄ базовий і НАМАГАЄТЬСЯ змінити тип
// успадкованого поля на НЕСУМІСНИЙ — TS кидає ЯВНУ, зрозумілу помилку
// ЩЕ НА МОМЕНТІ ОГОЛОШЕННЯ:

interface Base {
  id: number;
}
// interface Derived extends Base {
//   id: string; // ❌ Interface 'Derived' incorrectly extends interface 'Base'.
//                  Types of property 'id' are incompatible.
// }

// Той САМИЙ конфлікт через intersection type НЕ ловиться настільки
// явно — TS просто "обчислює" перетин number & string, що дає never
// для конкретного поля, і ти дізнаєшся про проблему лише коли
// СПРОБУЄШ РЕАЛЬНО СТВОРИТИ значення цього типу:
type BaseType = { id: number };
type DerivedType = BaseType & { id: string }; // компілюється БЕЗ помилки тут...
// const broken: DerivedType = { id: "abc" }; // ...а помилка виникає ТІЛЬКИ ТУТ:
//   ❌ Type 'string' is not assignable to type 'never'.

// ЦЕ ВАЖЛИВА ПРАКТИЧНА ПЕРЕВАГА interface: конфлікти при розширенні
// виявляються РАНІШЕ й з ЗРОЗУМІЛІШИМ повідомленням про помилку.


// ==========================================================================
// 6. КЛАСИ: implements ПРАЦЮЄ З ОБОМА, АЛЕ interface — "ІДІОМАТИЧНІШИЙ" ВИБІР
// ==========================================================================

interface Shape {
  area(): number;
}
class Circle implements Shape {
  constructor(private radius: number) {}
  area(): number {
    return Math.PI * this.radius ** 2;
  }
}

// type теж МОЖЕ використовуватись з implements, якщо описує форму об'єкта:
type Sizeable = { area(): number };
class Square implements Sizeable {
  constructor(private side: number) {}
  area(): number {
    return this.side ** 2;
  }
}
console.log(new Circle(2).area().toFixed(2), new Square(3).area());

// ІСТОРИЧНО й ЗА КОНВЕНЦІЄЮ (зокрема, у офіційному styleguide
// TypeScript і в більшості команд) для "контрактів", які клас
// РЕАЛІЗУЄ, використовують САМЕ interface — це не технічна вимога,
// а питання читабельності й консистентності коду.


// ==========================================================================
// 7. ВІДОБРАЖЕННЯ В ПОМИЛКАХ/АВТОДОПОВНЕННІ (IDE) — НЕЗНАЧНА, АЛЕ РЕАЛЬНА РІЗНИЦЯ
// ==========================================================================

// Коли IDE показує підказку типу для interface — вона показує САМЕ
// ІМ'Я interface (Config), не розгортаючи його вміст. Для type,
// побудованого через intersection (&) — IDE ЧАСТО розгортає ВЕСЬ
// об'єднаний тип повністю (усі поля з обох частин перетину), що
// може бути МЕНШ читабельним для складних, багаторівневих типів.
// Це суто "зручність під час розробки", а не помилка компіляції.


// ==========================================================================
// 8. КОЛИ type ОБОВ'ЯЗКОВИЙ (interface НЕ ЗМОЖЕ)
// ==========================================================================

// а) Union/intersection як самостійний, іменований тип:
type PaymentMethod = "card" | "cash" | "crypto";

// б) Mapped types (перетворення існуючого типу за шаблоном — окрема
// велика тема, детально буде в файлі про utility types):
type ReadonlyUser = { readonly [K in keyof UserType]: UserType[K] };

// в) Conditional types (тип, що залежить від УМОВИ над іншим типом —
// теж окрема тема):
type IsString<T> = T extends string ? true : false;
type CheckA = IsString<"текст">; // true
type CheckB = IsString<42>;       // false

// interface НЕ МОЖЕ виразити ЖОДНЕ з цього напряму — тільки type.


// ==========================================================================
// 9. КОЛИ interface ТРАДИЦІЙНО ОБИРАЮТЬ (НЕ ОБОВ'ЯЗКОВО, А ЗА ЗВИЧАЄМ)
// ==========================================================================

// а) публічний API бібліотеки/модуля — форма даних, яку МОЖУТЬ
//    захотіти РОЗШИРИТИ споживачі бібліотеки (завдяки declaration
//    merging, показаному в п. 4);
// б) контракти для класів (implements) — за конвенцією;
// в) прості, "плоскі" описи форми об'єкта без union/intersection —
//    де МОЖНА обрати або те, або те, і interface читається
//    ідіоматичніше саме для "опису сутності".


// ==========================================================================
// 10. ШПАРГАЛКА-ПОРІВНЯННЯ
// ==========================================================================

// | Критерій                              | interface                          | type                                |
// |-------------------------------------------|----------------------------------------|-----------------------------------------|
// | Може описати union/intersection/tuple/примітив | ❌ ні, лише форму об'єкта       | ✅ так, будь-який тип                  |
// | Розширення                              | extends (окреме ключове слово)       | & (intersection)                       |
// | Повторне оголошення з тим самим іменем | ОБ'ЄДНУЄТЬСЯ (declaration merging)   | ПОМИЛКА (Duplicate identifier)         |
// | Конфлікт типів при розширенні          | явна помилка НА МОМЕНТІ оголошення   | тихо стає never, помилка — при використанні |
// | Mapped / conditional types              | ❌ ні                                 | ✅ так                                  |
// | implements у класах                     | ✅ ідіоматичний вибір                 | ✅ теж працює, якщо описує форму об'єкта |
// | Типове застосування                     | публічні API, контракти класів       | union/literal-типи, складні трансформації типів |


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - для ПРОСТОЇ форми об'єкта interface і type — практично
//   взаємозамінні, вибір здебільшого стилістичний
// - interface МОЖЕ ЛИШЕ описувати форму об'єкта (включно з call-
//   сигнатурами функцій), type МОЖЕ описувати БУДЬ-ЯКИЙ тип —
//   union, intersection, tuple, mapped, conditional
// - НАЙВАЖЛИВІША поведінкова різниця: interface з ОДНАКОВИМ іменем,
//   оголошений повторно, ОБ'ЄДНУЄТЬСЯ (declaration merging); type —
//   одразу дає помилку "Duplicate identifier"
// - конфлікт типів при розширенні: interface extends ловить це ЯВНО
//   й РАНО; type & "мовчки" зводить конфліктне поле до never, і
//   помилка виринає пізніше, при реальному використанні
// - для publічних API бібліотек і контрактів класів (implements) —
//   за конвенцією обирають interface; для union/literal-типів і
//   складних трансформацій типів — ЛИШЕ type (альтернативи немає)