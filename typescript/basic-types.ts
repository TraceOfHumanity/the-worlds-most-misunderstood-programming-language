// ==========================================================================
// БАЗОВІ ТИПИ ТА TYPE ANNOTATIONS — TYPESCRIPT VS JAVASCRIPT
// ==========================================================================

// 0. ЩО ТАКЕ TypeScript НАСПРАВДІ
// -----------------------------------------------------
// TypeScript — це JavaScript + СТАТИЧНА СИСТЕМА ТИПІВ, яка існує
// ЛИШЕ НА ЕТАПІ РОЗРОБКИ/КОМПІЛЯЦІЇ. Компілятор (tsc) ПЕРЕВІРЯЄ типи,
// а потім ПРОСТО ВИДАЛЯЄ їх, залишаючи чистий JS — жодна анотація
// типу НЕ ІСНУЄ в рантаймі, вона не сповільнює виконання і не
// доступна через typeof/introspection.
//
// Це КЛЮЧОВА відмінність від динамічної типізації JS (детально
// розібраної в common/type-coercion.js): у JS тип значення
// перевіряється ПІД ЧАС виконання (runtime), у TS — ПІД ЧАС
// КОМПІЛЯЦІЇ (compile-time), а в рантаймі коду з перевірками вже
// не залишається взагалі.

// Ось як виглядає той самий код у JS і в TS:

// JavaScript (немає жодних анотацій — тип дізнається лише в рантаймі):
//   function addJS(a, b) {
//     return a + b;
//   }
//   addJS(1, "2"); // "12" — рантайм МОВЧКИ дозволяє це (детально в type-coercion.js)

// TypeScript (анотація типу — ПОМИЛКА виявляється ДО запуску коду):
function addTS(a: number, b: number): number {
  return a + b;
}
addTS(1, 2); // 3 — ок
// addTS(1, "2"); // ❌ Компілятор кине помилку ЩЕ ДО запуску:
// "Argument of type 'string' is not assignable to parameter of type 'number'."


// ==========================================================================
// 1. СИНТАКСИС TYPE ANNOTATION: ЗАВЖДИ `: Тип` ПІСЛЯ ІДЕНТИФІКАТОРА
// ==========================================================================

// Анотація типу пишеться ПІСЛЯ імені змінної/параметра/поля, через
// двокрапку — це та сама позиція, де в JS нічого немає:

let age: number = 30;
let username: string = "Олег";
let isActive: boolean = true;

// В JS цей самий код виглядав би просто:
//   let age = 30;
//   let username = "Олег";
//   let isActive = true;
// TS не змінює те, ЯК код ПРАЦЮЄ — лише додає перевірку, ЩО можна
// присвоїти цій змінній.


// ==========================================================================
// 2. ПРИМІТИВНІ ТИПИ — ТОЧНО ТІ САМІ, ЩО Й У JS, АЛЕ З ПЕРЕВІРКОЮ
// ==========================================================================

// TypeScript НЕ ВИГАДУЄ нові типи даних — він лише "називає" ті самі
// примітиви, що вже є в JS (детально в common/type-coercion.js, п. 2),
// і перевіряє, щоб змінна ЗАВЖДИ відповідала заявленому типу:

let tsNumber: number = 42;        // те саме, що typeof x === "number" у JS
let tsString: string = "текст";    // те саме, що typeof x === "string"
let tsBoolean: boolean = false;    // те саме, що typeof x === "boolean"
let tsBigInt: bigint = 42n;        // те саме, що typeof x === "bigint"
let tsSymbol: symbol = Symbol("id"); // те саме, що typeof x === "symbol"
let tsUndefined: undefined = undefined;
let tsNull: null = null;

// ПОМИЛКА ПРИСВОЄННЯ НЕПРАВИЛЬНОГО ТИПУ ВИЯВЛЯЄТЬСЯ ЩЕ ДО ЗАПУСКУ:
// tsNumber = "42"; // ❌ Type 'string' is not assignable to type 'number'.

// У ЧИСТОМУ JS ТАКОГО ЗАХИСТУ НЕМАЄ — присвоєння іншого типу просто
// МОВЧКИ ПРАЦЮЄ, і про проблему дізнаєшся хіба що в рантаймі (або й
// ніколи, якщо код "випадково" не зламався):
//   let numberJS = 42;
//   numberJS = "42"; // ок для JS, ніяких попереджень


// ==========================================================================
// 3. TYPE INFERENCE — TS ЧАСТО МОЖЕ "ВГАДАТИ" ТИП САМ, БЕЗ АНОТАЦІЇ
// ==========================================================================

// Якщо змінній ОДРАЗУ присвоюється значення, TS АВТОМАТИЧНО виводить
// (infers) тип із самого значення — писати анотацію РУЧНО НЕ ОБОВ'ЯЗКОВО:

let inferredNumber = 42;         // TS сам виводить тип: number
let inferredString = "текст";     // TS сам виводить тип: string
// inferredNumber = "тепер рядок"; // ❌ Помилка — TS "запам'ятав" number
                                     // з першого присвоєння, хоч анотації не було

// Анотацію ПИШУТЬ ЯВНО, КОЛИ:
//   а) значення ще НЕМАЄ в момент оголошення (let x: number; — заповниться пізніше)
//   б) тип, який TS вивів би сам, ШИРШИЙ, ніж треба (детально в п. 8 нижче)
//   в) сигнатура функції — параметри й повертане значення (компілятор
//      НЕ може "вгадати" тип параметра функції з нічого)

let laterAssigned: number;
laterAssigned = 100; // ок, тип уже заявлений заздалегідь


// ==========================================================================
// 4. МАСИВИ: Тип[] АБО Array<Тип>
// ==========================================================================

let numbersArr: number[] = [1, 2, 3];
let stringsArr: Array<string> = ["a", "b", "c"]; // ідентичний запис, інший синтаксис
let mixedNotAllowed: number[] = [1, 2, 3];
// mixedNotAllowed.push("текст"); // ❌ Argument of type 'string' is not
                                     // assignable to parameter of type 'number'.

// У JS масив може містити БУДЬ-ЯКІ типи одночасно без жодних скарг:
//   const jsArr = [1, "два", true]; // повністю легально для JS
// У TS для ЗМІШАНОГО масиву довелось би явно оголосити union-тип
// (детально розглянемо в окремому файлі про union/intersection types):
let explicitMixedArr: (number | string)[] = [1, "два"]; // TS дозволяє,
                                                            // якщо це заявлено ЯВНО


// ==========================================================================
// 5. TUPLES — МАСИВ ІЗ ФІКСОВАНОЮ ДОВЖИНОЮ Й ТИПОМ КОЖНОГО ЕЛЕМЕНТА
// ==========================================================================

// Tuple — концепція, якої НЕМАЄ в самому JS взагалі: це масив, де
// ЗАЗДАЛЕГІДЬ відомі і КІЛЬКІСТЬ елементів, і ТИП КОЖНОГО з них окремо.

let coordinate: [number, number] = [10, 20]; // рівно 2 числа
// coordinate = [10, 20, 30]; // ❌ Source has 3 element(s) but target allows only 2.
// coordinate = ["10", 20];    // ❌ Type 'string' is not assignable to type 'number'.

let httpResponseTuple: [number, string] = [200, "OK"]; // код + повідомлення,
                                                          // РІЗНІ типи на РІЗНИХ позиціях
console.log(httpResponseTuple[0], httpResponseTuple[1]); // 200 "OK"

// У ЧИСТОМУ JS немає способу гарантувати, що масив [200, "OK"] завжди
// матиме РІВНО 2 елементи саме таких типів — це ЛИШЕ угода в голові
// розробника; tuple робить цю угоду перевірюваною компілятором.


// ==========================================================================
// 6. any — "ВІДКЛЮЧЕННЯ" ПЕРЕВІРКИ ТИПІВ (уживай МІНІМАЛЬНО)
// ==========================================================================

// any — тип, який ГОВОРИТЬ компілятору: "не перевіряй цю змінну взагалі,
// довіряй мені". Це, по суті, ПОВЕРНЕННЯ до поведінки чистого JS для
// ЦІЄЇ конкретної змінної — TS БІЛЬШЕ НЕ дає жодних гарантій щодо неї.

let anythingGoes: any = 42;
anythingGoes = "тепер рядок";    // ок, any дозволяє БУДЬ-ЩО
anythingGoes = { key: "value" }; // теж ок
anythingGoes.nonExistentMethod(); // ❌ НЕ ловиться компілятором! Впаде в РАНТАЙМІ,
                                    // так само, як звичайний JS-код

// any "ЗАРАЗЖАЄ" усе, куди потрапляє — якщо функція повертає any,
// увесь подальший код, що працює з результатом, теж втрачає перевірку.
// Тому any вважається "аварійним люком", а НЕ звичним інструментом.


// ==========================================================================
// 7. unknown — БЕЗПЕЧНА АЛЬТЕРНАТИВА any
// ==========================================================================

// unknown теж означає "тип поки невідомий", АЛЕ, на відміну від any,
// ЗАБОРОНЯЄ використовувати значення БЕЗ ПОПЕРЕДНЬОЇ перевірки типу
// (детально механізм narrowing розглянемо в окремому файлі, тут —
// лише сама відмінність від any):

let notSureYet: unknown = "могло бути що завгодно";
// notSureYet.toUpperCase(); // ❌ Object is of type 'unknown'. — заборонено НАПРЯМУ

if (typeof notSureYet === "string") {
  console.log(notSureYet.toUpperCase()); // ✅ ок — TS "звузив" тип до string
                                            // усередині цього if-блоку
}

// ПРАВИЛО: якщо значення дійсно НЕВІДОМОГО типу (наприклад, дані з
// зовнішнього API чи user input) — використовуй unknown, а не any.
// unknown ЗМУШУЄ явно перевірити тип перед використанням, any —
// дозволяє мовчки помилятись.


// ==========================================================================
// 8. void — ВІДСУТНІСТЬ ЗНАЧЕННЯ, ЩО ПОВЕРТАЄТЬСЯ
// ==========================================================================

// void використовується як тип ПОВЕРНЕНОГО значення функції, яка
// НІЧОГО корисного не повертає (лише виконує побічну дію):

function logMessage(message: string): void {
  console.log(message);
  // немає return — або є "порожній" return;
}
logMessage("Привіт!"); // "Привіт!"

// У ЧИСТОМУ JS такої функції "тип повернення" взагалі не існує як
// поняття — функція просто повертає undefined, якщо немає return.
// void — це СПОСІБ TS ЯВНО задекларувати намір "ця функція не
// призначена повертати значення", навіть якщо технічно вона все одно
// повертає undefined у рантаймі.


// ==========================================================================
// 9. never — ТИП, ЯКИЙ НІКОЛИ НЕ МАЄ ЗНАЧЕННЯ
// ==========================================================================

// never позначає функцію/вираз, який НІКОЛИ НЕ ЗАВЕРШУЄТЬСЯ нормально —
// або завжди кидає помилку, або йде в нескінченний цикл. Це НЕ те
// саме, що void (яка ЗАВЕРШУЄТЬСЯ, просто без значення).

function throwError(message: string): never {
  throw new Error(message); // функція ЗАВЖДИ кидає, ніколи не "повертається"
}

function infiniteLoop(): never {
  while (true) {
    // ніколи не завершується
  }
}

// ПРАКТИЧНЕ ЗАСТОСУВАННЯ: never чудово ловить ПРОПУЩЕНІ ВИПАДКИ
// (exhaustiveness checking) — детально розглянемо, коли дійдемо до
// union-типів і switch, тут — лише сама ідея:
type Shape = { kind: "circle"; radius: number } | { kind: "square"; side: number };
function getArea(shape: Shape): number {
  switch (shape.kind) {
    case "circle":
      return Math.PI * shape.radius ** 2;
    case "square":
      return shape.side ** 2;
    default:
      // якщо колись додасться НОВИЙ варіант Shape і про нього забудуть
      // тут — TS підкаже помилку, бо shape тут МАВ БИ мати тип never,
      // а не якийсь реальний варіант, що "не влізає" в жоден case
      const exhaustiveCheck: never = shape;
      return exhaustiveCheck;
  }
}
console.log(getArea({ kind: "circle", radius: 2 }).toFixed(2)); // "12.57"


// ==========================================================================
// 10. object, Object, {} — ТРИ СХОЖІ, АЛЕ РІЗНІ ЗАПИСИ (ПАСТКА ДЛЯ ПОЧАТКІВЦІВ)
// ==========================================================================

// object (мала буква) — БУДЬ-ЯКЕ НЕ-примітивне значення (не number/
// string/boolean/symbol/null/undefined/bigint) — тобто об'єкти й масиви:
let anyObject: object = { key: "value" };
anyObject = [1, 2, 3]; // масив теж object — ок
// anyObject = 42; // ❌ Type 'number' is not assignable to type 'object'.

// {} (порожній тип-літерал) — ОЗНАЧАЄ "БУДЬ-ЯКЕ значення, окрім null
// та undefined" — це ЧАСТА ПАСТКА, бо звучить як "порожній об'єкт",
// а насправді дозволяє майже ВСЕ:
let almostAnything: {} = 42;       // ok!
almostAnything = "текст";           // ok!
almostAnything = { a: 1 };          // ok!
// almostAnything = null;            // ❌ не дозволено
// almostAnything = undefined;       // ❌ не дозволено

// Object (з великої літери) — тип, що описує ВСІ ВЛАСТИВОСТІ з
// Object.prototype (toString, hasOwnProperty тощо) — на практиці
// майже НІКОЛИ не використовується напряму в коді.

// РЕКОМЕНДАЦІЯ: для "довільного об'єкта з довільними полями"
// зазвичай краще явно описати структуру (детально — в окремому файлі
// про interface/type), а не покладатись на розмиті object/{}.


// ==========================================================================
// 11. type ANNOTATIONS ДЛЯ ФУНКЦІЙ: ПАРАМЕТРИ ТА ПОВЕРНЕНЕ ЗНАЧЕННЯ ОКРЕМО
// ==========================================================================

// Кожен параметр анотується ОКРЕМО, а тип повернення — ПІСЛЯ списку
// параметрів (перед {):

function multiply(a: number, b: number): number {
  return a * b;
}

// НЕОБОВ'ЯЗКОВІ параметри — знак ? ПІСЛЯ імені (тип параметра стає
// "Тип | undefined" автоматично):
function greet(name: string, greeting?: string): string {
  return `${greeting ?? "Привіт"}, ${name}!`;
}
console.log(greet("Марія"));            // "Привіт, Марія!"
console.log(greet("Марія", "Вітаю"));   // "Вітаю, Марія!"

// Параметри ЗІ ЗНАЧЕННЯМ ЗА ЗАМОВЧУВАННЯМ — тип ВИВОДИТЬСЯ з дефолту,
// анотацію можна не писати, хоча писати теж не заборонено:
function power(base: number, exponent = 2): number {
  return base ** exponent;
}
console.log(power(3));    // 9  (exponent за замовчуванням 2)
console.log(power(3, 3)); // 27


// ==========================================================================
// 12. ЗІСТАВЛЕННЯ: ЯК ТОЙ САМИЙ КОД ВИГЛЯДАЄ БЕЗ І З ТИПАМИ
// ==========================================================================

// JavaScript (жодних анотацій — усі помилки типів виявляються лише
// під час РЕАЛЬНОГО виконання коду, якщо взагалі виявляються):
//
//   function calculateTotal(price, quantity, discount) {
//     return price * quantity * (1 - discount);
//   }
//   calculateTotal(100, "5", 0.1); // "50050050050050050..." — рядок "5" множиться
//                                     на число 0.1, а потім конкатенується — БАГ,
//                                     що виявиться тільки при перегляді результату

// TypeScript (та сама логіка, з типами — компілятор ЗУПИНИТЬ до запуску):
function calculateTotal(price: number, quantity: number, discount: number): number {
  return price * quantity * (1 - discount);
}
console.log(calculateTotal(100, 5, 0.1)); // 450
// calculateTotal(100, "5", 0.1); // ❌ Argument of type 'string' is not
                                    // assignable to parameter of type 'number'.


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - TypeScript = JavaScript + типи, які існують ЛИШЕ на етапі
//   компіляції; у скомпільованому JS анотацій не залишається взагалі
// - синтаксис анотації: `ідентифікатор: Тип` — після імені змінної,
//   параметра чи поля
// - примітивні типи TS (number/string/boolean/bigint/symbol/undefined/
//   null) — це ті самі примітиви JS, просто з перевіркою на compile-time
// - type inference: TS сам виводить тип зі значення при ініціалізації —
//   явну анотацію найчастіше пишуть лише для параметрів функцій і
//   змінних без початкового значення
// - Тип[] / Array<Тип> — типізований масив; tuple [Тип1, Тип2] —
//   масив ФІКСОВАНОЇ довжини з РІЗНИМИ типами на кожній позиції
//   (концепція, якої в самому JS немає)
// - any — повністю вимикає перевірку типів (уживати як крайній
//   виняток); unknown — теж "невідомий тип", але ЗМУШУЄ перевірити
//   його ПЕРЕД використанням (безпечніша альтернатива any)
// - void — функція не повертає корисного значення; never — функція
//   ВЗАГАЛІ ніколи не завершується нормально (завжди throw / нескінченний цикл)
// - object / {} / Object — три РІЗНІ речі: object = не-примітив,
//   {} = "усе, крім null/undefined" (частa пастка), Object = тип із
//   методами Object.prototype (рідко потрібен напряму)
// - головна практична вигода: помилки типів (наприклад, передача
//   рядка туди, де очікується число) виявляються ДО запуску коду,
//   а не десь посеред виконання в продакшені