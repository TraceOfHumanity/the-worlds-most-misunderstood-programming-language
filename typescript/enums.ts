// ==========================================================================
// ENUMS — ІМЕНОВАНИЙ НАБІР КОНСТАНТ ЯК ОКРЕМА КОНСТРУКЦІЯ МОВИ
// ==========================================================================

// 0. ЗАГАЛЬНА ІДЕЯ
// -----------------------------------------------------
// enum — це, на відміну від УСЬОГО, що ми розглядали раніше (type,
// interface, keyof, as const), НЕ "стирається" повністю при
// компіляції — enum ГЕНЕРУЄ РЕАЛЬНИЙ JS-КОД, що ІСНУЄ в рантаймі
// (об'єкт-мапу). Це РОБИТЬ enum ВИНЯТКОМ серед конструкцій TS, і
// саме тому вибір "enum чи ні" — окреме, свідоме рішення, а не
// просто "зручний синтаксис".


// ==========================================================================
// 1. NUMERIC ENUM — ЗА ЗАМОВЧУВАННЯМ, ЧИСЛА, ЩО АВТОІНКРЕМЕНТУЮТЬСЯ
// ==========================================================================

enum Direction {
  Up,    // 0
  Down,  // 1
  Left,  // 2
  Right, // 3
}

function move(direction: Direction) {
  console.log(`рух: ${direction}`); // Direction.Up у виразі — просто число 0
}
move(Direction.Up);   // "рух: 0"
move(Direction.Right); // "рух: 3"

console.log(Direction.Up);   // 0 — це РЕАЛЬНЕ число в рантаймі
console.log(Direction[0]);   // "Up" — ЗВОРОТНЄ відображення число → назва (лише для numeric enum!)

// ПОЧАТКОВЕ ЗНАЧЕННЯ МОЖНА ЗАДАТИ ЯВНО — далі йде АВТОІНКРЕМЕНТ від нього:
enum HttpStatus {
  OK = 200,
  Created = 201,
  BadRequest = 400,
  NotFound = 404,
  ServerError = 500,
}
console.log(HttpStatus.NotFound); // 404


// ==========================================================================
// 2. ЩО РЕАЛЬНО ГЕНЕРУЄТЬСЯ В РАНТАЙМІ (НА ВІДМІНУ ВІД type/interface)
// ==========================================================================

// Скомпільований у звичайний JS, numeric enum ПЕРЕТВОРЮЄТЬСЯ
// ПРИБЛИЗНО в такий код (спрощено, дух генерації):
//
//   var Direction;
//   (function (Direction) {
//     Direction[(Direction["Up"] = 0)] = "Up";
//     Direction[(Direction["Down"] = 1)] = "Down";
//     Direction[(Direction["Left"] = 2)] = "Left";
//     Direction[(Direction["Right"] = 3)] = "Right";
//   })(Direction || (Direction = {}));
//
// Це САМЕ Й ДАЄ зворотнє відображення Direction[0] === "Up" — об'єкт
// Direction заповнюється В ОБИДВА боки (ключ→значення І значення→ключ).
// Порівняй це з type/interface/keyof — ЖОДЕН з них НЕ залишає ЖОДНОГО
// рядка коду після компіляції, enum — ЗАЛИШАЄ.


// ==========================================================================
// 3. STRING ENUM — БЕЗ АВТОІНКРЕМЕНТУ, БЕЗ ЗВОРОТНЬОГО ВІДОБРАЖЕННЯ
// ==========================================================================

enum LogLevel {
  Debug = "DEBUG",
  Info = "INFO",
  Warning = "WARNING",
  Error = "ERROR",
}

function log(level: LogLevel, message: string) {
  console.log(`[${level}] ${message}`);
}
log(LogLevel.Warning, "щось підозріле"); // "[WARNING] щось підозріле"

// У STRING enum КОЖНЕ значення ТРЕБА задати ЯВНО — автоінкремент тут
// НЕМОЖЛИВИЙ (немає "наступного рядка" за замовчуванням):
// enum Broken { A = "a", B, } // ❌ Enum member must have initializer.

console.log(LogLevel.Warning); // "WARNING" — реальний рядок, а НЕ число
// console.log(LogLevel["WARNING"]); // ❌ немає ЗВОРОТНЬОГО відображення
                                        // для string enum — лише Debug→"DEBUG",
                                        // а не "DEBUG"→Debug!


// ==========================================================================
// 4. HETEROGENEOUS ENUM (ЗМІШАНИЙ) — ІСНУЄ, АЛЕ МАЙЖЕ НІКОЛИ НЕ ПОТРІБЕН
// ==========================================================================

enum MixedEnum {
  No = 0,
  Yes = "YES",
}
// технічно валідно, АЛЕ офіційна документація TS прямо радить
// уникати такого змішування — плутає й НЕ дає жодної практичної
// переваги над двома окремими enum'ами


// ==========================================================================
// 5. const enum — ТЕ САМЕ, АЛЕ БЕЗ РАНТАЙМ-ОБ'ЄКТА (ІНЛАЙНИТЬСЯ)
// ==========================================================================

const enum Size {
  Small,
  Medium,
  Large,
}
function getSizeLabel(size: Size): string {
  return size === Size.Small ? "S" : size === Size.Medium ? "M" : "L";
}
console.log(getSizeLabel(Size.Medium)); // "M"

// НА ВІДМІНУ ВІД звичайного enum, const enum НЕ ГЕНЕРУЄ об'єкт-мапу
// в рантаймі — КОЖНЕ звернення Size.Medium ЗАМІНЮЄТЬСЯ НАПРЯМУ на
// число 1 ще ПІД ЧАС КОМПІЛЯЦІЇ (аналог inline-константи, як
// #define у C). Це ШВИДШЕ й НЕ залишає зайвого коду в бандлі.
//
// АЛЕ: const enum МАЄ ВІДОМІ ОБМЕЖЕННЯ (не працює з isolatedModules,
// проблемний при роздільній компіляції файлів, НЕ підтримується
// деякими інструментами збірки як Babel) — саме тому ОФІЦІЙНА
// документація TypeScript сьогодні РЕКОМЕНДУЄ уникати const enum
// у коді, що піде через такі інструменти.


// ==========================================================================
// 6. enum ЯК ТИП ДЛЯ ЗВИЧАЙНИХ ЧИСЕЛ — ЧАСТА, НЕБЕЗПЕЧНА ПАСТКА
// ==========================================================================

// Numeric enum за замовчуванням ДОЗВОЛЯЄ присвоїти БУДЬ-ЯКЕ число —
// компілятор ВВАЖАЄ, що "число — це завжди потенційно валідний
// varіант enum" (успадковано з C-подібних мов, де enum — це просто
// іменовані числа):

function setDirection(direction: Direction) {
  console.log(direction);
}
setDirection(Direction.Up); // ok
// setDirection(999); // ❌ У НОВІШИХ версіях TS це ПОМИЛКА для numeric enum
                         // (Argument of type '999' is not assignable...),
                         // АЛЕ ІСТОРИЧНО (старіші версії/деякі конфігурації)
                         // ЦЕ ПРОХОДИЛО без жодної скарги — джерело
                         // класичних "тихих" багів у старому коді.

// STRING enum ЦІЄЇ ПРОБЛЕМИ НЕ МАЄ — вони НІКОЛИ НЕ приймають
// "довільний" рядок, лише РЕАЛЬНІ учасники enum:
// log("RANDOM" as LogLevel, "test"); // потрібне явне приведення типу,
                                          // просто так довільний рядок НЕ підійде


// ==========================================================================
// 7. АЛЬТЕРНАТИВА enum: `as const` ОБ'ЄКТ + literal union (ПОРІВНЯННЯ)
// ==========================================================================

// (детально сам патерн — у typescript/const-assertions.ts, п. 4;
// тут — ПРЯМЕ порівняння з enum за всіма практичними параметрами)

const DirectionConst = {
  Up: "up",
  Down: "down",
  Left: "left",
  Right: "right",
} as const;
type DirectionType = (typeof DirectionConst)[keyof typeof DirectionConst];

function moveConst(direction: DirectionType) {
  console.log(`рух: ${direction}`);
}
moveConst(DirectionConst.Up); // "рух: up"


// ==========================================================================
// 8. ШПАРГАЛКА: enum VS `as const`-ОБ'ЄКТ — ЩО ОБРАТИ
// ==========================================================================

// | Критерій                              | enum                                  | `as const` об'єкт + union         |
// |-------------------------------------------|-------------------------------------------|---------------------------------------|
// | Залишає код у рантаймі                | ТАК (об'єкт-мапа генерується)            | НІ, звичайний JS-об'єкт, як писав сам |
// | Зворотнє відображення (0 → "Up")      | ТАК, але лише для numeric enum           | НІ, потрібно писати вручну            |
// | Tree-shaking / розмір бандла          | ГІРШЕ (зайвий згенерований код)          | КРАЩЕ (жодного зайвого коду)          |
// | Сумісність із isolatedModules/Babel   | звичайний enum — ОК, const enum — НІ    | завжди ОК (це просто JS)              |
// | Захист від "довільного числа"         | numeric enum — ІСТОРИЧНО слабший        | сильний одразу (literal union)        |
// | Використання як значення (Enum.X)     | так, природно                            | так, DirectionConst.Up                |
// | Використання як тип (параметр функції)| так, ім'я enum саме є типом              | потрібен ОКРЕМИЙ `keyof typeof` тип   |
// | Рекомендація сучасних style guide     | багато команд (і сам TS team) РАДЯТЬ    | ЗАЗВИЧАЙ типовий сучасний вибір       |
// |                                          | уникати на користь union у нових проєктах |                                     |


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - enum — ЄДИНА з розглянутих конструкцій, яка НЕ "стирається"
//   повністю при компіляції: генерує РЕАЛЬНИЙ JS-об'єкт у рантаймі
// - numeric enum: автоінкремент значень від 0 (або від заданого
//   стартового числа), МАЄ зворотнє відображення число→назва
// - string enum: КОЖЕН варіант задається ЯВНО, БЕЗ зворотнього
//   відображення, і БЕЗ historичної пастки з "довільним числом"
// - heterogeneous (змішаний) enum технічно існує, але майже НІКОЛИ
//   не потрібен на практиці
// - const enum — та сама ідея, АЛЕ інлайниться на етапі компіляції
//   без рантайм-об'єкта; має ВІДОМІ обмеження сумісності з
//   інструментами збірки (isolatedModules, Babel) — сучасна
//   документація TS РЕКОМЕНДУЄ його уникати
// - альтернатива без жодного рантайм-коду — `as const` об'єкт +
//   `(typeof obj)[keyof typeof obj]` (детально в const-assertions.ts) —
//   сьогодні ЧАСТО типовий вибір замість enum у нових проєктах,
//   хоча enum лишається зручним, коли реально потрібне зворотнє
//   відображення значення → ім'я