// ==========================================================================
// FUNCTION SIZE & INLINING — V8 OPTIMIZATION
// ==========================================================================

// 0. ЗАГАЛЬНА ІДЕЯ
// -----------------------------------------------------
// Inlining — оптимізація TurboFan, яка КОПІЮЄ ТІЛО ФУНКЦІЇ прямо в
// місце виклику, усуваючи overhead функційного виклику (push/pop
// стека, передача аргументів, jump до адреси). Крім усунення overhead,
// inlining ВІДКРИВАЄ ДВЕРІ для подальших оптимізацій — V8 бачить
// БІЛЬШИЙ КОНТЕКСТ і може спростити математику, усунути мертвий код тощо.
//
// Правильне використання дає 1.5-3x приросту для гарячих функцій.


// ==========================================================================
// 1. CALL OVERHEAD НА РІВНІ CPU
// ==========================================================================

// ARM64: кожен виклик функції коштує:
//
//   stp x29, x30, [sp, #-16]!  ; збережи frame pointer та link register
//   mov x0, #5                  ; передай аргумент a
//   mov x1, #3                  ; передай аргумент b
//   bl  add                     ; jump до функції (зберігає адресу повернення)
//   ldp x29, x30, [sp], #16    ; відновити стан після повернення
//
// На 1,000,000 викликів: ~20-50ms ТІЛЬКИ від overhead, без самого
// обчислення!
//
// ПІСЛЯ INLINING:
//
//   ; замість виклику — одна інструкція прямо в циклі:
//   add x0, x19, #5   ; i + 5 без жодного виклику


// ==========================================================================
// 2. ЛІМІТИ INLINING У V8
// ==========================================================================

//   Розмір функції:    < ~600 байтів байт-коду
//   Глибина inline:    ~5-6 рівнів вкладеності
//   Кількість inline:  ~1000 на одну компіляцію
//
// Якщо функція ПЕРЕВИЩУЄ ліміт — V8 НІКОЛИ її не інлайнить, незалежно
// від частоти виклику.


// ==========================================================================
// 3. INLINING ВІДКРИВАЄ ПОДАЛЬШІ ОПТИМІЗАЦІЇ
// ==========================================================================

// Це НАЙВАЖЛИВІШИЙ ефект inlining — після копіювання коду V8 бачить
// БІЛЬШИЙ КОНТЕКСТ і може оптимізувати далі:

function multiplyByTwo(x) {
  return x * 2;
}
function addTen(x) {
  return x + 10;
}
function process(x) {
  return addTen(multiplyByTwo(x));
}

// Після inlining V8 бачить (концептуально):
//   function process(x) { return x * 2 + 10; }
//
// Потім CONSTANT FOLDING:
//   ARM64: lsl x0, x0, #1  → add x0, x0, #10
//   Весь process() → 2 інструкції!
//
// БЕЗ inlining V8 не міг би побачити, що (x * 2) + 10 — один простий
// вираз (бо x * 2 і x + 10 живуть у РІЗНИХ, окремо скомпільованих
// функціях).


// ==========================================================================
// 4. ЩО РУЙНУЄ INLINING
// ==========================================================================

// 4.1. Занадто велика функція (> ~600 байтів байт-коду)
// -----------------------------------------------------
// function tooLarge(data) {
//   // 100+ рядків → ніколи не інлайниться
// }

// 4.2. try-catch УСЕРЕДИНІ функції
// -----------------------------------------------------
function withTryCatch(x) {
  try {
    return x * 2; // ❌ не інлайниться
  } catch (e) {
    return 0;
  }
}

// 4.3. Рекурсія
// -----------------------------------------------------
function factorial(n) {
  return n <= 1 ? 1 : n * factorial(n - 1); // ❌ не інлайниться
}

// 4.4. arguments об'єкт (legacy)
// -----------------------------------------------------
function withArguments() {
  return arguments[0] + arguments[1]; // ❌ не інлайниться
}

// 4.5. eval()
// -----------------------------------------------------
function withEval(x) {
  eval("console.log(x)"); // ❌ відключає ВСІ оптимізації для функції
  return x * 2;
}

// 4.6. debugger
// -----------------------------------------------------
function withDebugger(x) {
  debugger; // ❌ повністю відключає оптимізації
  return x * 2;
}


// ==========================================================================
// 5. ВАЖЛИВИЙ НЮАНС: try-catch ЗОВНІ НЕ РУЙНУЄ INLINING
// ==========================================================================

// ❌ try-catch УСЕРЕДИНІ → функція не інлайниться
function processItemBad(item) {
  try {
    return item.value * 2;
  } catch (e) {
    return 0;
  }
}

// ✅ try-catch ЗОВНІ → функція інлайниться нормально
function processItem(item) {
  return item.value * 2; // чиста функція, інлайниться!
}
function safeProcess(item) {
  try {
    return processItem(item); // processItem інлайниться ТУТ
  } catch (e) {
    return 0;
  }
}

// ПРАВИЛО: try-catch руйнує inlining ТІЛЬКИ для функції, УСЕРЕДИНІ
// якої він знаходиться. Функції, що ВИКЛИКАЮТЬСЯ всередині try-catch,
// — інлайняться нормально.


// ==========================================================================
// ПРАВИЛА ДЛЯ FUNCTION SIZE & INLINING
