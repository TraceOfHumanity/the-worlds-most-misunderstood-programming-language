// ПРАВИЛО 1: Збирай шматки в масив, роби один join() у кінці
// -----------------------------------------------------
const itemsForHtml = ["Яблуко", "Банан", "Вишня"];

// ❌ Потенційно повільно на великих обсягах / зі "змішаним" читанням
function buildHTMLBad(items) {
  let html = "";
  for (const item of items) {
    html += `<li>${item}</li>`;
  }
  return html;
}

// ✅ Передбачувано швидко: одна фінальна конкатенація
function buildHTML(items) {
  const parts = new Array(items.length);
  for (let i = 0; i < items.length; i++) {
    parts[i] = `<li>${items[i]}</li>`;
  }
  return parts.join("");
}
console.log(buildHTML(itemsForHtml));


// ПРАВИЛО 2: Уникай регулярних виразів і пошуку ВСЕРЕДИНІ циклу накопичення
// -----------------------------------------------------
// ❌ Кожна ітерація змушує V8 "сплющити" rope, щоб виконати .includes()
function buildLogBad(events) {
  let log = "";
  for (const event of events) {
    if (!log.includes(event.type)) { // читання ВСЕРЕДИНІ циклу накопичення!
      log += `${event.type}: ${event.message}\n`;
    }
  }
  return log;
}

// ✅ Розділи фази: спочатку збери дані (без читання проміжного рядка),
// потім один раз сформуй фінальний рядок
function buildLog(events) {
  const seen = new Set();
  const lines = [];
  for (const event of events) {
    if (!seen.has(event.type)) {
      seen.add(event.type);
      lines.push(`${event.type}: ${event.message}`);
    }
  }
  return lines.join("\n");
}


