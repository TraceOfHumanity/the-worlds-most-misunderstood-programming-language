const { performance } = require("perf_hooks");
const N = 100000;
const bigItems = Array.from({ length: N }, (_, i) => `item-${i}`);

let t0 = performance.now();
let concatResult = "";
for (const item of bigItems) {
  concatResult += `<li>${item}</li>`;
}
console.log(`+= у циклі:        ${(performance.now() - t0).toFixed(0)}ms (length=${concatResult.length})`);

t0 = performance.now();
const partsResult = new Array(bigItems.length);
for (let i = 0; i < bigItems.length; i++) {
  partsResult[i] = `<li>${bigItems[i]}</li>`;
}
const joined = partsResult.join("");
console.log(`Array + join():    ${(performance.now() - t0).toFixed(0)}ms (length=${joined.length})`);

