// Рядки в JS ІМУТАБЕЛЬНІ (детально в common/data-structures/String/String.js) —
// КОЖНА операція над рядком (конкатенація, slice, replace) СТВОРЮЄ НОВИЙ
// рядок, а не змінює старий. У гарячому циклі це означає БАГАТО
// проміжних алокацій — саме тому наївна конкатенація в циклі є однією
// з найпоширеніших "прихованих" причин повільного коду.
//
// Основне правило: не буди рядок через += у циклі. Збирай шматки в
// масив і роби ОДИН join() у кінці, або (для V8) покладайся на ROPES.


// ==========================================================================
// 1. ЧОМУ += У ЦИКЛІ ПОВІЛЬНИЙ (НАЇВНА МОДЕЛЬ)
// ==========================================================================

// Якби рядки завжди копіювались "буквально", кожен += означав би:
//   1) виділи пам'ять під НОВИЙ рядок довжиною (стара довжина + нова частина)
//   2) скопіюй УВЕСЬ старий вміст у нову пам'ять
//   3) допиши нову частину
//   4) стара пам'ять стає сміттям → GC-тиск
//
// На N ітерацій циклу з конкатенацією це давало б O(N²) складність
// копіювання (кожна ітерація копіює дедалі довший рядок).

function buildHTMLNaive(items) {
  let html = "";
  for (const item of items) {
    html += `<li>${item}</li>`; // потенційно новий рядок щоразу
  }
  return html;
}


// ==========================================================================
// 2. ЩО НАСПРАВДІ РОБИТЬ V8: ROPES (CONSSTRING)
// ==========================================================================

// V8 НЕ настільки наївний: для конкатенації довгих рядків він може
// створити внутрішню структуру ConsString ("rope") — об'єкт, що просто
// ЗБЕРІГАЄ ПОСИЛАННЯ на ліву й праву частини, а не копіює вміст одразу:
//
//   "abc" + "def" → ConsString { left: "abc", right: "def" }
//   (реальне копіювання відкладається до моменту, коли рядок ПОТРІБНО
//   прочитати ЯК ОДИН суцільний буфер — наприклад, indexOf(), charAt())
//
// Це ЗМ'ЯКШУЄ проблему для НАКОПИЧЕННЯ (простого += в циклі), АЛЕ:
//   - ConsString-дерево може стати ГЛИБОКИМ при тисячах конкатенацій —
//     кожна операція ЧИТАННЯ (не тільки фінальний вивід) змушує
//     "сплющити" (flatten) усе дерево в суцільний буфер, і це О(N)
//     операція, яка може відбутись у НЕОЧІКУВАНИЙ момент;
//   - якщо в циклі МІЖ конкатенаціями відбувається ЧИТАННЯ рядка
//     (наприклад, .length перевіряється рідко — це ОК, а от .charAt()
//     чи regex-перевірка ВСЕРЕДИНІ циклу — вже ні), rope доводиться
//     сплющувати РАЗ У РАЗ, і виграш зникає.
//
// ВИСНОВОК: покладатись на "може, V8 і так оптимізує" — НЕНАДІЙНО.
// Явний патерн з масивом + join() ПЕРЕДБАЧУВАНИЙ у БУДЬ-ЯКОМУ рушії.


