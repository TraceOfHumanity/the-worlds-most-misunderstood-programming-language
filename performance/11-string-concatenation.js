// ПРАВИЛО 4: Template literals — не безкоштовні, але й не "особливо повільні"
// -----------------------------------------------------
// Шаблонні рядки `${a}${b}` компілюються приблизно в той самий код,
// що й ручна конкатенація — вони НЕ мають прихованого overhead понад
// звичайний +. Головне джерело повільності — саме ЧАСТОТА конкатенацій
// у циклі, а не сам синтаксис.

const a = "x";
const b = "y";
console.log(`${a}${b}` === a + b); // true — семантично те саме


