// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - layout (reflow) — одна з найдорожчих стадій рендерингу браузера;
//   за замовчуванням браузер відкладає й батчить перерахунок layout
//   до одного разу за кадр
// - READ layout-залежної властивості (offsetWidth, getBoundingClientRect
//   тощо) ОДРАЗУ ПІСЛЯ WRITE стилю змушує браузер перерахувати layout
//   НЕГАЙНО й СИНХРОННО — forced synchronous layout
// - повторення цього патерну в циклі = layout thrashing: N елементів
//   → N синхронних reflow замість одного
// - головне правило: розділяй фази READ і WRITE — спочатку зчитай
//   усе, що треба, потім запиши все, що треба (batch read/write)
// - requestAnimationFrame — правильний момент для WRITE, синхронізований
//   з кадром; для частих подій (scroll/resize/mousemove) — throttle
//   через rAF-флаг
// - зміна className/classList замість купи окремих inline-стилів;
//   transform/opacity замість властивостей, що впливають на layout
//   (left/top/width/height/margin), коли можливо
// - профілюй через Chrome DevTools Performance tab — шукай часті
//   "Layout"-записи й попередження про forced reflow в консолі
//
// ЦЕЙ ПРИНЦИП — ЄДИНИЙ у серії, що стосується браузера, а не самого
// рушія V8, але логіка та сама: передбачувані, згруповані операції
// (batch) завжди дешевші за розкидані, чергування "читання-запис".