//   scrollWidth, scrollHeight, scrollTop, scrollLeft
//   getBoundingClientRect()
//   getComputedStyle() (для деяких властивостей)
//   window.getSelection()
//
// Якщо ОДРАЗУ ПІСЛЯ зміни стилю викликати БУДЬ-ЯКИЙ з них — це
// forced synchronous layout.


