// Це ЄДИНИЙ файл у цій серії, що стосується НЕ V8-рушія напряму, а
// того, ЯК браузер рендерить сторінку. Але причина та сама, що й у
// решти принципів: непередбачувані, "розкидані" операції змушують
// браузер робити ЗАЙВУ, дорогу роботу — тут це ПЕРЕРАХУНОК LAYOUT
// (розташування елементів на сторінці), а не деоптимізація V8.
//
// Основне правило: НЕ ЧЕРГУЙ читання layout-властивостей (offsetWidth,
// getBoundingClientRect тощо) із записом стилів у циклі. Спочатку
// прочитай УСЕ, що треба, потім запиши УСЕ, що треба.
//
// ЦЕЙ ФАЙЛ ПРИЗНАЧЕНИЙ ДЛЯ БРАУЗЕРНОГО СЕРЕДОВИЩА — приклади нижче
// потребують DOM (document, window) і НЕ виконаються напряму в Node.js.


// ==========================================================================
// 1. ЯК БРАУЗЕР РЕНДЕРИТЬ СТОРІНКУ (СПРОЩЕНО)
// ==========================================================================

// Конвеєр рендерингу (rendering pipeline), спрощено:
//
//   JavaScript → Style (обчислення CSS) → Layout (розташування,
//   "reflow") → Paint (малювання пікселів) → Composite (об'єднання шарів)
//
// LAYOUT — ОДНА З НАЙДОРОЖЧИХ стадій: браузер перераховує РОЗМІРИ й
// ПОЗИЦІЇ КОЖНОГО елемента, залежного від того, що ти змінив (а часто —
// і ВСІЄЇ сторінки, якщо зміна впливає на батьківські/сусідні елементи).
//
// За замовчуванням браузер намагається ВІДКЛАСТИ layout і зробити його
// ОДИН РАЗ за кадр (перед Paint) — навіть якщо ти змінив 100 стилів
// підряд, layout перерахується ОДИН раз, у потрібний момент.
//
// АЛЕ: якщо ти ЗАПИТУЄШ (READ) властивість, ЯКА ЗАЛЕЖИТЬ від layout
// (offsetWidth, offsetHeight, getBoundingClientRect(), scrollTop,
// getComputedStyle() тощо) ПІСЛЯ того, як щойно ЗМІНИВ стиль (WRITE) —
// браузер ЗМУШЕНИЙ негайно, СИНХРОННО перерахувати layout ПРЯМО ЗАРАЗ,
// щоб дати тобі АКТУАЛЬНЕ значення. Це називається FORCED SYNCHRONOUS
// LAYOUT (або "layout thrashing", коли це повторюється в циклі).


// ==========================================================================
// 2. LAYOUT THRASHING — ЧЕРГУВАННЯ READ/WRITE У ЦИКЛІ
// ==========================================================================

// ❌ КЛАСИЧНИЙ ПРИКЛАД LAYOUT THRASHING (браузерний псевдокод):
//
//   function resizeBoxesBad(boxes) {
//     for (const box of boxes) {
//       const width = box.offsetWidth;   // READ  — використовує layout
//       box.style.width = width + 10 + "px"; // WRITE — інвалідує layout
//       // ↑ наступна ітерація знову READ → браузер ЗМУШЕНИЙ перерахувати
//       //   layout ПРЯМО ТУТ, синхронно, для КОЖНОЇ ітерації!
//     }
//   }
//
// На N елементів — N ВИМУШЕНИХ синхронних layout-перерахунків замість
// ОДНОГО. Якщо N = 1000, а кожен reflow коштує ~1-5ms — це 1-5 СЕКУНД
// "фризу" замість долей мілісекунди.

// ✅ ПРАВИЛЬНО: спочатку УСІ READ, потім УСІ WRITE (batch read/write)
//
//   function resizeBoxesGood(boxes) {
//     // ФАЗА 1: зчитай усі потрібні значення ЗАЗДАЛЕГІДЬ
//     const widths = boxes.map((box) => box.offsetWidth); // READ, READ, READ...
//     // ФАЗА 2: запиши всі зміни — жодного READ між ними
//     boxes.forEach((box, i) => {
//       box.style.width = widths[i] + 10 + "px"; // WRITE, WRITE, WRITE...
//     });
//     // браузер перерахує layout ОДИН РАЗ, у потрібний момент
//   }


// ==========================================================================
// 3. ЯКІ ВЛАСТИВОСТІ "ЗМУШУЮТЬ" LAYOUT (READ, ЩО ТРИГЕРИТЬ REFLOW)
// ==========================================================================

// Найпоширеніші "layout-залежні" READ-властивості/методи:
