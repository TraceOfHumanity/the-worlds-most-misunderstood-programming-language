// V8 відстежує типи елементів масиву ОКРЕМО від типів звичайних властивостей:

const arrSmi = [1, 2, 3, 4, 5];       // PACKED_SMI_ELEMENTS (найшвидше)
const arrDouble = [1.1, 2.2, 3.3];     // PACKED_DOUBLE_ELEMENTS
const arrMixed = [1, 2, "three", 4];   // PACKED_ELEMENTS (повільніше для числових операцій)
const arrHoley = [1, 2, , 4, 5];       // HOLEY_SMI_ELEMENTS (діри = повільніше)

// ВАЖЛИВО: тип масиву може ТІЛЬКИ "деградувати", НАЗАД повернутись НЕ МОЖНА:
const degradingArr = [1, 2, 3];       // PACKED_SMI_ELEMENTS
degradingArr.push(3.14);               // → PACKED_DOUBLE_ELEMENTS (деградація!)
degradingArr.push("hello");            // → PACKED_ELEMENTS (деградація!)
// Назад до SMI вже НЕМОЖЛИВО, навіть якщо видалиш рядок!


