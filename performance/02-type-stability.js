// ПРАВИЛО 1: Функція повинна отримувати ОДИН тип
// -----------------------------------------------------
// ❌ Неправильно:
function formatBad(value) {
  return value.toString();
}
formatBad(42);
formatBad("hello");
formatBad(true);

// ✅ Правильно: окремі функції для різних типів
function formatNumber(value) {
  return value.toString();
}
function formatString(value) {
  return value;
}


// ПРАВИЛО 2: Явно конвертуй типи на вході
// -----------------------------------------------------
// ❌ Неправильно: значення від API може бути string або number
async function processUserBad(userId) {
  const user = await fetchUserStub(userId);
  return user.age * 2; // "30" * 2 або 30 * 2?
}

// ✅ Правильно: явна конвертація
async function processUser(userId) {
  const user = await fetchUserStub(userId);
  const age = Number(user.age); // ЗАВЖДИ number
  return age * 2;
}
function fetchUserStub() {
  return Promise.resolve({ age: "30" }); // заглушка для прикладу
}


// ПРАВИЛО 3: Уникай змішаних масивів
// -----------------------------------------------------
// ❌ Неправильно:
const dataMixed = [1, 2, "3", 4, null, 6];

// ✅ Правильно:
const numbersOnly = [1, 2, 3, 4, 5, 6];
const stringsOnly = ["1", "2", "3"];


// ПРАВИЛО 4: Default-параметри замість "необов'язкових" типів
// -----------------------------------------------------
// ❌ Неправильно: multiplier може бути number або undefined
function calculateBad(a, b, multiplier) {
  const m = multiplier || 1;
  return (a + b) * m;
}
calculateBad(1, 2);    // multiplier = undefined
calculateBad(1, 2, 3); // multiplier = number

// ✅ Правильно: default-параметр → ЗАВЖДИ number
function calculate(a, b, multiplier = 1) {
  return (a + b) * multiplier;
}


// ПРАВИЛО 5: Уникай зміни типу елементів масиву
// -----------------------------------------------------
// ❌ Неправильно:
const arrDegrade = [1, 2, 3]; // PACKED_SMI_ELEMENTS
arrDegrade.push(3.14);         // деградує до PACKED_DOUBLE_ELEMENTS

// ✅ Правильно: визнач тип від початку
const arrStableFromStart = [1.0, 2.0, 3.0]; // одразу PACKED_DOUBLE_ELEMENTS
arrStableFromStart.push(3.14);               // залишається PACKED_DOUBLE_ELEMENTS


// ПРАВИЛО 6: TypeScript допомагає, але НЕ ГАРАНТУЄ (для довідки, у цьому
// репозиторії код чистий JS, наводимо для контексту)
// -----------------------------------------------------
// TypeScript перевіряє типи ПРИ КОМПІЛЯЦІЇ:
//   function add(a: number, b: number): number { return a + b; }
// Але в РАНТАЙМІ (наприклад, через `as any` чи зовнішні дані):
//   const result = add(1 as any, "hello" as any);
//   // TypeScript: OK (через any)
//   // V8 в рантаймі: DEOPTIMIZE!
// TypeScript допомагає тим, що ти САМ не пишеш код з різними типами —
// але НЕ захищає від зовнішніх (наприклад, мережевих) даних.


// ==========================================================================
// ВПЛИВ НА ПРОДУКТИВНІСТЬ — БЕНЧМАРК
// ==========================================================================

const { performance } = require("perf_hooks");

function stableAdd(a, b) {
  return a + b;
}
function unstableAdd(a, b) {
  return a + b;
}

// "Забрудни" unstableAdd різними типами:
unstableAdd(1, 2);
unstableAdd(1.5, 2.5);
unstableAdd("a", "b");

let t0 = performance.now();
for (let i = 0; i < 100000000; i++) stableAdd(i, i + 1);
console.log(`Stable:   ${(performance.now() - t0).toFixed(0)}ms`);

t0 = performance.now();
for (let i = 0; i < 100000000; i++) unstableAdd(i, i + 1);
console.log(`Unstable: ${(performance.now() - t0).toFixed(0)}ms`);

// Орієнтовний результат:
//   Stable:   ~120ms  (monomorphic, 2 ASM інструкції)
//   Unstable: ~600ms  (megamorphic, 50+ ASM інструкцій)
//   Різниця: 5x


