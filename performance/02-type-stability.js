// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// | Стан функції           | Час (100M викликів) | ASM інструкцій | Причина                      |
// |--------------------------|----------------------|------------------|-------------------------------|
// | Monomorphic (SMI)        | ~120ms               | 2                | прямий машинний код           |
// | Monomorphic (Double)     | ~180ms               | 4                | float-операції                |
// | Polymorphic (2 типи)     | ~300ms               | 20+              | перевірка типу + 2 шляхи      |
// | Megamorphic (5+ типів)   | ~600ms               | 50-100           | runtime lookup                |
// | Після Deoptimization     | ~1200ms+             | N/A              | інтерпретація                 |
//
// - V8 проходить 3 рівні компіляції (Ignition → Sparkplug → TurboFan),
//   і TurboFan компілює код ПІД КОНКРЕТНІ спостережені типи
// - навіть у межах "number" є SMI / HeapNumber(Double) / BigInt —
//   з РІЗНОЮ швидкістю обробки
// - monomorphic (1 тип) → polymorphic (2-4 типи) → megamorphic (5+ типів) —
//   кожен рівень значно повільніший за попередній
// - деоптимізація (guard не пройшов) відкидає оптимізований код і
//   повертає функцію до повільної інтерпретації
// - тип масиву може ТІЛЬКИ деградувати (SMI → Double → Mixed), назад — ніколи
//
// КЛЮЧОВИЙ ПРИНЦИП: функція повинна ЗАВЖДИ отримувати ОДИН і той самий
// тип даних. Якщо це неможливо — явно конвертуй тип на вході, щоб
// внутрішня логіка функції працювала з одним типом.