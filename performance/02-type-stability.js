// ==========================================================================
// TYPE STABILITY & MONOMORPHISM — V8 OPTIMIZATION
// ==========================================================================

// 0. ЗАГАЛЬНА ІДЕЯ
// -----------------------------------------------------
// V8 компілює функції СПЕЦІАЛЬНО ПІД ТИПИ ДАНИХ, які вона отримує. Якщо
// функція ЗАВЖДИ отримує числа — генерується швидкий код для чисел.
// Якщо типи ЗМІНЮЮТЬСЯ — V8 деоптимізує код і повертається до повільної
// інтерпретації.
//
// Основне правило: функція повинна обробляти ОДИН тип даних. Якщо типи
// різні — розділи на окремі функції або переконайся, що тип завжди
// однаковий (явно конвертуй на вході).
//
// Розуміння Type Stability дає 3-5x приросту продуктивності для
// гарячих функцій.


// ==========================================================================
// 1. ТРИ СТАДІЇ КОМПІЛЯЦІЇ V8
// ==========================================================================

// V8 НЕ компілює код одразу. Він СПОСТЕРІГАЄ, потім оптимізує:
//
//   РІВЕНЬ 1: Інтерпретатор (Ignition)
//     - виконує код напряму, без компіляції
//     - повільно, але одразу готовий
//     - збирає інформацію про типи
//   ↓ (якщо функція викликається часто)
//   РІВЕНЬ 2: Baseline Compiler (Sparkplug)
//     - компілює в машинний код
//     - швидко, але без глибоких оптимізацій
//   ↓ (якщо функція викликається ДУЖЕ часто)
//   РІВЕНЬ 3: Optimizing Compiler (TurboFan)
//     - компілює з МАКСИМАЛЬНИМИ оптимізаціями під конкретні типи
//     - найшвидший можливий код
//
// КЛЮЧОВИЙ МОМЕНТ: TurboFan генерує код ПІД КОНКРЕТНІ ТИПИ, які він
// спостерігав. Якщо тип зміниться — код стає невалідним (деоптимізація).


// ==========================================================================
// 2. ЩО ВІДБУВАЄТЬСЯ НА МАШИННОМУ РІВНІ
// ==========================================================================

function add(a, b) {
  return a + b;
}

// ЯКЩО V8 БАЧИТЬ ТІЛЬКИ ЧИСЛА (Type Stable):
//
//   ; ARM64 Assembly (TurboFan), a в x0, b в x1
//   add x0, x0, x1   ; просте додавання
//   ret
//   ; 2 інструкції, 1 такт процесора

// ЯКЩО V8 НЕ ЗНАЄ ТИП (Type Unstable):
//
//   ldr x2, [x0]              ; завантаж тип a
//   cmp x2, #SMI_TAG          ; чи це ціле число?
//   bne .check_heap_number    ; якщо ні, перевір float
//   bne .check_string         ; якщо ні, перевір string
//   bne .generic_add          ; загальний шлях
//   .smi_add:
//   add x0, x0, x1
//   ret
//   .check_heap_number: ; ... ще 20+ інструкцій
//   .check_string:      ; ... ще 30+ інструкцій
//   .generic_add:       ; ... ще 50+ інструкцій, виклик runtime функції
//
// РІЗНИЦЯ: 2 інструкції vs 50-100 = 25-50x повільніше!


// ==========================================================================
// 3. ТИПИ ВСЕРЕДИНІ V8 (навіть JS-"number" — це кілька різних представлень)
// ==========================================================================

// JavaScript має тип "number", але V8 розрізняє БІЛЬШЕ варіантів:
//
//   SMI (Small Integer)
//     - цілі числа від -2^31 до 2^31-1
//     - приклад: 1, 42, -100, 0
//     - зберігається ПРЯМО в pointer (без алокації на heap!)
//     - НАЙШВИДШИЙ варіант
//
//   HeapNumber (Double)
//     - числа з плаваючою крапкою
//     - приклад: 3.14, 1.5, -0.001
//     - зберігається на Heap (повільніше)
//
//   BigInt
//     - дуже великі числа
//     - приклад: 9007199254740993n
//     - НАЙПОВІЛЬНІШИЙ варіант для арифметики
//
// Навіть УСЕРЕДИНІ "number" є різниця:

add(1, 2);     // SMI + SMI       → найшвидший шлях
add(1.5, 2.5); // Double + Double → інший шлях
add(1, 2.5);   // SMI + Double    → мусить конвертувати


// ==========================================================================
// 4. MONOMORPHIC, POLYMORPHIC, MEGAMORPHIC — ТРИ РІВНІ СТАБІЛЬНОСТІ ТИПУ
// ==========================================================================

function processValue(value) {
  return value * 2;
}

// MONOMORPHIC (один тип) — ІДЕАЛЬНО:
processValue(1);    // SMI
processValue(2);    // SMI
processValue(100);  // SMI
// V8: "Завжди SMI! Компілюю super-fast code!" — ~120ms для 100M викликів

// POLYMORPHIC (2-4 типи) — ГІРШЕ:
processValue(1);    // SMI
processValue(1.5);  // HeapNumber
processValue(2);    // SMI
// V8: "Бачив 2 різних типи, генерую код для обох" — ~300ms для 100M
// викликів (2.5x повільніше)

// MEGAMORPHIC (5+ типів) — ДУЖЕ ПОГАНО:
processValue(1);        // SMI
processValue(1.5);      // HeapNumber
processValue("hello");  // String
processValue(true);     // Boolean
processValue({});       // Object
// V8: "Не маю уявлення, що прийде — відключаю оптимізації" — ~600ms
// для 100M викликів (5x повільніше)


// ==========================================================================
// 5. SPECULATIVE OPTIMIZATION ТА DEOPTIMIZATION
// ==========================================================================

// V8 робить "ставку" на тип на основі спостережень:

function multiply(a, b) {
  return a * b;
}

// Розігрів: V8 спостерігає
for (let i = 0; i < 100000; i++) {
  multiply(i, 2); // завжди SMI
}
// TurboFan: "Завжди числа! Компілюю оптимізований код." Код містить
// GUARD (захист):
//   GUARD: чи a — число? якщо ні → DEOPTIMIZE
//   GUARD: чи b — число? якщо ні → DEOPTIMIZE
//   result = a * b  (машинна інструкція)

// multiply("hello", 2); // ❌ GUARD не пройшов!
// Що робить V8 при деоптимізації:
//   1) зупини виконання оптимізованого коду
//   2) відтвори стан стека
//   3) продовж в інтерпретаторі (30x повільніше!)
//   4) збирай нову інформацію про типи
//   5) спробуй скомпілювати знову (тепер для двох типів)
// Деоптимізація займає ~0.5-1ms. Якщо відбувається часто — катастрофа
// для продуктивності.

// ЯК ПОБАЧИТИ ДЕОПТИМІЗАЦІЮ:
//   node --trace-deopt myfile.js
// Виведе:
//   [deoptimizing (DEOPT eager)]: begin 0x... multiply
//   translating frame multiply => node=3, height=24


