                                        // для будь-якого нечислового "сміття" — уникай глобального isNaN()


// ==========================================================================
// 14. ПОРІВНЯННЯ ЧЕРЕЗ < > <= >= — ТЕЖ ЧЕРЕЗ ToPrimitive, АЛЕ БЕЗ NaN-ВИНЯТКІВ
// ==========================================================================

// Оператори відношення (не тільки == !=) також запускають ToPrimitive
// (з hint "number") для операндів-об'єктів — і ТЕЖ можуть давати
// несподіваний результат для рядків (лексикографічне порівняння).

console.log("10" < "9");    // true — ОБИДВА рядки → порівнюються ПОСИМВОЛЬНО ("1" < "9")
console.log(10 < 9);        // false — числа порівнюються нормально
console.log("10" < 9);      // false — один операнд число → ОБИДВА приводяться до чисел: 10 < 9
console.log([10] < [9]);    // true — [10] → "10", [9] → "9" → рядкове порівняння знову
console.log(null < 1);      // true — null → 0 (для реляційних операторів, на відміну від ==!)
console.log(null == 0);     // false — а ось тут null == 0 усе одно false (спеціальний виняток з пункту 9)
// ^ ЦЕ ВАЖЛИВА АСИМЕТРІЯ: null поводиться ІНАКШЕ в == порівняно з < > —
// у == null винятково дорівнює лише undefined, а в < > null ПРИВОДИТЬСЯ до 0


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - ToPrimitive(input, hint) — алгоритм приведення об'єкта до примітиву,
//   hint визначає порядок спроб: "string" → toString() спершу,
//   "number"/"default" → valueOf() спершу
// - Symbol.toPrimitive повністю перехоплює й замінює цей алгоритм,
//   якщо об'єкт його реалізує
// - falsy-значень РІВНО СІМ: false, 0, -0, 0n, "", null, undefined, NaN —
//   УСЕ ІНШЕ truthy, включно з [] і {}
// - + — єдиний арифметичний оператор із "гілкою поведінки" (конкатенація
//   vs додавання); - * / % ** ЗАВЖДИ приводять до чисел
// - === нічого не приводить; == приводить типи за алгоритмом Abstract
//   Equality Comparison — саме звідти й усі "дивні" результати ([] == false)
// - null == undefined → true, і це ЄДИНИЙ виняток — обидва не дорівнюють
//   нічому іншому через ==; але через < > null ВСЕ Ж приводиться до 0
// - три рівні рівності: == (з coercion) → === (без coercion, але NaN!==NaN,
//   +0===−0) → Object.is() (SameValue: NaN дорівнює NaN, +0 не дорівнює −0)
// - Number.isNaN() — надійна перевірка на NaN; глобальний isNaN() спершу
//   приводить аргумент до числа і тому ненадійний
// - рекомендація індустрії: завжди === (і eqeqeq у лінтерах), єдиний
//   узвичаєний виняток — ідіома `x == null` для перевірки null/undefined разом