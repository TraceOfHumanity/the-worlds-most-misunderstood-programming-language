// 12. object.is() ТА SAMEVALUEZERO — ЩЕ ТОЧНІШЕ ПОРІВНЯННЯ, НІЖ ===
// ==========================================================================

// Детально розглянуто в common/data-structures/Object/Object.js —
// тут коротко, у контексті "спектру" алгоритмів рівності в JS.
// Є ТРИ РІЗНІ алгоритми рівності в специфікації, від "найслабшого"
// до "найсуворішого":
//
//   ==   (Abstract Equality)      — приводить типи
//   ===  (Strict Equality)        — не приводить типи, АЛЕ NaN !== NaN, +0 === -0
//   Object.is() (SameValue)       — не приводить типи, І NaN дорівнює NaN, І +0 !== -0

console.log(NaN === NaN);       // false
console.log(Object.is(NaN, NaN)); // true
console.log(0 === -0);           // true
console.log(Object.is(0, -0));   // false
// Set/Map використовують ЩЕ ОДИН, четвертий варіант — SameValueZero
// (як Object.is(), АЛЕ +0 і -0 там усе-таки вважаються однаковими) —
// детально в common/data-structures/Map/Map.js та Set/Set.js


