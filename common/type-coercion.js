console.log("абв" - 1);     // NaN — "абв" неможливо привести до числа


// ==========================================================================
// 9. == (LOOSE EQUALITY) VS === (STRICT EQUALITY) — ГОЛОВНА ВІДМІННІСТЬ
// ==========================================================================

// === НЕ виконує ЖОДНОГО приведення типів: якщо типи РІЗНІ — одразу false.
// == СПЕРШУ приводить типи (за особливим алгоритмом Abstract Equality
// Comparison), і ЛИШЕ ПОТІМ порівнює.

console.log(1 === "1");    // false — різні типи, === не приводить нічого
console.log(1 == "1");     // true — "1" приведено до числа 1, потім 1 === 1

console.log(null === undefined); // false — === бачить різні типи
console.log(null == undefined);  // true — СПЕЦІАЛЬНИЙ виняток в алгоритмі: null == undefined,
                                   // але ОБИДВА НЕ дорівнюють нічому ІНШОМУ (навіть 0, "", false)
console.log(null == 0);           // false
console.log(undefined == 0);      // false


// 10. АЛГОРИТМ АБСТРАКТНОГО ПОРІВНЯННЯ (== ) — ПО КРОКАХ
// -----------------------------------------------------
// Спрощено (ключові правила, у порядку перевірки):
//   1. Якщо типи ОДНАКОВІ — == працює точно як === (без жодних сюрпризів)
//   2. null == undefined → true (і ЛИШЕ одне з одним чи із собою)
//   3. number == string → рядок приводиться до числа, потім порівняння чисел
//   4. boolean == будь-що → boolean СПЕРШУ приводиться до числа (true→1, false→0)
//   5. object == (number | string) → об'єкт приводиться до примітиву
//      через ToPrimitive (той самий алгоритм із пункту 2 вище!), потім
//      порівнюється результат
//   6. NaN нічому НЕ дорівнює, навіть самому собі (детально в пункті 13)

console.log(true == 1);        // true — true → 1
console.log(true == "1");      // true — true → 1, "1" → 1
console.log(false == "");      // true — false → 0, "" → 0
console.log(false == "0");     // true — false → 0, "0" → 0
console.log([] == false);      // true — [] → ToPrimitive → "" → 0; false → 0
console.log([] == "");         // true — [] → "" (через toString/join)
console.log([] == 0);          // true — [] → "" → 0
console.log([1] == 1);         // true — [1] → "1" → 1
console.log([1, 2] == "1,2");  // true — [1,2] → toString() → "1,2"

// НАЙСУМНОЗВІСНІШИЙ ПРИКЛАД "ДИВНОСТІ" == :
console.log([] == ![]);        // true — ![] спершу стає false (масив truthy → ! інвертує в false),
                                 // потім [] == false → як вище → true. Класична "пастка на співбесіді"


// 11. ЧОМУ РЕКОМЕНДУЮТЬ ЗАВЖДИ ВИКОРИСТОВУВАТИ ===
// -----------------------------------------------------
// === повністю ПЕРЕДБАЧУВАНИЙ: результат залежить ЛИШЕ від типу
// й значення, ніяких прихованих кроків ToPrimitive. Практично усі
// сучасні style guide (Airbnb, Google тощо) і лінтери (ESLint eqeqeq)
// вимагають === всюди, окрім ОДНОГО узвичаєного винятку:

console.log(someValue == null); // ІДІОМА: перевіряє ОДНОЧАСНО і null, і undefined
// еквівалент: someValue === null || someValue === undefined
function someValue() {} // (заглушка, щоб приклад вище не падав у консолі)


