// + — ЄДИНИЙ оператор, що working ІНАКШЕ залежно від типів операндів:
// ЯКЩО хоча б один операнд (ПІСЛЯ ToPrimitive) — рядок → КОНКАТЕНАЦІЯ.
// В ІНШОМУ ВИПАДКУ → числове додавання.
// Усі інші арифметичні оператори (- * / % **) ЗАВЖДИ приводять ОБИДВА
