// Є ЯВНЕ приведення (ти сам пишеш String(x), Number(x)) і НЕЯВНЕ
// (рушій робить це "за кадром" — саме воно й породжує плутанину).

console.log(Number("42"));   // 42 — ЯВНЕ приведення
console.log("42" * 1);       // 42 — НЕЯВНЕ приведення (рушій сам перетворив "42" на число)
console.log(String(42));     // "42" — ЯВНЕ
console.log(42 + "");        // "42" — НЕЯВНЕ


