// 2. ТРИ "ПІДКАЗКИ" (HINTS) АЛГОРИТМУ ToPrimitive
// ==========================================================================

// Коли рушію потрібно перетворити ОБ'ЄКТ на примітив (для арифметики,
// конкатенації, порівняння), він викликає внутрішній абстрактний
// алгоритм ToPrimitive(input, hint). hint підказує, У ЯКОМУ КОНТЕКСТІ
// відбувається приведення, і саме hint визначає ПОРЯДОК спроб:
//
//   hint "number" (арифметика, <, >, -, *, /):
//     1) якщо є Symbol.toPrimitive — викликати його з hint "number"
//     2) інакше спробувати valueOf() — якщо повернув примітив, взяти його
//     3) інакше спробувати toString() — взяти його результат
//
//   hint "string" (шаблонні рядки, String(x), конкатенація зі знанням про рядок):
//     1) якщо є Symbol.toPrimitive — викликати його з hint "string"
//     2) інакше спробувати toString() ПЕРШИМ
//     3) інакше spробувати valueOf()
//
//   hint "default" (оператор + без явного контексту, ==, якщо жоден з
//   операндів не рядок і не число):
//     1) якщо є Symbol.toPrimitive — викликати його з hint "default"
//     2) інакше — ТА САМА послідовність, що й у "number": valueOf() → toString()

const customObj = {
  valueOf() {
    console.log("викликано valueOf()");
    return 10;
  },
  toString() {
    console.log("викликано toString()");
    return "рядкове представлення";
  },
};

console.log(customObj * 2);        // hint "number" → valueOf() спрацював → 20
console.log(`${customObj}`);       // hint "string" → toString() спрацював → "рядкове представлення"
console.log(customObj + "");       // hint "default" → valueOf() спрацював першим → "10"


// 3. Symbol.toPrimitive — ПОВНИЙ КОНТРОЛЬ НАД АЛГОРИТМОМ (найвищий пріоритет)
// -----------------------------------------------------
// Якщо об'єкт реалізує [Symbol.toPrimitive](hint), він ПЕРЕХОПЛЮЄ
// ВСІ три сценарії — valueOf()/toString() узагалі НЕ РОЗГЛЯДАЮТЬСЯ.
// (Детально розглянуто в common/data-structures/Symbol/Symbol.js —
// тут фокус саме на тому, ЯК це вписується в загальний алгоритм.)

class Money {
  constructor(amount) {
    this.amount = amount;
  }
  [Symbol.toPrimitive](hint) {
    if (hint === "number") return this.amount;
    if (hint === "string") return `${this.amount} грн`;
    return `Money(${this.amount})`; // hint === "default"
  }
}
const price = new Money(100);
console.log(+price);           // 100 — hint "number"
console.log(`${price}`);        // "100 грн" — hint "string"
console.log(price + "");        // "Money(100)" — hint "default"


// 4. ЩО ВІДБУВАЄТЬСЯ З МАСИВАМИ Й ОБ'ЄКТАМИ ПРИ ToPrimitive
// -----------------------------------------------------
// Array.prototype.valueOf() повертає САМ МАСИВ (об'єкт, а не примітив) —
// тому алгоритм ІГНОРУЄ цей результат і йде далі до toString(),
// який для масиву — це join(","):

console.log([1, 2, 3] + "");     // "1,2,3" — через toString() → join(",")
console.log([1, 2, 3] * 2);      // NaN — "1,2,3" (рядок) неможливо перетворити на число

console.log([] + []);            // "" — обидва toString() дають "", разом — ""
console.log([] + {});            // "[object Object]" — "" + звичайний Object.prototype.toString()
console.log({} + []);            // залежить від контексту: у виразі-операторі {} може
                                   // трактуватись як БЛОК КОДУ, а не об'єкт-літерал!

// Object.prototype.valueOf() за замовчуванням теж повертає САМ ОБ'ЄКТ
// (не примітив) — тому для звичайного {} алгоритм теж "падає" до toString():
console.log({} + "");            // "[object Object]"
console.log(String({}));         // "[object Object]"


