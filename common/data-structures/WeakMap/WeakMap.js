// ==========================================================================
// WEAKMAP — КОЛЕКЦІЯ КЛЮЧ-ЗНАЧЕННЯ ЗІ "СЛАБКИМИ" КЛЮЧАМИ-ОБ'ЄКТАМИ (ES6)
// ==========================================================================

// 1. ЩО ТАКЕ WeakMap І ЧИМ ВІН ВІДРІЗНЯЄТЬСЯ ВІД Map
// -----------------------------------------------------
// WeakMap — це "родич" Map, який зберігає пари ключ-значення, АЛЕ
// з трьома фундаментальними обмеженнями, що роблять його спеціальним
// інструментом, а не просто "полегшеною версією" Map:
//   1) ключами можуть бути ЛИШЕ ОБ'ЄКТИ (і, з ES2023, реєстровані
//      symbol'и через Symbol.for()) — жодних рядків, чисел, boolean;
//   2) посилання на ключ "СЛАБКЕ" (weak reference) — не заважає
//      збирачу сміття (garbage collector) видалити цей об'єкт;
//   3) WeakMap НЕ ITERABLE — немає keys()/values()/entries()/
//      forEach()/size — вміст неможливо "перелічити".

const weakMap = new WeakMap();
const keyObj1 = { id: 1 };
weakMap.set(keyObj1, "приватні дані для keyObj1");
console.log(weakMap.get(keyObj1)); // "приватні дані для keyObj1"

// weakMap.set("рядок", "значення"); // TypeError: Invalid value used as weak map key


// ==========================================================================
// 2. СТВОРЕННЯ WeakMap
// ==========================================================================

// а) порожній WeakMap
const emptyWeakMap = new WeakMap();

// б) WeakMap одразу з даними — приймає iterable з пар [об'єкт-ключ, значення]
const objKey1 = {};
const objKey2 = {};
const filledWeakMap = new WeakMap([
  [objKey1, "значення 1"],
  [objKey2, "значення 2"],
]);
console.log(filledWeakMap.get(objKey1)); // "значення 1"

// НА ВІДМІНУ ВІД Map, WeakMap НЕ МОЖНА створити "порожнім і подивитись",
// скільки в ньому елементів, чи скопіювати весь вміст — немає жодного
// способу отримати повний список записів (це навмисне обмеження).


// ==========================================================================
// 3. weakMap.set(keyObj, value) — ДОДАВАННЯ / ОНОВЛЕННЯ
// ==========================================================================

const configWeakMap = new WeakMap();
const configOwner = {};
configWeakMap.set(configOwner, { theme: "dark" });
configWeakMap.set(configOwner, { theme: "light" }); // оновлення — той самий ключ
console.log(configWeakMap.get(configOwner)); // { theme: "light" }

// set() ПОВЕРТАЄ САМ WeakMap — можна ланцюжком, як і в Map:
const chainedWeakMap = new WeakMap().set(objKey1, 1).set(objKey2, 2);


// ==========================================================================
// 4. weakMap.get(keyObj) — ОТРИМАННЯ ЗНАЧЕННЯ
// ==========================================================================

console.log(configWeakMap.get(configOwner)); // { theme: "light" }
console.log(configWeakMap.get({}));          // undefined — це ІНШИЙ об'єкт у пам'яті!

// ВАЖЛИВО: пошук у WeakMap відбувається ЗА ПОСИЛАННЯМ на об'єкт,
// а не за "вмістом" — навіть якщо два об'єкти виглядають однаково,
// це РІЗНІ ключі:
const lookAlikeKey1 = { tag: "same shape" };
const lookAlikeKey2 = { tag: "same shape" };
const shapeWeakMap = new WeakMap();
shapeWeakMap.set(lookAlikeKey1, "прив'язано до першого об'єкта");
console.log(shapeWeakMap.get(lookAlikeKey2)); // undefined — не той самий об'єкт


// ==========================================================================
// 5. weakMap.has(keyObj) — ПЕРЕВІРКА НАЯВНОСТІ КЛЮЧА
// ==========================================================================

console.log(configWeakMap.has(configOwner)); // true
console.log(configWeakMap.has({}));           // false — новий об'єкт, ключа нема


// ==========================================================================
// 6. weakMap.delete(keyObj) — ВИДАЛЕННЯ ЗАПИСУ
// ==========================================================================

console.log(configWeakMap.delete(configOwner)); // true — видалено
console.log(configWeakMap.delete({}));            // false — такого ключа й не було
console.log(configWeakMap.has(configOwner));      // false


// ==========================================================================
// 7. ЧОГО В WeakMap НЕМАЄ — І ЧОМУ САМЕ
// ==========================================================================

// НЕМАЄ: size, keys(), values(), entries(), forEach(), for...of,
// clear(). Причина одна й та сама для всіх: об'єкт-ключ може бути
// видалений збирачем сміття В БУДЬ-ЯКИЙ МОМЕНТ, непередбачувано для
// коду. Якби існував спосіб "перелічити" вміст WeakMap, результат
// залежав би від того, КОЛИ саме відпрацював garbage collector —
// а момент його роботи НЕ визначений специфікацією й непередбачуваний.
// Тому будь-яка ітерованість WeakMap суперечила б самій ідеї "слабкості".

