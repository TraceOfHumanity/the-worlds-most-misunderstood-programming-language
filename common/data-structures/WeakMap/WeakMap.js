// 9. ГОЛОВНЕ ЗАСТОСУВАННЯ: "ПРИВАТНІ" ДАНІ БЕЗ ВИТОКУ ПАМ'ЯТІ
// ==========================================================================

// Класичний патерн ДО появи приватних полів класу (#field) —
// зберігати "приватний" стан об'єкта окремо, в WeakMap, ключем до
// якого є сам публічний екземпляр:

const _privateData = new WeakMap();

class BankAccount {
  constructor(owner, initialBalance) {
    this.owner = owner; // публічне поле
    _privateData.set(this, { balance: initialBalance }); // приватне — недоступне ззовні напряму
  }

  deposit(amount) {
    const data = _privateData.get(this);
    data.balance += amount;
    return data.balance;
  }

  getBalance() {
    return _privateData.get(this).balance;
  }
}

const account = new BankAccount("Марія", 1000);
console.log(account.deposit(500));   // 1500
console.log(account.getBalance());   // 1500
console.log(account.balance);        // undefined — ззовні "приватні" дані недоступні
console.log(Object.keys(account));   // ["owner"] — balance взагалі не видно на об'єкті

// коли account стане недосяжним (наприклад, вийде зі scope), і сам
// об'єкт, і його приватні дані в _privateData звільняться разом —
// на відміну від звичайного Map, де запис лишився б "висіти" назавжди,
// поки хтось явно не викличе map.delete()

// СУЧАСНА АЛЬТЕРНАТИВА для приватності — #privateField у класах:
class ModernBankAccount {
  #balance; // справжнє приватне поле, WeakMap для цього більше не обов'язковий
  constructor(initialBalance) {
    this.#balance = initialBalance;
  }
  getBalance() {
    return this.#balance;
  }
}
// WeakMap і сьогодні залишається корисним для метаданих про об'єкти,
// якими розробник НЕ керує напряму (наприклад, DOM-елементи в браузері)


