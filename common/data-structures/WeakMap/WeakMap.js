// ==========================================================================
// 12. WeakMap vs Map — КОЛИ ЩО ОБИРАТИ
// ==========================================================================

// | Критерій                    | Map                          | WeakMap                        |
// |-------------------------------|-------------------------------|----------------------------------|
// | Тип ключа                    | будь-який                    | лише об'єкти (+ реєстровані symbol) |
// | Керування пам'яттю            | ручне (map.delete()/clear()) | автоматичне (garbage collection) |
// | Ітерованість                  | так (keys/values/entries/forEach) | НІ — жодного способу перелічити |
// | size                          | є                             | немає                            |
// | Типове застосування            | звичайні колекції даних      | приватні/додаткові метадані для об'єктів,
// |                                |                                | кеш "прив'язаний" до об'єкта      |

// Правило вибору: якщо потрібно ЗБЕРІГАТИ дані, ПОКИ ІСНУЄ пов'язаний
// з ними об'єкт, і не думати про ручне очищення — WeakMap. Якщо
// потрібна повноцінна, передбачувана колекція з ітерацією — Map.


// ПІДСУМОК:
// - WeakMap: пари ключ-значення, де КЛЮЧ — обов'язково об'єкт,
//   а посилання на нього "слабке" (не заважає garbage collection)
// - методи: set()/get()/has()/delete() — той самий інтерфейс, що в Map
// - НЕМАЄ size, keys/values/entries/forEach, НЕ ітерований — навмисно,
//   бо вміст може непередбачувано зникати через збирач сміття
// - пошук за ключем — за ПОСИЛАННЯМ, а не за вмістом об'єкта
// - коли об'єкт-ключ стає недосяжним, garbage collector автоматично
//   звільняє і сам об'єкт, і відповідний запис у WeakMap
// - головні застосування: приватні дані об'єктів (до появи #field),
//   кешування "прив'язане" до об'єкта, метадані для DOM-елементів
// - вибирай WeakMap замість Map, коли потрібна автоматична "прибирання
//   за собою" пам'яті, а не звичайна, ітерована колекція