// 10. ЗАСТОСУВАННЯ: КЕШУВАННЯ РЕЗУЛЬТАТІВ ДЛЯ ОБ'ЄКТІВ
// ==========================================================================

// WeakMap ідеально підходить для кешу "результат обчислення для
// конкретного об'єкта" — коли об'єкт видаляється, кеш для нього
// звільняється сам, без ручного очищення й без ризику витоку пам'яті.

const computationCache = new WeakMap();

function expensiveComputation(dataObj) {
  if (computationCache.has(dataObj)) {
    console.log("з кешу");
    return computationCache.get(dataObj);
  }
  console.log("обчислюємо заново...");
  const result = dataObj.values.reduce((sum, n) => sum + n, 0); // умовно "дорога" операція
  computationCache.set(dataObj, result);
  return result;
}

const dataset = { values: [1, 2, 3, 4, 5] };
console.log(expensiveComputation(dataset)); // "обчислюємо заново..." → 15
console.log(expensiveComputation(dataset)); // "з кешу" → 15


