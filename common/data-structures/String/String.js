// ПІДСУМОК:
// - String — примітивний, ІМУТАБЕЛЬНИЙ тип; методи повертають НОВИЙ
//   рядок, оригінал завжди залишається незмінним
// - НІКОЛИ не використовуй new String() — це об'єкт-обгортка,
//   що поводиться інакше, ніж примітив, і ламає === порівняння
// - length рахує UTF-16 code units, а НЕ "видимі символи" — емодзі
//   та подібні символи можуть зайняти length === 2 при одному символі
// - для коректної роботи з Unicode: [...str] / for...of (посимвольно
//   правильно), codePointAt()/fromCodePoint() (замість charCodeAt/fromCharCode),
//   normalize() (для порівняння еквівалентних форм запису)
// - slice() — сучасний вибір для вирізання підрядка (на відміну від
//   застарілих substring()/substr())
// - replace() потребує /g для заміни ВСІХ входжень, replaceAll() —
//   замінює всі за замовчуванням (і не потребує /g для рядків)
// - для локалізованого сортування використовуй localeCompare(),
//   а не < >, які порівнюють посимвольно за кодами
// - рядки ітеровані напряму (for...of/spread), і саме так найкраще
//   Unicode-безпечно розвертати/перебирати текст
// - "" — falsy, будь-який непорожній рядок (навіть " ") — truthy