// ==========================================================================
// UNDERSTANDING FILE SYSTEM — ЧИТАННЯ ТА ЗАПИС ФАЙЛІВ ДЕТАЛЬНО
// ==========================================================================

// (Приклади нижче використовують fs/promises — рекомендований стиль
// для нового коду, детально порівняння стилів — 01-overview.js)

const fs = require("fs/promises");
const os = require("os");
const path = require("path");
const demoFilePath = path.join(os.tmpdir(), "fs-read-write-demo.txt");

async function main() {
  // ========================================================================
  // 1. writeFile() — СТВОРИТИ АБО ПОВНІСТЮ ПЕРЕЗАПИСАТИ ФАЙЛ
  // ========================================================================

  // ЯКЩО ФАЙЛУ НЕМАЄ — writeFile() СТВОРЮЄ ЙОГО. ЯКЩО ФАЙЛ ВЖЕ Є —
  // ЙОГО ВМІСТ ПОВНІСТЮ ЗАМІНЮЄТЬСЯ (НЕ дописується!) НОВИМ вмістом:

  await fs.writeFile(demoFilePath, "Перший рядок");
  console.log(await fs.readFile(demoFilePath, "utf-8")); // "Перший рядок"

  await fs.writeFile(demoFilePath, "Зовсім інший вміст");
  console.log(await fs.readFile(demoFilePath, "utf-8")); // "Зовсім інший вміст" —
                                                             // "Перший рядок" ЗНИК ПОВНІСТЮ!


  // ========================================================================
  // 2. readFile() — З ENCODING І БЕЗ: РЯДОК ЧИ BUFFER
  // ========================================================================

  // БЕЗ АРГУМЕНТУ encoding readFile() ПОВЕРТАЄ Buffer (сирі байти,
  // детально Buffer — node/buffers/index.js), А НЕ рядок:

  const rawBuffer = await fs.readFile(demoFilePath);
  console.log(Buffer.isBuffer(rawBuffer)); // true
  console.log(rawBuffer);                    // <Buffer 32 be 2f ...> — байти, НЕ текст

  // З АРГУМЕНТОМ "utf-8" (чи іншим кодуванням) — ПОВЕРТАЄ РЯДОК:
  const textContent = await fs.readFile(demoFilePath, "utf-8");
  console.log(typeof textContent); // "string"
  console.log(textContent);          // "Зовсім інший вміст"

  // ЦЕ ВАЖЛИВО ДЛЯ БІНАРНИХ ФАЙЛІВ (картинки, PDF тощо) — ЯКЩО
  // ВКАЗАТИ "utf-8" ДЛЯ ФАЙЛУ, ЩО НЕ Є ТЕКСТОМ, ОТРИМАЄШ
  // ПОШКОДЖЕНИЙ/НЕЧИТАБЕЛЬНИЙ "РЯДОК" — ДЛЯ БІНАРНИХ ДАНИХ ЗАВЖДИ
  // ЧИТАЙ БЕЗ encoding (як Buffer) І ОБРОБЛЯЙ ЯК БАЙТИ.


  // ========================================================================
  // 3. appendFile() — ДОДАТИ В КІНЕЦЬ, НЕ ЗАМІНЮЮЧИ ІСНУЮЧИЙ ВМІСТ
  // ========================================================================

  await fs.writeFile(demoFilePath, "Рядок 1\n"); // спочатку "з нуля"
  await fs.appendFile(demoFilePath, "Рядок 2\n"); // ДОДАЄ, НЕ стираючи "Рядок 1"
  await fs.appendFile(demoFilePath, "Рядок 3\n");
  console.log(await fs.readFile(demoFilePath, "utf-8"));
  // Рядок 1
  // Рядок 2
  // Рядок 3


  // ========================================================================
  // 4. РІЗНИЦЯ МІЖ writeFile() ТА appendFile() — КЛАСИЧНА ПЛУТАНИНА
  // ========================================================================

  // writeFile() ЗА ЗАМОВЧУВАННЯМ ВІДКРИВАЄ ФАЙЛ ІЗ ПРАПОРЦЕМ "w"
  // (write, ОБРІЗАЄ ІСНУЮЧИЙ ВМІСТ ДО НУЛЯ ПЕРЕД ЗАПИСОМ), А
  // appendFile() — З ПРАПОРЦЕМ "a" (append, ЗАВЖДИ ПИШЕ В КІНЕЦЬ,
  // НЕ ЧІПАЮЧИ НАЯВНЕ). ДЕТАЛЬНО ПОВНИЙ СПИСОК ПРАПОРЦІВ (r/w/a/r+/
  // w+/a+/wx/ax тощо) — 03-file-handles.js.

  // ❌ ЧАСТА ПОМИЛКА: очікувати, що ПОВТОРНИЙ writeFile() "ДОПИШЕ" —
  // НАСПРАВДІ ВІН ЗНИЩИТЬ УСЕ, ЩО БУЛО РАНІШЕ:
  await fs.writeFile(demoFilePath, "тільки цей рядок");
  console.log(await fs.readFile(demoFilePath, "utf-8")); // "тільки цей рядок" —
                                                             // "Рядок 1/2/3" ЗНИКЛИ БЕЗСЛІДНО


  // ========================================================================
  // 5. ВЕЛИКІ ФАЙЛИ: ЧОМУ readFile()/writeFile() НЕ ЗАВЖДИ ПІДХОДЯТЬ
  // ========================================================================

  // readFile() ЗАВАНТАЖУЄ ВЕСЬ ФАЙЛ ЦІЛИКОМ У ПАМ'ЯТЬ — для файлу
  // на кілька ГІГАБАЙТ ЦЕ МОЖЕ ВИЧЕРПАТИ ДОСТУПНУ ПАМ'ЯТЬ ПРОЦЕСУ
  // Node.js ЩЕ ДО ТОГО, ЯК ФАЙЛ ВЗАГАЛІ ВДАСТЬСЯ ОБРОБИТИ. ДЛЯ
  // ВЕЛИКИХ ФАЙЛІВ (чи ФАЙЛІВ НЕВІДОМОГО РОЗМІРУ) ПОТРІБНІ STREAMS —
  // читання ЧАСТИНАМИ (chunks), БЕЗ УТРИМАННЯ ВСЬОГО ФАЙЛУ В ПАМ'ЯТІ
  // ОДНОЧАСНО (детальний, окремий майбутній файл про Streams).


  // ========================================================================
  // 6. ОПЦІЇ writeFile(): flag, mode
  // ========================================================================

  // { flag: "wx" } — СТВОРИТИ файл, ЛИШЕ ЯКЩО ЙОГО ЩЕ НЕ ІСНУЄ
  // (ІНАКШЕ — помилка EEXIST, а НЕ мовчазна перезаписка):
  try {
    await fs.writeFile(demoFilePath, "спроба перезаписати", { flag: "wx" });
  } catch (err) {
    console.log("Очікувана помилка:", err.code); // "EEXIST" — файл ВЖЕ існує
  }

  const freshPath = path.join(os.tmpdir(), "fs-read-write-fresh.txt");
  await fs.rm(freshPath, { force: true }); // прибираємо "хвости" з попередніх запусків
  await fs.writeFile(freshPath, "новий файл", { flag: "wx" }); // ✅ файлу ще не було — ok
  console.log(await fs.readFile(freshPath, "utf-8")); // "новий файл"


  // ========================================================================
  // 7. ЧАСТКОВЕ ЧИТАННЯ/ЗАПИС ЗА ДОПОМОГОЮ ФАЙЛОВОГО ДЕСКРИПТОРА
  // ========================================================================

  // readFile()/writeFile() ЗАВЖДИ ПРАЦЮЮТЬ ІЗ УСІМ ФАЙЛОМ ЦІЛИКОМ.
  // ЯКЩО ПОТРІБНО ПРОЧИТАТИ/ЗАПИСАТИ ЛИШЕ КОНКРЕТНИЙ ШМАТОК (наприклад,
  // ВІДНОВИТИ ПЕРЕРВАНЕ ЗАВАНТАЖЕННЯ, ЧИ ЗМІНИТИ БАЙТИ ПОСЕРЕД
  // ВЕЛИКОГО ФАЙЛУ) — ПОТРІБЕН fs.open() і РОБОТА З FileHandle
  // НАПРЯМУ (ДЕТАЛЬНО — 03-file-handles.js).


  // ========================================================================
  // ПРИБИРАННЯ ЗА СОБОЮ (демонстраційні файли — тимчасові, у os.tmpdir())
  // ========================================================================
  await fs.rm(demoFilePath, { force: true });
  await fs.rm(freshPath, { force: true });
}

main().catch((err) => console.error("Помилка в демонстрації:", err));


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - writeFile() СТВОРЮЄ файл АБО ПОВНІСТЮ ЗАМІНЮЄ його вміст —
//   ПОВТОРНИЙ виклик "стирає" усе, що було раніше
// - appendFile() ЗАВЖДИ ДОПИСУЄ В КІНЕЦЬ, не чіпаючи наявний вміст —
//   ЦЕ ГОЛОВНА, найчастіше плутана різниця з writeFile()
// - readFile() БЕЗ encoding повертає Buffer (сирі байти); З encoding
//   ("utf-8" тощо) — рядок; для БІНАРНИХ файлів (картинки тощо)
//   ЗАВЖДИ читай БЕЗ encoding
// - readFile()/writeFile() ЗАВАНТАЖУЮТЬ ВЕСЬ ФАЙЛ у пам'ять цілком —
//   для ВЕЛИКИХ файлів потрібні Streams (окремий майбутній файл)
// - опція { flag: "wx" } дає БЕЗПЕЧНЕ "створити, лише якщо ще не
//   існує" — замість тихого перезапису
// - для ЧАСТКОВОГО читання/запису (не всього файлу цілком) потрібен
//   fs.open() і FileHandle (детально — 03-file-handles.js)