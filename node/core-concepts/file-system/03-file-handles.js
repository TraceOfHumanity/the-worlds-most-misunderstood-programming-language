// ==========================================================================
// UNDERSTANDING FILE SYSTEM — FILE HANDLES, FLAGS ТА ЧАСТКОВИЙ ДОСТУП
// ==========================================================================

// 1. ЩО ТАКЕ ФАЙЛОВИЙ ДЕСКРИПТОР (file descriptor) І FileHandle
// -----------------------------------------------------
// Коли ОПЕРАЦІЙНА СИСТЕМА ВІДКРИВАЄ файл, ВОНА видає ПРОГРАМІ
// ЧИСЛОВИЙ "ІДЕНТИФІКАТОР" ЦЬОГО ВІДКРИТОГО файлу — ФАЙЛОВИЙ
// ДЕСКРИПТОР (file descriptor, "fd"). УСІ ПОДАЛЬШІ операції
// (читання, запис, закриття) ВІДБУВАЮТЬСЯ ЧЕРЕЗ ЦЕЙ ДЕСКРИПТОР, А
// НЕ через "ім'я файлу" ЗНОВУ — ОС ВЖЕ ЗНАЄ, ПРО ЯКИЙ САМЕ файл
// ЙДЕТЬСЯ, І ДЕ В НЬОМУ ЗАРАЗ "ПОЗИЦІЯ КУРСОРА".
//
// У Node.js (fs/promises) ЦЕЙ ДЕСКРИПТОР "ОБГОРНУТИЙ" В ОБ'ЄКТ
// FileHandle — ЗРУЧНИЙ ІНТЕРФЕЙС ІЗ МЕТОДАМИ read()/write()/close()
// ТОЩО, ЩО ПІД КАПОТОМ ВИКОРИСТОВУЄ ЦЕЙ САМИЙ fd.

const fs = require("fs/promises");
const os = require("os");
const path = require("path");
const demoFilePath = path.join(os.tmpdir(), "fs-filehandle-demo.txt");

async function main() {
  // ========================================================================
  // 2. fs.open() — ОТРИМАТИ FileHandle
  // ========================================================================

  const fileHandle = await fs.open(demoFilePath, "w"); // "w" — детально flags, розділ 4
  console.log(typeof fileHandle.read);  // "function"
  console.log(typeof fileHandle.write); // "function"
  console.log(typeof fileHandle.close); // "function"

  await fileHandle.write("Hello file content"); // ASCII — щоб КОЖЕН символ = РІВНО 1 БАЙТ
                                                    // (для кирилиці/емодзі байти й символи
                                                    // НЕ збігаються 1:1 — детально
                                                    // node/core-concepts/buffers/index.js, розділ 5;
                                                    // "розрізати" такий текст ПОСЕРЕД
                                                    // символу за фіксованою кількістю
                                                    // байтів дало б "биту" UTF-8-послідовність)
  await fileHandle.close(); // ⚠️ ОБОВ'ЯЗКОВО закривати — розділ 5


  // ========================================================================
  // 3. ЧАСТКОВИЙ ЗАПИС/ЧИТАННЯ ЗА КОНКРЕТНОЮ ПОЗИЦІЄЮ (offset)
  // ========================================================================

  // readFile()/writeFile() (детально 02-reading-and-writing-files.js)
  // ЗАВЖДИ ПРАЦЮЮТЬ ІЗ ФАЙЛОМ ЦІЛИКОМ. FileHandle ДОЗВОЛЯЄ ЧИТАТИ/
  // ПИСАТИ РІВНО СТІЛЬКИ БАЙТІВ, СКІЛЬКИ ТРЕБА, ПОЧИНАЮЧИ З
  // КОНКРЕТНОЇ ПОЗИЦІЇ — БЕЗ ТОРКАННЯ РЕШТИ ФАЙЛУ:

  const rwHandle = await fs.open(demoFilePath, "r+"); // "r+" — читання Й запис,
                                                          // файл МАЄ вже існувати
  // читаємо БАЙТИ 0-4 (перших 5 байтів файлу):
  const readBuffer = Buffer.alloc(5);
  await rwHandle.read(readBuffer, 0, 5, 0); // (буфер, offset у буфері, скільки байтів, позиція у файлі)
  console.log(readBuffer.toString("utf-8")); // "Hello" (перші 5 байтів = перші 5 символів ASCII)

  // ПЕРЕЗАПИСУЄМО ЛИШЕ БАЙТИ, ЩО ПОЧИНАЮТЬСЯ З ПОЗИЦІЇ 0, НЕ ЧІПАЮЧИ РЕШТУ:
  await rwHandle.write("REPLACED", 0, "utf-8"); // (дані, позиція у файлі, кодування)
  await rwHandle.close();

  console.log(await fs.readFile(demoFilePath, "utf-8"));
  // "REPLACEDle content" — ЛИШЕ ПЕРШІ 8 БАЙТІВ ("Hello fi" → "REPLACED")
  // ЗМІНИЛИСЯ, РЕШТА ("le content") ЗАЛИШИЛАСЬ ТІЄЮ Ж, ЩО Й БУЛА


  // ========================================================================
  // 4. FILE SYSTEM FLAGS — ПОВНИЙ НАБІР "РЕЖИМІВ" ВІДКРИТТЯ ФАЙЛУ
  // ========================================================================

  //   "r"   — читання; ПОМИЛКА, ЯКЩО файл НЕ існує
  //   "r+"  — читання Й запис; ПОМИЛКА, ЯКЩО файл НЕ існує
  //   "w"   — запис; СТВОРЮЄ файл, ЯКЩО не існує; ОБРІЗАЄ до 0 (стирає!), ЯКЩО існує
  //   "w+"  — читання Й запис; ТЕ САМЕ, ЩО "w" (створює/обрізає)
  //   "a"   — ДОПИС у кінець; СТВОРЮЄ файл, ЯКЩО не існує
  //   "a+"  — читання Й ДОПИС у кінець; створює, ЯКЩО не існує
  //   "wx"  — ЯК "w", АЛЕ ПОМИЛКА (EEXIST), ЯКЩО файл ВЖЕ існує (детально
  //           показано в 02-reading-and-writing-files.js, розділ 6)
  //   "ax"  — ЯК "a", АЛЕ ТЕЖ ПОМИЛКА, ЯКЩО файл ВЖЕ існує

  const flagsDemoPath = path.join(os.tmpdir(), "fs-flags-demo.txt");
  await fs.rm(flagsDemoPath, { force: true });

  const wHandle = await fs.open(flagsDemoPath, "w");
  await wHandle.close();
  console.log("Файл створено через 'w' flag");

  try {
    await fs.open(flagsDemoPath, "r"); // файл ВЖЕ Є — "r" відкриє БЕЗ помилки
    console.log("'r' відкрив ІСНУЮЧИЙ файл успішно");
  } catch (err) {
    console.log("Несподівана помилка:", err.code);
  }

  await fs.rm(flagsDemoPath, { force: true });
  try {
    await fs.open(flagsDemoPath, "r"); // а ТЕПЕР файлу НЕМАЄ
  } catch (err) {
    console.log("'r' на неіснуючому файлі:", err.code); // "ENOENT"
  }


  // ========================================================================
  // 5. ЧОМУ ОБОВ'ЯЗКОВО ЗАКРИВАТИ FileHandle (close())
  // ========================================================================

  // КОЖЕН ВІДКРИТИЙ ФАЙЛОВИЙ ДЕСКРИПТОР — ЦЕ ОБМЕЖЕНИЙ РЕСУРС
  // ОПЕРАЦІЙНОЇ СИСТЕМИ (у більшості ОС — ЛІМІТ у КІЛЬКА ТИСЯЧ
  // ОДНОЧАСНО ВІДКРИТИХ ДЕСКРИПТОРІВ НА ПРОЦЕС). ЯКЩО НЕ ЗАКРИВАТИ
  // FileHandle ПІСЛЯ ВИКОРИСТАННЯ — ЦЕ КЛАСИЧНИЙ "RESOURCE LEAK"
  // (витік РЕСУРСУ, АНАЛОГІЧНИЙ ВИТОКУ ПАМ'ЯТІ, АЛЕ ДЛЯ ДЕСКРИПТОРІВ,
  // А НЕ ПАМ'ЯТІ) — РАНО ЧИ ПІЗНО ПРОЦЕС ОТРИМАЄ ПОМИЛКУ
  // "EMFILE: too many open files" І НЕ ЗМОЖЕ ВІДКРИТИ ЖОДНОГО НОВОГО
  // файлу/сокета.
  //
  // ✅ НАДІЙНИЙ ПАТЕРН — try/finally, ЩОБ close() ВИКЛИКАВСЯ НАВІТЬ
  // ПРИ ПОМИЛЦІ ВСЕРЕДИНІ try:

  async function safeFileOperation(filePath) {
    const handle = await fs.open(filePath, "r+");
    try {
      const buffer = Buffer.alloc(5);
      await handle.read(buffer, 0, 5, 0);
      return buffer.toString("utf-8");
    } finally {
      await handle.close(); // ГАРАНТОВАНО виконається, НАВІТЬ якщо read() кине помилку
    }
  }
  await fs.writeFile(demoFilePath, "12345");
  console.log(await safeFileOperation(demoFilePath));

  // ✅ АБО — using-декларація (ES2023+/Node.js з підтримкою) чи
  // fs/promises fileHandle[Symbol.asyncDispose] — сучасніший, АЛЕ
  // ПОКИ ЩЕ РІДШЕ ВИКОРИСТОВУВАНИЙ підхід; try/finally — НАДІЙНИЙ
  // ВИБІР, ЯКИЙ ПРАЦЮЄ В БУДЬ-ЯКІЙ ВЕРСІЇ Node.js.


  // ========================================================================
  // 6. stat() ЧЕРЕЗ FileHandle — МЕТАДАНІ ВІДКРИТОГО ФАЙЛУ
  // ========================================================================

  const statHandle = await fs.open(demoFilePath, "r");
  const stats = await statHandle.stat();
  console.log("Розмір файлу (байти):", stats.size);
  console.log("Це файл?", stats.isFile());
  console.log("Це директорія?", stats.isDirectory());
  await statHandle.close();
  // (детально повний набір stat-полів — 04-directories-and-stats.js)


  // ========================================================================
  // ПРИБИРАННЯ
  // ========================================================================
  await fs.rm(demoFilePath, { force: true });
  await fs.rm(flagsDemoPath, { force: true });
}

main().catch((err) => console.error("Помилка в демонстрації:", err));


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - файловий дескриптор (fd) — числовий "ідентифікатор" відкритого
//   файлу від ОС; FileHandle у Node.js — зручна обгортка над ним
// - fs.open(path, flag) повертає FileHandle із методами read()/
//   write()/close()/stat() тощо
// - на відміну від readFile()/writeFile(), FileHandle дозволяє
//   читати/писати РІВНО ПОТРІБНУ КІЛЬКІСТЬ БАЙТІВ, ПОЧИНАЮЧИ З
//   КОНКРЕТНОЇ ПОЗИЦІЇ (offset), НЕ ЧІПАЮЧИ РЕШТУ ФАЙЛУ
// - flags визначають режим доступу: r/r+ (читання, файл МАЄ існувати),
//   w/w+ (запис, СТВОРЮЄ або ОБРІЗАЄ до нуля), a/a+ (дописування,
//   створює за потреби), wx/ax (як w/a, але помилка, якщо файл ВЖЕ є)
// - НЕЗАКРИТИЙ FileHandle — витік файлового дескриптора (обмежений
//   ресурс ОС) — завжди закривай через close(), НАЙНАДІЙНІШЕ —
//   у блоці finally, щоб це відбувалось НАВІТЬ при помилці
// - FileHandle теж має stat() для метаданих (розмір, тип) без
//   потреби відкривати файл ЗАНОВО через шлях