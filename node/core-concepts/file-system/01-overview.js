// ==========================================================================
// UNDERSTANDING FILE SYSTEM — МОДУЛЬ fs: ЗАГАЛЬНИЙ ОГЛЯД
// ==========================================================================

// 1. ЩО ТАКЕ МОДУЛЬ fs
// -----------------------------------------------------
// fs ("file system") — вбудований модуль Node.js для роботи з
// ФАЙЛОВОЮ СИСТЕМОЮ операційної системи: читання/запис файлів,
// створення/видалення директорій, отримання метаданих (розмір, дата
// зміни), спостереження за змінами тощо. Це ОДИН із НАЙСТАРІШИХ і
// НАЙВАЖЛИВІШИХ модулів Node.js — САМЕ МОЖЛИВІСТЬ РОБОТИ З ФАЙЛАМИ
// (чого немає в JS у браузері з міркувань безпеки) — ОДНА З
// ГОЛОВНИХ ПРИЧИН, ЧОМУ Node.js взагалі існує ЯК ОКРЕМЕ середовище
// виконання JS, відмінне від браузера.

const fs = require("fs");
console.log(typeof fs.readFile); // "function" — модуль fs доступний одразу, без npm install


// ==========================================================================
// 2. ТРИ СТИЛІ API: CALLBACK, SYNC, PROMISES — ОДНІ Й ТІ САМІ ОПЕРАЦІЇ
// ==========================================================================

// Модуль fs ІСТОРИЧНО пропонує ОДНУ Й ТУ САМУ операцію в ТРЬОХ
// РІЗНИХ "СТИЛЯХ" виклику — розуміння ЦЬОГО критично важливе, бо
// СПЛУТУВАННЯ стилів — одна з найчастіших причин "дивних" багів
// (детально приклад — розділ 5).

const os = require("os");
const path = require("path");
const demoFilePath = path.join(os.tmpdir(), "fs-overview-demo.txt");

// СТВОРЮЄМО ФАЙЛ ЗАЗДАЛЕГІДЬ (синхронно), ЩОБ ДЕМОНСТРАЦІЇ НИЖЧЕ
// МАЛИ З ЧИМ ПРАЦЮВАТИ — САМЕ ТУТ Sync-виклик ДОРЕЧНИЙ (розділ 2.2):
fs.writeFileSync(demoFilePath, "Початковий вміст");

// 2.1. CALLBACK-СТИЛЬ — НАЙСТАРІШИЙ, ЩЕ ДО async/await У МОВІ
// -----------------------------------------------------
// Кожна функція ПРИЙМАЄ callback ОСТАННІМ аргументом, за конвенцією
// Node.js "error-first" (детально common/asynchronous/asynchronous.js, розділ 3):
// перший параметр callback'а — ПОМИЛКА (або null, якщо все гаразд).

fs.writeFile(demoFilePath, "Привіт, файлова система!", (err) => {
  if (err) {
    console.error("Помилка запису:", err);
    return;
  }
  fs.readFile(demoFilePath, "utf-8", (err, data) => {
    if (err) {
      console.error("Помилка читання:", err);
      return;
    }
    console.log("Callback-стиль прочитав:", data);
  });
});

// 2.2. SYNC-СТИЛЬ — БЛОКУЄ ВЕСЬ ПОТІК ВИКОНАННЯ (event loop) ДО ЗАВЕРШЕННЯ
// -----------------------------------------------------
// Функції з суфіксом "Sync" ВИКОНУЮТЬСЯ СИНХРОННО — код ЗУПИНЯЄТЬСЯ
// на ЦЬОМУ рядку, ПОКИ операція введення/виведення НЕ ЗАВЕРШИТЬСЯ.
// Це ПРЯМО СУПЕРЕЧИТЬ ідеї Node.js "не блокувати event loop"
// (детально сама модель — common/asynchronous/asynchronous.js, розділ 0):

const syncContent = fs.readFileSync(demoFilePath, "utf-8"); // ⚠️ БЛОКУЄ тут усе інше
console.log("Sync-стиль прочитав:", syncContent); // "Початковий вміст" — ЩЕ ДО
                                                     // того, як callback-запис вище
                                                     // РЕАЛЬНО завершиться (він асинхронний!)

// ⚠️ SYNC-МЕТОДИ ПРИЙНЯТНІ ЛИШЕ:
//   - на САМОМУ СТАРТІ застосунку (читання конфігурації ДО того,
//     як сервер почав приймати запити — тут "блокування" не шкодить,
//     бо ОБСЛУГОВУВАТИ запити ще НІКОГО);
//   - у ОДНОРАЗОВИХ CLI-скриптах, де немає ІНШИХ одночасних задач.
// У СЕРВЕРІ, ЩО ОБСЛУГОВУЄ БАГАТО ЗАПИТІВ ОДНОЧАСНО, Sync-метод
// "ЗАМОРОЗИТЬ" ОБРОБКУ ВСІХ ІНШИХ запитів на час операції введення/
// виведення — Node.js ОДНОПОТОКОВИЙ (детально common/asynchronous/asynchronous.js,
// розділ 0), і Sync-виклик БЛОКУЄ ЦЕЙ ЄДИНИЙ потік ПОВНІСТЮ.

// 2.3. PROMISE-СТИЛЬ (fs/promises) — СУЧАСНИЙ, РЕКОМЕНДОВАНИЙ ЗА ЗАМОВЧУВАННЯМ
// -----------------------------------------------------
// Той САМИЙ callback-API, АЛЕ КОЖНА функція ПОВЕРТАЄ Promise —
// ПРИРОДНО ПОЄДНУЄТЬСЯ З async/await (детально common/asynchronous/asynchronous.js,
// розділ "СПОСІБ 3: ASYNC/AWAIT"):

const fsPromises = require("fs/promises"); // або: const fsPromises = require("fs").promises;

async function readWithPromises() {
  await fsPromises.writeFile(demoFilePath, "Оновлений вміст через Promises");
  const content = await fsPromises.readFile(demoFilePath, "utf-8");
  console.log("Promise-стиль прочитав:", content);
}
readWithPromises();


// ==========================================================================
// 3. ЧОМУ Є ВСІ ТРИ СТИЛІ, І ЧОМУ PROMISE-СТИЛЬ — ТИПОВИЙ ВИБІР СЬОГОДНІ
// ==========================================================================

// Callback-стиль З'ЯВИВСЯ ПЕРШИМ (Node.js старший за async/await
// у самій мові на кілька років) — САМЕ ЧЕРЕЗ ЦЕ БАГАТО СТАРОГО коду
// й досі використовує callback'и. Sync-версії ІСНУВАЛИ ЗАВЖДИ ЯК
// "простий шлях" для CLI-скриптів, ДЕ НЕ ВАЖЛИВА конкурентність.
// fs/promises З'ЯВИВСЯ ЗНАЧНО ПІЗНІШЕ (стабілізувався в Node.js 14) —
// ЯК "МІСТОК" МІЖ старим callback-API і сучасним async/await-стилем.
//
// СЬОГОДНІ ДЛЯ НОВОГО КОДУ РЕКОМЕНДУЄТЬСЯ fs/promises + async/await:
// НЕ БЛОКУЄ event loop (на відміну від Sync), І ЧИТАЄТЬСЯ ЛІНІЙНО,
// БЕЗ "ПІРАМІДИ" ВКЛАДЕНИХ callback'ів (детально проблема callback
// hell — common/asynchronous/asynchronous.js, розділ "CALLBACK HELL").


// ==========================================================================
// 4. ФУНКЦІЇ fs АСИНХРОННІ, АЛЕ САМА I/O-ОПЕРАЦІЯ ВІДБУВАЄТЬСЯ НЕ В JS-ПОТОЦІ
// ==========================================================================

// Асинхронні (не-Sync) методи fs НЕ "БЛОКУЮТЬ" JS-потік, БО РЕАЛЬНА
// робота з ДИСКОМ виконується Node.js ЧЕРЕЗ ВНУТРІШНІЙ ПУЛ ПОТОКІВ
// (libuv thread pool) — ОКРЕМИЙ ВІД ГОЛОВНОГО JS-потоку. Коли операція
// на диску ЗАВЕРШУЄТЬСЯ, РЕЗУЛЬТАТ "ПОВЕРТАЄТЬСЯ" в event loop ЯК
// звичайна МАКРОЗАДАЧА (детально мікро/макрозадачі —
// common/asynchronous/asynchronous.js, розділ 15 "EVENT LOOP"), і ВИКОНУЄТЬСЯ
// callback/резолвиться Promise.
//
// САМЕ ТОМУ:
console.log("1: цей рядок виконається ПЕРШИМ");
fs.readFile(demoFilePath, "utf-8", () => {
  console.log("3: а цей — ПІСЛЯ всього синхронного коду й мікрозадач");
});
console.log("2: цей рядок виконається ДРУГИМ, ще ДО завершення читання файлу");


// ==========================================================================
// 5. КЛАСИЧНА ПАСТКА: ЗМІШУВАННЯ СТИЛІВ АБО ЗАБУТИЙ await
// ==========================================================================

// ❌ Забутий await — Promise просто "висить" необробленим, а код
// ПРОДОВЖУЄ виконуватись, НІБИ файл ВЖЕ записаний (хоча це НЕ так):
async function brokenSequence() {
  fsPromises.writeFile(demoFilePath, "новий вміст"); // ЗАБУТО await!
  const content = await fsPromises.readFile(demoFilePath, "utf-8");
  console.log("Могли прочитати СТАРИЙ вміст:", content); // непередбачувано,
                                                             // залежить від того,
                                                             // ЩО швидше завершиться
}

// ✅ Правильно — ЧЕКАЄМО завершення запису ПЕРЕД читанням:
async function correctSequence() {
  await fsPromises.writeFile(demoFilePath, "гарантовано записаний вміст");
  const content = await fsPromises.readFile(demoFilePath, "utf-8");
  console.log("Гарантовано прочитали:", content);
}
correctSequence();


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - fs — вбудований модуль Node.js для роботи з файловою системою;
//   можливість читати/писати файли — одна з причин, чому Node.js
//   узагалі існує окремо від браузерного JS
// - КОЖНА операція fs існує У ТРЬОХ стилях: callback (найстаріший,
//   error-first конвенція), Sync (блокує event loop ПОВНІСТЮ), і
//   Promise-стиль через require("fs/promises") (сучасний, для async/await)
// - Sync-методи прийнятні ЛИШЕ на старті застосунку чи в CLI-скриптах
//   БЕЗ конкурентних задач — у сервері вони "заморожують" ОБРОБКУ
//   УСІХ ІНШИХ запитів, бо Node.js однопотоковий
// - асинхронні методи НЕ блокують JS-потік, бо РЕАЛЬНА робота з
//   диском виконується через внутрішній пул потоків (libuv),
//   результат повертається в event loop як звичайна асинхронна подія
// - fs/promises — рекомендований стиль для НОВОГО коду: НЕ блокує,
//   природно поєднується з async/await, без callback hell
// - класична пастка: забутий await для fs/promises-методу — код
//   продовжує виконуватись, НЕ дочекавшись реального завершення
//   операції з диском