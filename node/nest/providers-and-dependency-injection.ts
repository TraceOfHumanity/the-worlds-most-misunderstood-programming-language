//
//   @Injectable()
//   export class OrdersService {
//     constructor(
//       @Inject(forwardRef(() => UsersService))
//       private readonly usersService: UsersService,
//     ) {}
//   }
//
// АЛЕ: ЦЕ "ЛАТКА", А НЕ РЕКОМЕНДОВАНИЙ ПАТЕРН — ЦИКЛІЧНА ЗАЛЕЖНІСТЬ
// ЗАЗВИЧАЙ СИГНАЛІЗУЄ ПРО НЕВДАЛИЙ ПОДІЛ ВІДПОВІДАЛЬНОСТІ МІЖ
// СЕРВІСАМИ — ЧАСТО КРАЩЕ РІШЕННЯ: ВИНЕСТИ СПІЛЬНУ ЛОГІКУ В ТРЕТІЙ,
// ОКРЕМИЙ СЕРВІС, ВІД ЯКОГО ЗАЛЕЖАТЬ ОБИДВА, ЗАМІСТЬ ТОГО, ЩОБ ВОНИ
// ЗАЛЕЖАЛИ ОДИН ВІД ОДНОГО НАПРЯМУ.


// ==========================================================================
// 13. ПОРІВНЯННЯ: DI-КОНТЕЙНЕР NEST VS РУЧНИЙ "DI" У ЧИСТОМУ JS
// ==========================================================================

// У ЧИСТОМУ JS (БЕЗ ФРЕЙМВОРКА) ТОЙ САМИЙ ПРИНЦИП "НЕ СТВОРЮЙ
// ЗАЛЕЖНІСТЬ САМ, ОТРИМУЙ ЇЇ ЗЗОВНІ" РЕАЛІЗУЮТЬ ВРУЧНУ — ЧЕРЕЗ
// ПАРАМЕТРИ ФУНКЦІЙ/КОНСТРУКТОРІВ (той самий ПРИНЦИП, ЯКИЙ
// ЗУСТРІЧАЄТЬСЯ, НАПРИКЛАД, У ФУНКЦІЯХ ВИЩОГО ПОРЯДКУ, ЩО ПРИЙМАЮТЬ
// callback ЯК АРГУМЕНТ, ЗАМІСТЬ ТОГО, ЩОБ "ЗАШИВАТИ" ЙОГО ВСЕРЕДИНІ —
// common/asynchronous.js):
//
//   // "РУЧНИЙ" DI У ЧИСТОМУ JS — ТИ САМ "ЗБИРАЄШ" ГРАФ:
//   function createUsersService(database) {
//     return {
//       findAll: () => database.query("SELECT * FROM users"),
//     };
//   }
//   function createUsersController(usersService) {
//     return {
//       getAll: () => usersService.findAll(),
//     };
//   }
//   // "ВРУЧНУ" БУДУЄМО ГРАФ, У ПРАВИЛЬНОМУ ПОРЯДКУ, САМІ:
//   const database = createDatabaseConnection();
//   const usersService = createUsersService(database);
//   const usersController = createUsersController(usersService);
//
// NEST РОБИТЬ РІВНО ЦЕ Ж САМЕ, АЛЕ АВТОМАТИЧНО: ЧИТАЄ ТИПИ
// КОНСТРУКТОРІВ (ЧЕРЕЗ МЕТАДАНІ ДЕКОРАТОРІВ) І САМ "ЗБИРАЄ" ЦЕЙ
// ЛАНЦЮЖОК СТВОРЕННЯ, НЕЗАЛЕЖНО ВІД ТОГО, НАСКІЛЬКИ ВІН ВЕЛИКИЙ І
// ЗАПЛУТАНИЙ. ЦЕ І Є ГОЛОВНА "МАГІЯ" DI-КОНТЕЙНЕРА: ВІН ЗВІЛЬНЯЄ ТЕБЕ
// ВІД РУЧНОГО "ЗБИРАННЯ" ДЕСЯТКІВ/СОТЕНЬ ВЗАЄМОПОВ'ЯЗАНИХ КЛАСІВ У
// ВЕЛИКОМУ ЗАСТОСУНКУ.


// ==========================================================================
// ШПАРГАЛКА
// ==========================================================================

// | Конструкція                                  | Навіщо                                                |
// |----------------------------------------------------|-----------------------------------------------------------|
// | @Injectable()                                     | позначає клас як provider, видимий для DI-контейнера    |
// | providers: [X] у @Module()                        | реєструє provider У ЦЬОМУ модулі (скорочена форма)      |
// | { provide, useClass }                              | розгорнута форма — ТОЙ самий сенс, ЯВНО                  |
// | { provide, useValue }                              | ГОТОВЕ значення/об'єкт замість класу (конфіги, моки)     |
// | { provide, useFactory, inject }                    | значення, ОБЧИСЛЕНЕ функцією (МОЖЕ бути асинхронним)     |
// | { provide, useExisting }                            | АЛІАС до вже існуючого provider'а                        |
// | @Inject(token)                                     | явна вказівка ТОКЕНА (обов'язково для interface/string)  |
// | @Optional()                                        | provider, БЕЗ якого МОЖНА обійтись (undefined замість помилки) |
// | Scope.DEFAULT / REQUEST / TRANSIENT                | життєвий цикл provider'а (singleton / на запит / щоразу)|
// | exports: [X] у @Module()                            | робить provider ДОСТУПНИМ ІНШИМ модулям (через imports) |
// | @Global()                                          | provider доступний СКРІЗЬ без повторного imports        |
// | forwardRef()                                       | "обхідний шлях" для циклічних залежностей (уникай, якщо можливо) |


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - provider — ЗАГАЛЬНА назва для будь-чого, що DI-контейнер МОЖЕ
//   "впорснути" в інший клас; Service — НАЙПОШИРЕНІШИЙ, АЛЕ НЕ
//   ЄДИНИЙ вид provider'а
// - @Injectable() позначає клас "видимим" для DI; providers у
//   @Module() РЕЄСТРУЄ ЙОГО в конкретному модулі — БЕЗ ОБОХ КРОКІВ
//   Nest НЕ ЗМОЖЕ його "знайти", і ПОМИЛКА ловиться ОДРАЗУ ПІД ЧАС
//   старту застосунку, а не десь у рантаймі
// - constructor injection: Nest ЧИТАЄ ТИПИ параметрів КОНСТРУКТОРА
//   ЧЕРЕЗ МЕТАДАНІ й САМ "будує" ГРАФ залежностей знизу вгору —
//   ти НІКОЛИ не пишеш `new` для provider'ів вручну
// - ЗА ЗАМОВЧУВАННЯМ provider — SINGLETON (Scope.DEFAULT): ОДИН
//   екземпляр на ВЕСЬ застосунок; Scope.REQUEST дає НОВИЙ екземпляр
//   на КОЖЕН HTTP-запит, АЛЕ "просочується" на все, що ВІД НЬОГО
//   залежить, і коштує продуктивності
// - custom providers (useValue/useClass/useFactory/useExisting)
//   дають ГНУЧКІСТЬ поза "просто класом" — моки для тестів, вибір
//   реалізації залежно від середовища, асинхронне створення
// - injection tokens (@Inject(token)) ОБОВ'ЯЗКОВІ, коли ТИП
//   параметра — interface чи примітив (вони зникають після
//   компіляції й НІЧОГО НЕ означають у рантаймі)
// - provider ВИДИМИЙ лише в СВОЄМУ модулі, ЯКЩО НЕ exports; @Global()
//   робить його доступним скрізь без повторного imports
// - циклічні залежності (forwardRef()) — ЗДЕБІЛЬШОГО СИМПТОМ
//   поганого поділу відповідальності, а НЕ норма
// - Nest-DI — АВТОМАТИЗОВАНА ВЕРСІЯ ТОГО САМОГО ПРИНЦИПУ, ЯКИЙ У
//   чистому JS РОБИТЬ РОЗРОБНИК ВРУЧНУ, ПЕРЕДАЮЧИ ЗАЛЕЖНОСТІ ЧЕРЕЗ
//   параметри функцій/конструкторів замість `new` "усередині" коду