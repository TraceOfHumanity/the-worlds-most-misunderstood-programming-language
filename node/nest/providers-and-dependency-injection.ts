// UsersService. IoC-КОНТЕЙНЕР НЕ МОЖЕ ВИРІШИТИ, ЯКИЙ СТВОРИТИ ПЕРШИМ
// (детально ПОРЯДОК СТВОРЕННЯ "ЗНИЗУ ВГОРУ" — розділ 4) — ЦЕ І Є
// CIRCULAR DEPENDENCY. Nest ДАЄ forwardRef() ЯК "ОБХІДНИЙ ШЛЯХ":
//
//   @Injectable()
//   export class UsersService {
//     constructor(
//       @Inject(forwardRef(() => OrdersService))
//       private readonly ordersService: OrdersService,
