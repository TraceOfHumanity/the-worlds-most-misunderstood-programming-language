// ==========================================================================
// NEST.JS PROVIDERS & DEPENDENCY INJECTION — ДЕТАЛЬНО
// ==========================================================================

// 0. НАГАДУВАННЯ З overview.ts
// -----------------------------------------------------
// Dependency Injection (DI) — патерн, де клас НЕ СТВОРЮЄ САМ об'єкти,
// від яких залежить, а ОТРИМУЄ їх ЗЗОВНІ (найчастіше — через
// конструктор). У Nest ЦЕ ЦЕНТРАЛЬНИЙ архітектурний принцип, і за
// НЬОГО відповідає окремий механізм — IoC-КОНТЕЙНЕР (Inversion of
// Control container), що САМ вирішує, ЯКИЙ екземпляр КОМУ передати.
// Тут — детально: ЩО таке provider, ЯК контейнер "розплутує" граф
// залежностей, і ЯКІ бувають ВИНЯТКОВІ сценарії (кастомні provider'и,
// scope'и, циклічні залежності).
//
// (Як і в попередніх файлах про Nest, приклади — ПСЕВДОКОД, що
// потребує реального @nestjs/core/@nestjs/common, АЛЕ синтаксично
// відповідає РЕАЛЬНОМУ коду 1:1.)


// ==========================================================================
// 1. ЩО ТАКЕ "PROVIDER" У ТЕРМІНОЛОГІЇ NEST
// ==========================================================================

// "Provider" — ЗАГАЛЬНА назва для БУДЬ-ЧОГО, ЩО МОЖЕ БУТИ "ВПОРШНЕНЕ"
// (injected) в ІНШИЙ клас через DI: сервіси, репозиторії, фабрики,
// helper-класи, навіть ПРОСТІ значення (детально — розділ 5, custom
// providers). Service — ЛИШЕ НАЙПОШИРЕНІШИЙ, "типовий" ВИПАДОК
// provider'а, а НЕ ОКРЕМА мовна конструкція.

//   @Injectable()
//   export class UsersService {
//     private users: { id: number; name: string }[] = [];
//
//     findAll() {
//       return this.users;
//     }
//     create(name: string) {
//       const user = { id: Date.now(), name };
//       this.users.push(user);
//       return user;
//     }
//   }
//
// @Injectable() — ДЕКОРАТОР, що ПОЗНАЧАЄ клас як "видимий" для DI-
// контейнера. БЕЗ ЦЬОГО ДЕКОРАТОРА клас НЕ МОЖЕ бути provider'ом —
// Nest ПРОСТО НЕ ЗНАТИМЕ, ЯК ЙОГО СТВОРЮВАТИ й КЕРУВАТИ його
// життєвим циклом.


// ==========================================================================
// 2. РЕЄСТРАЦІЯ PROVIDER'А В МОДУЛІ — ЯК Nest "ДІЗНАЄТЬСЯ" ПРО НЬОГО
// ==========================================================================

// Просто ПОЗНАЧИТИ клас @Injectable() — НЕДОСТАТНЬО: ЙОГО ще ТРЕБА
// ЗАРЕЄСТРУВАТИ в масиві providers ВІДПОВІДНОГО @Module() (детально
// сам Module — overview.ts, розділ 2.3):
//
//   @Module({
//     controllers: [UsersController],
//     providers: [UsersService], // ← ОСЬ ТУТ Nest "дізнається", що
//                                    UsersService ІСНУЄ і ЙОГО МОЖНА
//                                    "впорснути" в контролери/інші
//                                    provider'и ЦЬОГО модуля
//   })
//   export class UsersModule {}
//
// ЯКЩО provider НЕ ЗАРЕЄСТРОВАНИЙ у providers, а ЙОГО НАМАГАЮТЬСЯ
// "впорснути" — Nest ВИКИНЕ ПОМИЛКУ ПІД ЧАС СТАРТУ застосунку (а НЕ
// десь глибоко в рантаймі під час обробки запиту!):
//
//   Error: Nest can't resolve dependencies of the UsersController
//   (?). Please make sure that the argument UsersService at index [0]
//   is available in the UsersModule context.
//
// ЦЕ ВАЖЛИВА ПЕРЕВАГА: ПОМИЛКА "забув зареєструвати сервіс" ЛОВИТЬСЯ
// ОДРАЗУ ПРИ ЗАПУСКУ, а НЕ ПІСЛЯ ТОГО, ЯК ЩОСЬ ЗЛАМАЛОСЯ В ПРОДАКШЕНІ
// на конкретному запиті.


// ==========================================================================
// 3. CONSTRUCTOR INJECTION — ЯК ЗАЛЕЖНІСТЬ РЕАЛЬНО "ПОТРАПЛЯЄ" В КЛАС
// ==========================================================================

//   @Controller("users")
//   export class UsersController {
//     constructor(private readonly usersService: UsersService) {}
//     //           ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
//     //           "private readonly" ТУТ — ЦЕ TypeScript PARAMETER
//     //           PROPERTIES (скорочений синтаксис): компілятор
//     //           АВТОМАТИЧНО СТВОРЮЄ private-поле this.usersService
//     //           І ОДРАЗУ ПРИСВОЮЄ йому значення параметра — НЕ
//     //           ПОТРІБНО писати this.usersService = usersService; вручну
//
//     @Get()
//     findAll() {
//       return this.usersService.findAll();
//     }
//   }
//
// NEST "ЧИТАЄ" ТИПИ ПАРАМЕТРІВ КОНСТРУКТОРА (ЧЕРЕЗ reflect-metadata —
// та сама технологія, що дозволяє декораторам ІСНУВАТИ ЯК метадані,
// коротко згадано в overview.ts, розділ 4) І РОЗУМІЄ: "щоб СТВОРИТИ
// UsersController, ПОТРІБЕН ЕКЗЕМПЛЯР UsersService" — САМЕ ТИП
// ПАРАМЕТРА (UsersService) І Є "ІНСТРУКЦІЄЮ" для DI-контейнера, ЯКИЙ
// САМЕ provider ТУТ ПОТРІБЕН.


// ==========================================================================
// 4. IoC-КОНТЕЙНЕР: ЯК NEST "РОЗПЛУТУЄ" ГРАФ ЗАЛЕЖНОСТЕЙ
// ==========================================================================

// Уяви, що є ТРИ КЛАСИ, ЩО ЗАЛЕЖАТЬ ОДИН ВІД ОДНОГО:
//
//   @Injectable()
//   export class DatabaseService { /* підключення до БД */ }
//
//   @Injectable()
//   export class UsersRepository {
//     constructor(private readonly db: DatabaseService) {}
//   }
//
//   @Injectable()
//   export class UsersService {
//     constructor(private readonly repository: UsersRepository) {}
//   }
//
//   @Controller("users")
//   export class UsersController {
//     constructor(private readonly usersService: UsersService) {}
//   }
//
// ПІД ЧАС СТАРТУ ЗАСТОСУНКУ (NestFactory.create(AppModule), детально
// overview.ts, розділ 7) IoC-контейнер БУДУЄ ГРАФ ЗАЛЕЖНОСТЕЙ І
// СТВОРЮЄ ЕКЗЕМПЛЯРИ У ПРАВИЛЬНОМУ ПОРЯДКУ — "ЗНИЗУ ВГОРУ":
//
//   1) DatabaseService НЕ МАЄ ЖОДНИХ ЗАЛЕЖНОСТЕЙ → СТВОРЮЄТЬСЯ ПЕРШИМ
//   2) UsersRepository ПОТРЕБУЄ DatabaseService (ВЖЕ Є) → створюється
//   3) UsersService ПОТРЕБУЄ UsersRepository (ВЖЕ Є) → створюється
//   4) UsersController ПОТРЕБУЄ UsersService (ВЖЕ Є) → створюється
//
// ТИ САМ НІКОЛИ НЕ ПИШЕШ `new DatabaseService()` чи `new UsersRepository(db)`
// ВРУЧНУ — ВЕСЬ ЦЕЙ "ЛАНЦЮЖОК СТВОРЕННЯ" ВІДБУВАЄТЬСЯ АВТОМАТИЧНО.
// Це ПРЯМИЙ АНАЛОГ того, ЯК Node.js РОЗВ'ЯЗУЄ require()/import
// (детально сам механізм модулів — окремо), АЛЕ ДЛЯ ЕКЗЕМПЛЯРІВ
// КЛАСІВ, а не файлів.


// ==========================================================================
// 5. SINGLETON ЗА ЗАМОВЧУВАННЯМ — ОДИН ЕКЗЕМПЛЯР НА ВЕСЬ ЗАСТОСУНОК
// ==========================================================================

// ЗА ЗАМОВЧУВАННЯМ (DEFAULT SCOPE) КОЖЕН provider СТВОРЮЄТЬСЯ РІВНО
// ОДИН РАЗ ЗА ВЕСЬ ЧАС РОБОТИ ЗАСТОСУНКУ — ЦЕЙ САМИЙ ЕКЗЕМПЛЯР
// ПОВТОРНО ВИКОРИСТОВУЄТЬСЯ ДЛЯ УСІХ КЛАСІВ, ЩО ЙОГО ПОТРЕБУЮТЬ, У
// БУДЬ-ЯКОМУ ЗАПИТІ:
//
//   @Injectable()
//   export class CounterService {
//     private count = 0;
//     increment() {
//       return ++this.count;
//     }
//   }
//
//   // Якщо ДВА РІЗНІ контролери "впорснуть" CounterService —
//   // ОБИДВА ОТРИМАЮТЬ ТОЙ САМИЙ ЕКЗЕМПЛЯР (той самий this.count!):
//   @Controller("a")
//   export class AController {
//     constructor(private readonly counter: CounterService) {}
//     @Get() hit() { return this.counter.increment(); } // 1, потім 3, потім 5...
//   }
//   @Controller("b")
//   export class BController {
//     constructor(private readonly counter: CounterService) {}
//     @Get() hit() { return this.counter.increment(); } // 2, потім 4, потім 6...
//   }
//   // ОБИДВА ЕНДПОІНТИ "ДІЛЯТЬ" ОДИН СПІЛЬНИЙ СТАН — це і Є singleton
//
// ЦЕ ЕФЕКТИВНО (НЕ СТВОРЮЄТЬСЯ НОВИЙ ЕКЗЕМПЛЯР НА КОЖЕН ЗАПИТ), АЛЕ
// ОЗНАЧАЄ: НЕ ЗБЕРІГАЙ У ЗВИЧАЙНОМУ (DEFAULT SCOPE) PROVIDER'І
// СТАН, СПЕЦИФІЧНИЙ ДЛЯ ОДНОГО КОНКРЕТНОГО HTTP-ЗАПИТУ (наприклад,
// ID поточного користувача) — ЦЕЙ СТАН "ПРОТЕЧЕ" В ІНШІ, ПАРАЛЕЛЬНІ
// ЗАПИТИ (класична пастка, аналогічна ГЛОБАЛЬНИМ ЗМІННИМ У JS,
// детально common/variables-and-execution-context/var.js).


// ==========================================================================
// 6. INJECTION SCOPES — КОЛИ ПОТРІБЕН НЕ-SINGLETON PROVIDER
// ==========================================================================

// Nest ДОЗВОЛЯЄ ЗМІНИТИ "ЖИТТЄВИЙ ЦИКЛ" provider'а через { scope }
// в @Injectable():
//
//   import { Injectable, Scope } from "@nestjs/common";
//
//   @Injectable({ scope: Scope.DEFAULT })   // singleton (за замовчуванням) — розділ 5
//   @Injectable({ scope: Scope.REQUEST })   // НОВИЙ екземпляр НА КОЖЕН HTTP-запит
//   @Injectable({ scope: Scope.TRANSIENT }) // НОВИЙ екземпляр НА КОЖНЕ "впорснення"
//                                              (навіть у межах ОДНОГО запиту, якщо
//                                              кілька класів його потребують)
//
// Scope.REQUEST — ТИПОВИЙ ВИБІР, КОЛИ ПОТРІБНО ЗБЕРІГАТИ ДАНІ,
// СПЕЦИФІЧНІ ДЛЯ ОДНОГО ЗАПИТУ (наприклад, "поточний користувач,
// що робить запит"):
//
//   @Injectable({ scope: Scope.REQUEST })
//   export class RequestContextService {
//     currentUserId: string | null = null; // БЕЗПЕЧНО — це ОКРЕМИЙ
//                                              екземпляр ДЛЯ КОЖНОГО запиту
//   }
//
// ⚠️ ВАЖЛИВИЙ КОМПРОМІС: Scope.REQUEST "ПРОСОЧУЄТЬСЯ" ВГОРУ ГРАФОМ
// ЗАЛЕЖНОСТЕЙ — ЯКЩО UsersService ЗАЛЕЖИТЬ ВІД REQUEST-scoped
// provider'а, UsersService ТЕЖ СТАЄ REQUEST-scoped (навіть ЯКЩО САМ
// НЕ ОГОЛОШУВАВ ЦЕ ЯВНО) — а ЦЕ ОЗНАЧАЄ ВІДМОВУ ВІД SINGLETON-
// ОПТИМІЗАЦІЇ ДЛЯ ВСЬОГО "ЛАНЦЮЖКА" ЙОГО СПОЖИВАЧІВ, ЩО МОЖЕ
// ПОМІТНО ВПЛИНУТИ НА ПРОДУКТИВНІСТЬ ПРИ ВИСОКОМУ НАВАНТАЖЕННІ
// (НОВІ ЕКЗЕМПЛЯРИ НА КОЖЕН ЗАПИТ ЗАМІСТЬ ОДНОГО СПІЛЬНОГО).


// ==========================================================================
// 7. CUSTOM PROVIDERS — КОЛИ ПОТРІБНО БІЛЬШЕ, НІЖ "ПРОСТО КЛАС"
// ==========================================================================

// Масив providers у @Module() ПРИЙМАЄ НЕ ЛИШЕ "ГОЛІ" класи — ЦЕ
// СКОРОЧЕНИЙ ЗАПИС. ПОВНА, РОЗГОРНУТА ФОРМА ВИГЛЯДАЄ ТАК:
//
//   providers: [UsersService]
//   // ЦЕ РІВНО ТЕ САМЕ, ЩО:
//   providers: [{ provide: UsersService, useClass: UsersService }]
//
// "provide" — ЦЕ ТОКЕН (ІМ'Я, ЗА ЯКИМ ЦЕЙ PROVIDER ШУКАЄТЬСЯ), А
// РЕШТА ПОЛІВ ОПИСУЄ, ЯК САМЕ ЙОГО СТВОРИТИ. Розгорнута форма
// ВІДКРИВАЄ КІЛЬКА ПОТУЖНИХ МОЖЛИВОСТЕЙ:

// 7.1. useValue — ГОТОВЕ ЗНАЧЕННЯ ЗАМІСТЬ КЛАСУ (КОНФІГИ, КОНСТАНТИ, МОКИ)
// -----------------------------------------------------
//   const MOCK_USERS_SERVICE = { findAll: () => [{ id: 1, name: "Тест" }] };
//
//   @Module({
//     providers: [{ provide: UsersService, useValue: MOCK_USERS_SERVICE }],
//   })
//   export class UsersTestModule {}
//   // ІДЕАЛЬНО для ЮНІТ-ТЕСТІВ: "підмінюємо" РЕАЛЬНИЙ сервіс на
//   // ПРОСТИЙ ОБ'ЄКТ БЕЗ ЖОДНИХ ЗМІН у коді КОНТРОЛЕРА

// 7.2. useClass — ІНШИЙ КЛАС ЗА ТИМ САМИМ ТОКЕНОМ (ЗАЛЕЖНО ВІД СЕРЕДОВИЩА)
// -----------------------------------------------------
//   @Module({
//     providers: [
//       {
//         provide: EmailService,
//         useClass: process.env.NODE_ENV === "production"
//           ? RealEmailService   // реально відправляє листи
//           : FakeEmailService,  // просто логує в консоль, НЕ відправляє
//       },
//     ],
//   })
//   export class NotificationsModule {}

// 7.3. useFactory — ЗНАЧЕННЯ, ЩО ОБЧИСЛЮЄТЬСЯ ФУНКЦІЄЮ (МОЖЕ САМА МАТИ ЗАЛЕЖНОСТІ)
// -----------------------------------------------------
//   @Module({
//     providers: [
//       {
//         provide: "DATABASE_CONNECTION",
//         useFactory: async (configService: ConfigService) => {
//           const connection = await createConnection(configService.get("DB_URL"));
//           return connection;
//         },
//         inject: [ConfigService], // ЯКІ provider'и ПЕРЕДАТИ у useFactory як аргументи
//       },
//     ],
//   })
//   export class DatabaseModule {}
//   // useFactory — ЄДИНИЙ спосіб, КОЛИ СТВОРЕННЯ ЗАЛЕЖИТЬ ВІД
//   // АСИНХРОННОЇ ОПЕРАЦІЇ АБО ВІД ЗНАЧЕНЬ, ВІДОМИХ ЛИШЕ В РАНТАЙМІ

// 7.4. useExisting — АЛІАС ("ІНШЕ ІМ'Я") ДЛЯ ВЖЕ ІСНУЮЧОГО PROVIDER'А
// -----------------------------------------------------
//   providers: [
//     LoggerService,
//     { provide: "AliasedLoggerService", useExisting: LoggerService },
//   ]
//   // "AliasedLoggerService" І LoggerService ТЕПЕР ВКАЗУЮТЬ НА ОДИН
//   // І ТОЙ САМИЙ ЕКЗЕМПЛЯР (НЕ СТВОРЮЄТЬСЯ ДРУГИЙ!)


// ==========================================================================
// 8. INJECTION TOKENS — КОЛИ ТОКЕН НЕ МОЖЕ БУТИ КЛАСОМ
// ==========================================================================

// ТИПИ TypeScript (interface, "просто" тип значення на кшталт string
// чи number) ПОВНІСТЮ ЗНИКАЮТЬ ПІСЛЯ КОМПІЛЯЦІЇ (детально —
// typescript/basic-types.ts, вступ) — А ЦЕ ОЗНАЧАЄ, ЩО DI-КОНТЕЙНЕР
// (ЯКИЙ ПРАЦЮЄ В РАНТАЙМІ, КОЛИ ТИПІВ УЖЕ НЕМАЄ) НЕ МОЖЕ
// "ІН'ЄКТУВАТИ" ЗА interface — interface ЦЕ ЛИШЕ COMPILE-TIME
// КОНСТРУКЦІЯ, ЇЙ НІЧОГО НЕ ВІДПОВІДАЄ В РАНТАЙМІ:
//
//   interface Logger {
//     log(message: string): void;
//   }
//   // constructor(private readonly logger: Logger) {} // ❌ Nest НЕ ЗМОЖЕ
//                                                          "здогадатись", ЯКИЙ
//                                                          РЕАЛЬНИЙ клас підставити —
//                                                          interface Logger В РАНТАЙМІ
//                                                          ПРОСТО НЕ ІСНУЄ
//
// РІШЕННЯ — ЯВНИЙ INJECTION TOKEN (РЯДОК, symbol, АБО КЛАС-МАРКЕР) І
// @Inject() ДЛЯ ЙОГО ЯВНОЇ ВКАЗІВКИ В КОНСТРУКТОРІ:
//
//   export const LOGGER_TOKEN = "LOGGER_TOKEN"; // МОЖЕ бути й Symbol("LOGGER")
//
//   @Module({
//     providers: [{ provide: LOGGER_TOKEN, useClass: ConsoleLogger }],
//   })
//   export class LoggingModule {}
//
//   @Injectable()
//   export class UsersService {
//     constructor(@Inject(LOGGER_TOKEN) private readonly logger: Logger) {}
//     //           ^^^^^^^^^^^^^^^^^^^^^
//     //           ЯВНО КАЖЕМО: "ШУКАЙ PROVIDER ЗА ЦИМ ТОКЕНОМ",
//     //           А НЕ ЗА ТИПОМ ПАРАМЕТРА (interface ТУТ ЛИШЕ ДЛЯ
//     //           COMPILE-TIME ПІДКАЗКИ МЕТОДІВ logger.log(...))
//   }
//
// ДЛЯ ЗВИЧАЙНИХ КЛАСІВ (НЕ interface) @Inject() НЕ ПОТРІБЕН — Nest
// САМ БЕРЕ КЛАС ЯК ТОКЕН (детально — розділ 3, "Nest читає ТИПИ
// параметрів").


// ==========================================================================
// 9. @Optional() — PROVIDER, БЕЗ ЯКОГО МОЖНА ОБІЙТИСЬ
// ==========================================================================

// ЯКЩО ЗАЛЕЖНІСТЬ НЕ ОБОВ'ЯЗКОВА (МОЖЕ БУТИ НЕ ЗАРЕЄСТРОВАНА В
// ПЕВНИХ КОНФІГУРАЦІЯХ) — @Optional() ЗАПОБІГАЄ ПОМИЛЦІ "Nest can't
// resolve dependencies" ПРИ СТАРТІ, ПІДСТАВЛЯЮЧИ undefined:
//
//   @Injectable()
//   export class UsersService {
//     constructor(
//       @Optional() @Inject("FEATURE_FLAGS") private readonly flags?: FeatureFlags,
//     ) {}
//
//     isNewFlowEnabled() {
//       return this.flags?.newFlow ?? false; // БЕЗПЕЧНО, навіть ЯКЩО flags === undefined
//     }
//   }


// ==========================================================================
// 10. ЕКСПОРТ PROVIDER'ІВ МІЖ МОДУЛЯМИ
// ==========================================================================

// ЗА ЗАМОВЧУВАННЯМ provider ВИДИМИЙ ЛИШЕ ВСЕРЕДИНІ СВОГО МОДУЛЯ.
// ЩОБ ІНШИЙ МОДУЛЬ МІГ ЙОГО "ВПОРСНУТИ" — ЙОГО ТРЕБА ЯВНО ЕКСПОРТУВАТИ
// (детально сам синтаксис Module — overview.ts, розділ 2.3):
//
//   @Module({
//     providers: [UsersService],
//     exports: [UsersService], // ← БЕЗ ЦЬОГО РЯДКА ІНШІ МОДУЛІ
//                                  НЕ ЗМОЖУТЬ "ВПОРСНУТИ" UsersService,
//                                  НАВІТЬ ЯКЩО ІМПОРТУЮТЬ UsersModule!
//   })
//   export class UsersModule {}
//
//   @Module({
//     imports: [UsersModule], // ІМПОРТУЄМО МОДУЛЬ, ЩОБ ОТРИМАТИ
//                                 ДОСТУП ДО ЙОГО exports
