// 9. ЯК NEST ВИЗНАЧАЄ, ЩО ПОВЕРНУТИ КЛІЄНТУ (СТАНДАРТНИЙ РЕЖИМ)
// ==========================================================================

// У "СТАНДАРТНОМУ" (не-express-специфічному) підході handler ПРОСТО
// return'ить значення — Nest САМ серіалізує його в JSON і виставляє
// правильний Content-Type:
//
//   @Get(":id")
//   findOne(@Param("id") id: string) {
//     return { id, name: "Олег" }; // Nest САМ робить res.json({...}) "під капотом"
//   }
//
// АСИНХРОННІ HANDLER'И — Nest РОЗУМІЄ Promise/async-await НАТИВНО
// (детально механіка самого async/await — common/asynchronous/asynchronous.js):
//
//   @Get(":id")
//   async findOne(@Param("id") id: string) {
//     const user = await this.usersService.findById(id); // Nest ДОЧЕКАЄТЬСЯ
//                                                             Promise і візьме РЕЗУЛЬТАТ
//     return user;
//   }
//
// ЦЕЙ "СТАНДАРТНИЙ" підхід — РЕКОМЕНДОВАНИЙ за замовчуванням, бо він
// НЕ ЗАВ'ЯЗАНИЙ на конкретну HTTP-бібліотеку (Express чи Fastify) —
// код контролера ЛИШАЄТЬСЯ ОДНАКОВИМ незалежно від того, ЩО Nest
// використовує "під капотом".


// ==========================================================================
// 10. LIBRARY-SPECIFIC РЕЖИМ: @Res() — ПРЯМИЙ ДОСТУП ДО ОБ'ЄКТА ВІДПОВІДІ
// ==========================================================================

// Іноді потрібен ПОВНИЙ, ручний контроль над відповіддю (стрімінг
// файлу, нестандартні заголовки, кукі тощо) — для цього є @Res()
// (Express-подібний res-об'єкт, детально знайомий за node/core-concepts/http):
//
//   import { Response } from "express";
//
//   @Get(":id")
//   findOne(@Param("id") id: string, @Res() res: Response) {
//     res.status(200).json({ id, name: "Олег" }); // ТЕПЕР ти сам
//                                                     повністю відповідаєш за відповідь
//   }
//
// ⚠️ КРИТИЧНО ВАЖЛИВИЙ НЮАНС: ЩОЙНО ти додаєш @Res() у ПАРАМЕТРИ
// handler'а, NEST ПЕРЕСТАЄ "автоматично" обробляти return-значення
// ЦЬОГО handler'а — ТИ ЗОБОВ'ЯЗАНИЙ САМ викликати res.send()/res.json()/
// res.end(), ІНАКШЕ ЗАПИТ "ЗАВИСНЕ" (клієнт ніколи НЕ ОТРИМАЄ
// відповідь, бо жоден код так і НЕ завершив HTTP-response):
//
//   @Get(":id")
//   findOneBroken(@Param("id") id: string, @Res() res: Response) {
//     return { id }; // ❌ ЦЕ ПРОСТО ІГНОРУЄТЬСЯ! res.json()/.send() НЕ викликано —
//                       клієнт "зависне" в очікуванні відповіді назавжди
//   }
//
// ЯКЩО ПОТРІБЕН ДОСТУП до res ЛИШЕ ДЛЯ ЧОГОСЬ ДОДАТКОВОГО (наприклад,
// встановити cookie), а РЕШТУ ВІДПОВІДІ ХОЧЕШ ЛИШИТИ "СТАНДАРТНОМУ"
// режиму — є { passthrough: true }:
//
//   @Get(":id")
//   findOne(@Param("id") id: string, @Res({ passthrough: true }) res: Response) {
//     res.cookie("lastViewedId", id); // ДОДАТКОВА дія над res
//     return { id, name: "Олег" };      // А return усе одно ПРАЦЮЄ звично!
//   }


// ==========================================================================
// 11. @Req() — ПОВНИЙ ОБ'ЄКТ ЗАПИТУ (КОЛИ ДЕКОРАТОРІВ-ПАРАМЕТРІВ НЕДОСТАТНЬО)
// ==========================================================================

//   import { Request } from "express";
//
//   @Get()
//   findAll(@Req() req: Request) {
//     console.log(req.ip, req.headers["user-agent"]);
//     return "ok";
//   }
//
// ЗАЗВИЧАЙ @Param()/@Query()/@Body()/@Headers() ПОКРИВАЮТЬ 95%
// потреб — @Req() потрібен ЛИШЕ для ДІЙСНО специфічних речей
// (наприклад, req.ip, кастомні властивості, додані middleware).


// ==========================================================================
// 12. ВКЛАДЕНІ ШЛЯХИ Й ВАЙЛДКАРДИ
// ==========================================================================

//   @Controller("users")
//   export class UsersController {
//     @Get("me/profile")     // GET /users/me/profile — статичний вкладений шлях
//     getMyProfile() { ... }
//
//     @Get("*")                // GET /users/будь-що — "ловить" усе, що НЕ
//     catchUnmatched() { ... } //   збіглося з іншими, БІЛЬШ КОНКРЕТНИМИ маршрутами
//   }
//
// ПОРЯДОК ОГОЛОШЕННЯ МЕТОДІВ У КЛАСІ ВПЛИВАЄ на пріоритет зіставлення
// маршрутів (більш конкретні варто оголошувати РАНІШЕ за "ловці всього").


// ==========================================================================
// 13. СЕРВІС ЯК ЗАЛЕЖНІСТЬ — ЧОМУ КОНТРОЛЕР НЕ "РОБИТЬ" РОБОТУ САМ
// ==========================================================================

// Повний, реалістичний приклад, що ЗВОДИТЬ УСЕ РАЗОМ (детально сам
// механізм DI — окремий майбутній файл, тут — лише ЯК ЦЕ ВИГЛЯДАЄ
// З БОКУ КОНТРОЛЕРА):
//
//   @Controller("users")
//   export class UsersController {
//     constructor(private readonly usersService: UsersService) {}
//     // ^ Nest САМ створює/підставляє UsersService — жодного `new` тут немає
//
//     @Get()
//     findAll(@Query("role") role?: string) {
//       return this.usersService.findAll(role); // КОНТРОЛЕР ЛИШЕ делегує
//     }
//
//     @Get(":id")
//     async findOne(@Param("id") id: string) {
//       const user = await this.usersService.findById(id);
//       if (!user) {
//         throw new NotFoundException(`Користувача ${id} не знайдено`);
//         // ^ NestJS має ГОТОВІ HTTP exception-класи (NotFoundException,
//         //   BadRequestException, ForbiddenException тощо) — кинута
//         //   помилка АВТОМАТИЧНО перетворюється на правильну HTTP-
//         //   відповідь (404, 400, 403...) через exception filters
//         //   (детально — окремий майбутній файл)
//       }
//       return user;
//     }
//
//     @Post()
//     create(@Body() dto: CreateUserDto) {
//       return this.usersService.create(dto);
//     }
//   }
//
// ЦЕ ГОЛОВНИЙ ПРИНЦИП: КОНТРОЛЕР — "ТОНКИЙ" ШАР (thin controller).
// Уся РЕАЛЬНА логіка (пошук у БД, перевірки, обчислення) живе В
// СЕРВІСІ, а НЕ в контролері — САМЕ ЦЕ РОЗДІЛЕННЯ РОБИТЬ КОНТРОЛЕР
// ЛЕГКИМ ДЛЯ ЧИТАННЯ (він буквально "мапа маршрутів") І ЛЕГКИМ ДЛЯ
// ТЕСТУВАННЯ (сервіс тестується ОКРЕМО, без HTTP-шару взагалі).


// ==========================================================================
// ШПАРГАЛКА: НАЙПОШИРЕНІШІ ДЕКОРАТОРИ КОНТРОЛЕРА
// ==========================================================================

// | Декоратор                    | Що робить                                              |
// |----------------------------------|---------------------------------------------------------|
// | @Controller(prefix)             | позначає клас контролером, задає спільний префікс URL |
// | @Get / @Post / @Put / @Patch / @Delete / @All | прив'язує метод до HTTP-методу + підшляху |
// | @Param(key?)                     | дані з ДИНАМІЧНОЇ частини URL (:id)                   |
// | @Query(key?)                     | дані з query-рядка (?key=value)                        |
// | @Body(key?)                      | дані з JSON-тіла запиту (зазвичай — DTO)              |
// | @Headers(key?)                   | HTTP-заголовки запиту                                   |
// | @HttpCode(code)                  | явний статус-код відповіді                              |
// | @Header(name, value)             | явний заголовок відповіді                               |
// | @Redirect(url?, code?)           | HTTP-редирект                                            |
// | @Req() / @Res()                  | "сирий" об'єкт запиту/відповіді (library-specific режим)|


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - @Controller(prefix) + декоратори HTTP-методів (@Get/@Post/...)
//   ОГОЛОШУЮТЬ маршрути ДЕКЛАРАТИВНО, через метадані — на відміну
//   від ІМПЕРАТИВНОГО app.get() в "голому" Express
// - @Param()/@Query()/@Body()/@Headers() "витягують" відповідні
//   частини HTTP-запиту й передають їх у handler ЯК ЗВИЧАЙНІ
//   аргументи функції — Nest сам "збирає" значення за позицією параметра
// - DTO-тип у @Body() — ЛИШЕ compile-time підказка форми; БЕЗ
//   окремого ValidationPipe жодної РЕАЛЬНОЇ перевірки в рантаймі НЕМАЄ
//   (той самий принцип "типи зникають", що й у чистому TypeScript)
// - "стандартний" режим — просто return значення з handler'а, Nest
//   сам серіалізує й відправляє відповідь; РОЗУМІЄ async/await нативно
// - "library-specific" режим (@Res()) дає повний контроль, АЛЕ ЗНІМАЄ
//   з Nest відповідальність за відповідь — ти МУСИШ сам викликати
//   res.send()/.json(), інакше запит "зависне"; { passthrough: true }
//   дозволяє скомбінувати обидва підходи
