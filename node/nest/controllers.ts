// у ПРАВИЛЬНОМУ порядку (ЗА ПОЗИЦІЄЮ параметра, а НЕ за назвою):
//
//   @Patch(":id")
//   update(
//     @Param("id") id: string,
//     @Body() dto: UpdateUserDto,
//     @Query("notify") notify: string,
