// ==========================================================================
// NEST.JS CONTROLLERS — МАРШРУТИЗАЦІЯ HTTP-ЗАПИТІВ ДЕТАЛЬНО
// ==========================================================================

// 0. НАГАДУВАННЯ З overview.ts
// -----------------------------------------------------
// Controller — клас, що ВІДПОВІДАЄ ЗА МАРШРУТИЗАЦІЮ: приймає HTTP-
// запит, ДІСТАЄ з нього потрібні дані (параметри URL, query-рядок,
// тіло запиту), делегує РОБОТУ сервісу (детально Providers/DI —
// окремий майбутній файл) і повертає ВІДПОВІДЬ. Тут — детально ПРО
// САМ контролер: декоратори маршрутів, як "витягти" дані із запиту,
// як керувати статус-кодом/заголовками відповіді.
//
// Приклади нижче — ПСЕВДОКОД (потребують встановлених @nestjs/core,
// @nestjs/common), АЛЕ синтаксично й структурно ТОЧНО відповідають
// РЕАЛЬНОМУ Nest-коду — саме так це виглядає в справжньому проєкті.


// ==========================================================================
// 1. @Controller() — БАЗОВИЙ ДЕКОРАТОР І ПРЕФІКС МАРШРУТУ
// ==========================================================================

// @Controller(префікс) ПОЗНАЧАЄ клас як контролер і ЗАДАЄ СПІЛЬНИЙ
// префікс URL для УСІХ методів усередині нього:
//
//   @Controller("users")
//   export class UsersController {
//     // усі маршрути нижче автоматично починаються з /users
//   }
//
// БЕЗ АРГУМЕНТУ — контролер обслуговує маршрути ВІД КОРЕНЯ (/):
//
//   @Controller()
//   export class AppController {
//     @Get()
//     getHello(): string {
//       return "Привіт!"; // GET /
//     }
//   }


// ==========================================================================
// 2. ДЕКОРАТОРИ HTTP-МЕТОДІВ — ОДИН ДЕКОРАТОР НА ОДИН МЕТОД HANDLER'А
// ==========================================================================

// Кожен HTTP-метод має СВІЙ декоратор, що застосовується ДО МЕТОДУ
// КЛАСУ (не до самого класу) — метод стає "handler" для ЦЬОГО
// поєднання HTTP-методу й підшляху:
//
//   @Controller("users")
//   export class UsersController {
//     @Get()               // GET /users
//     findAll() { ... }
//
//     @Get(":id")           // GET /users/:id
//     findOne(@Param("id") id: string) { ... }
//
//     @Post()               // POST /users
//     create(@Body() dto: CreateUserDto) { ... }
//
//     @Put(":id")           // PUT /users/:id — ПОВНА заміна ресурсу
//     replace(@Param("id") id: string, @Body() dto: CreateUserDto) { ... }
//
//     @Patch(":id")         // PATCH /users/:id — ЧАСТКОВЕ оновлення
//     update(@Param("id") id: string, @Body() dto: UpdateUserDto) { ... }
//
//     @Delete(":id")        // DELETE /users/:id
//     remove(@Param("id") id: string) { ... }
//
//     @All("*")              // ЛОВИТЬ УСІ HTTP-методи на будь-якому підшляху
//     catchAll() { ... }
//   }
//
// ЦЕ ПРЯМИЙ АНАЛОГ app.get()/app.post()/... в Express — РІЗНИЦЯ ЛИШЕ
// в тому, ЩО маршрут ОГОЛОШУЄТЬСЯ ЧЕРЕЗ ДЕКОРАТОР МЕТОДУ, а не через
// виклик функції з callback.


// ==========================================================================
// 3. @Param() — ДІСТАТИ ЗМІННУ ЧАСТИНУ URL
// ==========================================================================

// :id у шляху "@Get(':id')" — ДИНАМІЧНИЙ сегмент URL. @Param()
// "витягує" ЙОГО значення з РЕАЛЬНОГО запиту:
//
//   @Get(":id")
//   findOne(@Param("id") id: string) {
//     return `користувач з id=${id}`;
//   }
//   // GET /users/42 → id === "42" (ЗАВЖДИ РЯДОК, навіть якщо URL містив цифри!)
//
// БЕЗ АРГУМЕНТУ @Param() ПОВЕРТАЄ ОБ'ЄКТ З УСІМА параметрами шляху
// одразу (корисно, якщо їх декілька):
//
//   @Get(":category/:id")
//   findByCategoryAndId(@Param() params: { category: string; id: string }) {
//     return `${params.category} / ${params.id}`;
//   }
//   // GET /users/electronics/42 → { category: "electronics", id: "42" }


// ==========================================================================
// 4. @Query() — ДІСТАТИ QUERY-РЯДОК (?key=value)
// ==========================================================================

//   @Get()
//   findAll(@Query("page") page: string, @Query("limit") limit: string) {
//     return `сторінка ${page}, ліміт ${limit}`;
//   }
//   // GET /users?page=2&limit=10 → page === "2", limit === "10"
//
// БЕЗ АРГУМЕНТУ — ОБ'ЄКТ з УСІМА query-параметрами:
//
//   @Get()
//   findAll(@Query() query: { page?: string; limit?: string }) {
//     const page = Number(query.page ?? 1);   // ЯВНА конвертація в число —
//     const limit = Number(query.limit ?? 20); // query ЗАВЖДИ приходить як рядки
//                                                  // (детально проблема типів з
//                                                  // зовнішніх джерел — common/type-coercion.js)
//     return { page, limit };
//   }


// ==========================================================================
// 5. @Body() — ДІСТАТИ ТІЛО ЗАПИТУ (JSON), НАЙЧАСТІШЕ ЧЕРЕЗ DTO
// ==========================================================================

// DTO (Data Transfer Object) — ЗВИЧАЙНИЙ клас/interface, що ОПИСУЄ
// ОЧІКУВАНУ ФОРМУ тіла запиту. @Body() "прив'язує" JSON-тіло HTTP-
// запиту ДО ТИПУ DTO:
//
//   export class CreateUserDto {
//     name: string;
//     email: string;
//     age: number;
//   }
//
//   @Post()
//   create(@Body() dto: CreateUserDto) {
//     return `створено ${dto.name} <${dto.email}>`;
//   }
//   // POST /users  { "name": "Олег", "email": "oleg@example.com", "age": 30 }
//
// ВАЖЛИВО: САМ ПО СОБІ @Body() з ТИПОМ CreateUserDto НЕ ВАЛІДУЄ
// ДАНІ В РАНТАЙМІ — тип DTO ТУТ ЛИШЕ ДЛЯ COMPILE-TIME підказки (той
// самий принцип "типи зникають після компіляції" з
// typescript/basic-types.ts, п. 0). ЩОБ РЕАЛЬНО ПЕРЕВІРИТИ вхідні
// дані ПІД ЧАС ВИКОНАННЯ (наприклад, що email — дійсно email, а age —
// дійсно число ≥ 0), потрібні PIPES (клас-валідатор + ValidationPipe) —
// окрема, детальна тема майбутнього файлу; тут важливо ЗАПАМ'ЯТАТИ,
// що БЕЗ pipe DTO — це ЛИШЕ "обіцянка" форми, а НЕ гарантія:
//
//   @Post()
//   create(@Body() dto: CreateUserDto) {
//     // БЕЗ ValidationPipe сюди МОЖЕ прийти { name: 123, email: null } —
//     // TypeScript тут БЕЗСИЛИЙ, бо перевірка типів давно "зникла"
//     // на етапі компіляції (детально різниця compile-time/runtime —
//     // typescript/basic-types.ts, вступ)
//   }
//
// ЧАСТИНА тіла (одне конкретне поле):
//
//   @Post()
//   create(@Body("name") name: string) { ... } // бере ЛИШЕ поле "name" з JSON-тіла


