// 8. КОДИ СТАТУСУ Й ЗАГОЛОВКИ ВІДПОВІДІ
// ==========================================================================

// 8.1. @HttpCode() — ЗМІНИТИ СТАТУС-КОД ЗА ЗАМОВЧУВАННЯМ
// -----------------------------------------------------
// За замовчуванням Nest повертає 200 (для GET/PUT/PATCH/DELETE) або
