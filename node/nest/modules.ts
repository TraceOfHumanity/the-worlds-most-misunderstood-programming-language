//   МОДУЛІ РАЗОМ (ЛИШЕ imports)
// - КОЖЕН ЗАСТОСУНОК МАЄ ОДИН КОРЕНЕВИЙ AppModule, ЯКИЙ "ЗБИРАЄ"
//   ФІЧЕ-МОДУЛІ (UsersModule, OrdersModule...), КОЖЕН З ЯКИХ
//   ВІДПОВІДАЄ ЗА ОДНУ ЛОГІЧНУ ЧАСТИНУ ДОМЕНУ
// - КОЖЕН МОДУЛЬ МАЄ СВІЙ "ІЗОЛЬОВАНИЙ" DI-КОНТЕЙНЕР — provider,
//   НЕ ЕКСПОРТОВАНИЙ ЯВНО, НЕВИДИМИЙ ЗА МЕЖАМИ СВОГО МОДУЛЯ, НАВІТЬ
//   ЯКЩО МОДУЛЬ ІМПОРТОВАНО В ІНШИЙ (це НАВМИСНА ІНКАПСУЛЯЦІЯ)
// - imports ІМПОРТУЄ ВЕСЬ exports МОДУЛЯ ЦІЛИКОМ, а не окремі
//   provider'и вибірково
// - ПОВТОРНЕ ІМПОРТУВАННЯ ОДНОГО Й ТОГО Ж МОДУЛЯ В КІЛЬКОХ МІСЦЯХ
//   НЕ СТВОРЮЄ ДУБЛІКАТІВ — МОДУЛЬ (І ЙОГО provider'и) ЛИШАЄТЬСЯ
//   SINGLETON НА ВЕСЬ ЗАСТОСУНОК
// - МОДУЛЬ МОЖЕ РЕЕКСПОРТУВАТИ ЦІЛИЙ ІМПОРТОВАНИЙ МОДУЛЬ, "ПРОКИДАЮЧИ"
