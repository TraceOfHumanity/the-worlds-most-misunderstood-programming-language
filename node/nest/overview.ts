// ==========================================================================
// NEST.JS — ЗАГАЛЬНЕ ОЗНАЙОМЛЕННЯ: ЩО ЦЕ Й ЯК ВОНО ПРАЦЮЄ
// ==========================================================================

// 0. ЩО ТАКЕ NestJS
// -----------------------------------------------------
// NestJS — це ФРЕЙМВОРК для побудови server-side застосунків на
// Node.js, написаний і призначений САМЕ ДЛЯ TypeScript (хоча технічно
// дозволяє й чистий JS). На відміну від Express чи Fastify (які
// самі по собі — "мінімалістичні" бібліотеки для маршрутизації HTTP-
// запитів, БЕЗ нав'язаної структури проєкту), Nest НАКЛАДАЄ ЦІЛУ
// АРХІТЕКТУРНУ ФІЛОСОФІЮ: як організовувати код, як компоненти
// спілкуються між собою, де живе бізнес-логіка.
//
// ПІД КАПОТОМ Nest, за замовчуванням, ВИКОРИСТОВУЄ САМЕ Express
// (можна перемкнути на Fastify) — тобто Nest НЕ "замінює" Express,
// а БУДУЄ НАД НИМ шар архітектури, dependency injection і
// декораторів. Це варто розуміти одразу: Nest — НЕ конкурент
// Express на тому самому рівні абстракції, а НАДБУДОВА НАД ним
// (або над Fastify).


// ==========================================================================
// 1. ЧОМУ NEST З'ЯВИВСЯ: ПРОБЛЕМА, ЯКУ ВІН ВИРІШУЄ
// ==========================================================================

// Express навмисно НЕ ДИКТУЄ структуру проєкту — це і сила (повна
// свобода), і слабкість (кожна команда/розробник вигадує СВОЮ
// структуру, і ВЕЛИКІ Express-проєкти з часом стають ВАЖКО
// підтримувати без узгодженої архітектури: де класти бізнес-логіку,
// як тестувати роути ізольовано, як перевикористовувати сервіси
// між різними частинами застосунку).
//
// Nest НАВМИСНО ЗАПОЗИЧУЄ архітектурні ідеї з Angular (той самий
// автор екосистеми, Kamil Myśliwiec, свідомо орієнтувався на
// Angular-подібний підхід для backend): МОДУЛІ, ДЕКОРАТОРИ,
// DEPENDENCY INJECTION, чітке розділення відповідальності. Якщо ти
// колись працював з Angular на фронтенді — структура Nest-проєкту
// виглядатиме ЗНАЙОМОЮ.


// ==========================================================================
// 2. ТРИ БАЗОВІ БУДІВЕЛЬНІ БЛОКИ NEST-ЗАСТОСУНКУ
// ==========================================================================

// Практично КОЖЕН Nest-застосунок будується з ЦИХ трьох типів
// класів, що взаємодіють через ДЕКОРАТОРИ (@Controller, @Injectable,
// @Module тощо — детально декоратори розберемо в окремому файлі):

// 2.1. CONTROLLER (контролер) — ПРИЙМАЄ HTTP-ЗАПИТИ
// -----------------------------------------------------
// Контролер — це клас, що ВІДПОВІДАЄ ЗА МАРШРУТИЗАЦІЮ: "які URL і
// HTTP-методи ОБСЛУГОВУЄ ЦЕЙ клас". Сам контролер НЕ МАЄ містити
// бізнес-логіку — лише приймати запит, делегувати роботу сервісу,
// повернути відповідь. Це ПРЯМИЙ АНАЛОГ "route handlers" в Express,
// АЛЕ оформлений як КЛАС із МЕТОДАМИ, позначеними декораторами:
//
//   @Controller("users")
//   export class UsersController {
//     @Get()
//     findAll() { ... }       // GET /users
//
//     @Get(":id")
//     findOne(@Param("id") id: string) { ... } // GET /users/:id
//
//     @Post()
//     create(@Body() dto: CreateUserDto) { ... } // POST /users
//   }
//
// (детальний розбір декораторів контролера, параметрів запиту тощо —
// в окремому файлі про контролери)


// 2.2. PROVIDER / SERVICE (сервіс) — МІСТИТЬ БІЗНЕС-ЛОГІКУ
// -----------------------------------------------------
// Provider (найчастіше — Service) — це клас, що ІНКАПСУЛЮЄ РЕАЛЬНУ
// логіку: роботу з базою даних, обчислення, звернення до зовнішніх
// API. Контролер НЕ РОБИТЬ ЦЮ РОБОТУ САМ — він ЗАПИТУЄ сервіс:
//
//   @Injectable()
//   export class UsersService {
//     private users = [];
//
//     findAll() {
//       return this.users;
//     }
//     create(dto: CreateUserDto) {
//       const user = { id: Date.now(), ...dto };
//       this.users.push(user);
//       return user;
//     }
//   }
//
// @Injectable() — ключовий декоратор: він ПОЗНАЧАЄ клас як такий,
// що МОЖЕ БУТИ "ВПРОВАДЖЕНИЙ" (injected) в ІНШІ класи через
// dependency injection (детально — розділ 3 нижче).


// 2.3. MODULE (модуль) — ОБ'ЄДНУЄ ПОВ'ЯЗАНІ КОНТРОЛЕРИ Й СЕРВІСИ
// -----------------------------------------------------
// Модуль — це "КОНТЕЙНЕР", що ГРУПУЄ разом контролери, сервіси й
// інші модулі, ПОВ'ЯЗАНІ ЛОГІЧНО (наприклад, усе про "users" — в
// одному UsersModule). Кожен Nest-застосунок МАЄ ХОЧА Б ОДИН
// кореневий модуль (типово AppModule), і МОЖЕ мати БАГАТО дочірніх,
// "фіче-орієнтованих" модулів:
//
//   @Module({
//     controllers: [UsersController],
//     providers: [UsersService],
//     exports: [UsersService], // робить UsersService доступним ІНШИМ модулям
//   })
//   export class UsersModule {}
//
//   @Module({
//     imports: [UsersModule, ProductsModule], // "збирає" фіче-модулі разом
//   })
//   export class AppModule {}
//
// ЦЯ МОДУЛЬНА СТРУКТУРА — ГОЛОВНА ВІДМІННІСТЬ від "плоского" Express-
// застосунку: замість одного великого файлу з роутами (чи довільної
// саморобної структури папок) Nest ЗМУШУЄ явно ОГОЛОШУВАТИ, ЩО з
// чим пов'язане і ЩО ЕКСПОРТУЄТЬСЯ назовні модуля.


// ==========================================================================
// 3. DEPENDENCY INJECTION (DI) — СЕРЦЕ АРХІТЕКТУРИ NEST
// ==========================================================================

// Dependency Injection — це патерн, де КЛАС НЕ СТВОРЮЄ САМ ті
// об'єкти, від яких залежить (наприклад, UsersController НЕ робить
// `new UsersService()` вручну всередині себе) — ЗАМІСТЬ ЦЬОГО
// потрібна залежність ПЕРЕДАЄТЬСЯ ЗЗОВНІ, найчастіше через
// КОНСТРУКТОР, а САМ Nest (точніше, його DI-контейнер) відповідає
// за те, ЩОБ СТВОРИТИ й "підставити" ПРАВИЛЬНИЙ екземпляр:
//
//   @Controller("users")
//   export class UsersController {
//     constructor(private readonly usersService: UsersService) {}
//     //           ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
//     //           Nest САМ бачить, що потрібен UsersService,
//     //           САМ створює (чи перевикористовує) його екземпляр,
//     //           і САМ передає його сюди — БЕЗ жодного `new` у коді контролера
//
//     @Get()
//     findAll() {
//       return this.usersService.findAll(); // просто делегуємо роботу сервісу
//     }
//   }
//
// ЧОМУ ЦЕ ВАЖЛИВО:
//   - ТЕСТУВАННЯ: у юніт-тесті МОЖНА підставити "фейковий" UsersService
//     (мок) замість реального, НЕ ЗМІНЮЮЧИ код контролера;
//   - ПЕРЕВИКОРИСТАННЯ: якщо кілька контролерів потребують ОДИН і
//     той самий UsersService, Nest, ЗА ЗАМОВЧУВАННЯМ, створює
//     ОДИН СПІЛЬНИЙ екземпляр (singleton) на весь застосунок —
//     жодних дублювань стану;
//   - СЛАБКЕ ЗВ'ЯЗУВАННЯ (loose coupling): контролер ЗНАЄ ЛИШЕ ПРО
//     ІНТЕРФЕЙС сервісу (публічні методи), а НЕ про те, ЯК САМЕ той
//     реалізований усередині.
//
// ЦЕЙ САМИЙ ПРИНЦИП — узагальнена версія "ін'єкції залежностей", що
// ти вже бачив у ЧИСТОМУ JS через ЗВИЧАЙНІ функції вищого порядку чи
// параметри конструктора (наприклад, функції в common/asynchronous/asynchronous.js,
// що приймають callback ЗЗОВНІ, а не викликають щось "заховане"
// всередині) — Nest ЛИШЕ АВТОМАТИЗУЄ ЦЕЙ ПАТЕРН і РОБИТЬ ЙОГО
// ЦЕНТРАЛЬНИМ принципом усієї архітектури.


// ==========================================================================
// 4. ЯК ДЕКОРАТОРИ "ОПИСУЮТЬ" КЛАС, А NEST "ЧИТАЄ" ЦІ ОПИСИ
// ==========================================================================

// Декоратори (@Controller, @Injectable, @Module, @Get, @Post тощо) —
// ЦЕ TypeScript/ECMAScript-конструкція, що ДОДАЄ МЕТАДАНІ до класу
// чи методу, БЕЗ ЗМІНИ того, ЯК ЦЕЙ клас/метод "виглядає" з точки
// зору звичайного коду. Nest, під час СТАРТУ застосунку, СКАНУЄ ЦІ
// метадані (через бібліотеку reflect-metadata) і БУДУЄ НА ЇХ ОСНОВІ:
//   - ГРАФ ЗАЛЕЖНОСТЕЙ (хто від кого залежить — для DI);
//   - ТАБЛИЦЮ МАРШРУТІВ (який метод контролера відповідає, якому
//     HTTP-методу + URL);
//   - ПОРЯДОК виконання middleware/guards/interceptors/pipes
//     (детально — окремі файли, це вже "процес обробки запиту").
//
// Це ПРИНЦИПОВО ІНШИЙ підхід, ніж в Express, де МАРШРУТИ РЕЄСТРУЮТЬСЯ
// ІМПЕРАТИВНО (app.get("/users", handler) виконується як ЗВИЧАЙНИЙ
// рядок JS-коду) — у Nest маршрути ДЕКЛАРУЮТЬСЯ ЧЕРЕЗ МЕТАДАНІ, а
// САМ Nest "збирає" їх воєдино на етапі старту (bootstrap).


// ==========================================================================
// 5. ЖИТТЄВИЙ ЦИКЛ ЗАПИТУ (СПРОЩЕНО) — ЩО ВІДБУВАЄТЬСЯ МІЖ HTTP-ЗАПИТОМ І ВІДПОВІДДЮ
// ==========================================================================

// Запит, що прилітає в Nest-застосунок, проходить ЧЕРЕЗ КІЛЬКА
// ПОСЛІДОВНИХ ШАРІВ (кожен — окрема, детально розглянута в майбутніх
// файлах тема):
//
//   1) Middleware       — виконується ПЕРШИМ, ще ДО того, як Nest
//                          "знає", який саме controller/handler
//                          обслуговуватиме запит (аналог Express middleware)
//   2) Guards            — вирішують, чи ДОЗВОЛЕНО взагалі виконати
//                          цей handler (авторизація/аутентифікація)
//   3) Interceptors (before) — можуть ТРАНСФОРМУВАТИ запит ДО обробки
//   4) Pipes              — ВАЛІДУЮТЬ і ТРАНСФОРМУЮТЬ вхідні дані
//                          (наприклад, @Body() dto: CreateUserDto —
//                          саме pipe перевіряє, що dto відповідає формі)
//   5) Controller handler — власне МЕТОД контролера виконується,
//                          звертається до Service
//   6) Interceptors (after) — можуть ТРАНСФОРМУВАТИ РЕЗУЛЬТАТ ПІСЛЯ обробки
//   7) Exception filters  — ЛОВЛЯТЬ помилки, що виникли на БУДЬ-ЯКОМУ
//                          з попередніх кроків, і формують ЄДИНИЙ
//                          формат відповіді про помилку
//
// САМЕ ЦЕЙ КОНВЕЄР (pipeline) і є "магією" Nest — замість того, щоб
// РУЧНО писати перевірку авторизації/валідації В КОЖНОМУ роуті (як
// часто буває в "сирому" Express), ці наскрізні задачі ВИНОСЯТЬСЯ В
// ОКРЕМІ, ПЕРЕВИКОРИСТОВУВАНІ КЛАСИ й ПРОСТО "НАВІШУЮТЬСЯ" на
// потрібні контролери/методи ЧЕРЕЗ ДЕКОРАТОРИ.


// ==========================================================================
// 6. ТИПОВА СТРУКТУРА ФАЙЛІВ NEST-ПРОЄКТУ
// ==========================================================================

//   src/
//     main.ts                 — точка входу, "bootstrap" застосунку
//     app.module.ts            — кореневий модуль
//     app.controller.ts        — кореневий контролер (часто /health чи /)
//     app.service.ts           — кореневий сервіс
//     users/
//       users.module.ts        — фіче-модуль
//       users.controller.ts    — маршрути /users
//       users.service.ts       — бізнес-логіка users
//       dto/
//         create-user.dto.ts   — форма даних для ВХІДНОГО запиту (Data Transfer Object)
//       entities/
//         user.entity.ts       — форма даних, як вона ЗБЕРІГАЄТЬСЯ (напр., в БД)
//
// НАЙМЕНУВАННЯ ФАЙЛІВ ЗА КОНВЕНЦІЄЮ (.controller.ts, .service.ts,
// .module.ts, .dto.ts) — це НЕ ВИМОГА компілятора, а СТАЛА
// СПІЛЬНОТНА УГОДА, яку офіційний Nest CLI ДОТРИМУЄТЬСЯ автоматично
// при генерації файлів (детально CLI — окремим пунктом нижче).


// ==========================================================================
// 7. BOOTSTRAP — ЯК ЗАСТОСУНОК РЕАЛЬНО СТАРТУЄ (main.ts)
// ==========================================================================

// Мінімальний приклад точки входу (псевдокод, потребує встановленого
// @nestjs/core та @nestjs/common — тут наведено для розуміння форми,
// а не для копіювання без контексту реального проєкту):
//
//   import { NestFactory } from "@nestjs/core";
//   import { AppModule } from "./app.module";
//
//   async function bootstrap() {
//     const app = await NestFactory.create(AppModule); // будує ВЕСЬ граф
//                                                          // модулів/сервісів/контролерів
//                                                          // з AppModule як кореня
//     await app.listen(3000); // під капотом — app.listen() ТОГО САМОГО
//                                 Express-застосунку, який Nest створив і налаштував
//   }
//   bootstrap();
//
// NestFactory.create(AppModule) — це МОМЕНТ, коли Nest РЕАЛЬНО
// "СКАНУЄ" ВЕСЬ дерево imports/controllers/providers, ПОЧИНАЮЧИ з
// AppModule, будує DI-контейнер і РЕЄСТРУЄ всі маршрути в
// Express (чи Fastify) — усе, розглянуте в розділах 2-5, "оживає"
// саме на цьому кроці.


// ==========================================================================
// 8. NEST VS "ГОЛИЙ" EXPRESS — КОЛИ ЩО ОБИРАТИ
// ==========================================================================

// | Критерій                          | Express                              | NestJS                                  |
// |----------------------------------------|------------------------------------------|-----------------------------------------------|
// | Структура проєкту                     | НЕ нав'язується, повна свобода          | ЧІТКА, архітектурно визначена (модулі/DI)   |
// | Крива навчання                        | НИЗЬКА, мінімалізм                       | ВИЩА — потрібно зрозуміти DI, декоратори     |
// | TypeScript                             | опціонально, "приклеюється" зверху       | "рідний" для TS, декоратори — TS-фіча        |
// | Масштабованість ВЕЛИКОЇ команди/проєкту| потребує РУЧНОЇ дисципліни                | архітектура ДОПОМАГАЄ тримати порядок        |
// | Швидкість написання МАЛЕНЬКОГО API    | дуже швидко, мінімум коду                | більше "boilerplate" для простих випадків    |
// | Тестованість                           | залежить від того, як сам організував код | DI РОБИТЬ мокати залежності природно ЛЕГКО  |
// | Під капотом                            | сам є HTTP-сервером                       | ЗАЗВИЧАЙ ВИКОРИСТОВУЄ Express/Fastify ВСЕРЕДИНІ |
//
// ЗАГАЛЬНЕ ПРАВИЛО: маленький сервіс/прототип/мікросервіс з
// кількома ендпоінтами — часто простіше й швидше на "голому"
// Express; ВЕЛИКИЙ backend із багатьма командами, довгостроковою
// підтримкою і складною бізнес-логікою — там, де Nest's архітектурна
// дисципліна окупається З ЧАСОМ.


// ==========================================================================
// 9. NEST CLI — ІНСТРУМЕНТ ДЛЯ ГЕНЕРАЦІЇ СТРУКТУРИ
// ==========================================================================

// Офіційний CLI (`@nestjs/cli`, команда `nest`) автоматизує
// СТВОРЕННЯ файлів ЗА СТАНДАРТНОЮ структурою й конвенцією іменування
// з розділу 6:
//
//   nest new my-project           # створює НОВИЙ застосунок з нуля
//   nest generate module users    # (nest g module users) — новий фіче-модуль
//   nest generate controller users
//   nest generate service users
//
// Це ТОЙ САМИЙ принцип, що й Angular CLI (звідки й запозичений сам
// підхід) — CLI одразу СТВОРЮЄ ФАЙЛ, ПРАВИЛЬНО ІМЕНОВАНИЙ, З
// ПОТРІБНИМИ декораторами, і АВТОМАТИЧНО ДОДАЄ його в масив
// controllers/providers відповідного @Module().


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - NestJS — TypeScript-first backend-фреймворк, побудований НАД
//   Express (чи Fastify) — НЕ заміна їм, а АРХІТЕКТУРНА НАДБУДОВА
// - запозичує ідеї з Angular: модулі, декоратори, dependency injection
// - три базові будівельні блоки: Controller (маршрутизація) →
//   Service/Provider (бізнес-логіка) → Module (групує їх разом)
// - Dependency Injection — Nest САМ створює й "підставляє" залежності
//   через конструктор, замість ручного `new` усередині класу; це
//   дає легке тестування, спільні (singleton) екземпляри сервісів,
//   слабке зв'язування компонентів
// - декоратори (@Controller, @Injectable, @Module, @Get...) — ЦЕ
//   МЕТАДАНІ, які Nest СКАНУЄ на старті застосунку, щоб побудувати
//   граф залежностей і таблицю маршрутів — на відміну від Express,
//   де маршрути реєструються ІМПЕРАТИВНО, рядок за рядком
