// ПІДСУМОК:
// - бітові оператори (& | ^ ~ << >> >>>) працюють з 32-бітними ЦІЛИМИ
//   ЗІ ЗНАКОМ: число спершу перетворюється (ToInt32) — дробова частина
//   відкидається, старші біти понад 32 втрачаються, NaN/Infinity → 0
// - від'ємні числа зберігаються в ДОВНЯЛЬНОМУ КОДІ (two's complement):
//   -n === ~n + 1, тому ~n === -(n + 1); 31-й біт — знаковий
// - & — маскування, перевірка бітів, остача від ділення на 2ⁿ;
//   | — встановлення бітів і пакування; ^ — перемикання та XOR-трюки
//   (a ^ a = 0, a ^ b ^ b = a); ~ — інверсія, маски "усе, крім"
// - << множить на 2ⁿ, >> ділить на 2ⁿ зі збереженням знаку (округлює
//   вниз до −∞), >>> заповнює нулями і дає беззнакове число
//   (x >>> 0 — спосіб отримати uint32)
// - кількість зсуву береться за модулем 32: 1 << 32 === 1
// - прапорці: (1 << n) для кожного біта; додати |=, прибрати &= ~,
//   перемкнути ^=, перевірити (x & f) === f
// - для 64+ бітів і точності — BigInt (без >>>, без змішування з
//   Number), BigInt.asUintN/asIntN обмежують розрядність
// - корисне: n & (n - 1) (степінь двійки, popcount), n & -n (молодший
//   біт), Math.clz32 (старший біт), Math.imul (коректне 32-бітне
//   множення для хешів), Uint32Array як BitSet
// - ПАСТКИ: пріоритет операторів (завжди ставте дужки), відсікання
//   дробової частини тільки в межах int32 (для великих — Math.trunc),
//   плутанина & з &&, значення > 2³¹ стають від'ємними
// - зсуви замість ділення/множення "для швидкості" сьогодні майже
//   не мають сенсу — використовуйте біти там, де вони природні:
//   прапорці, бінарні формати, хеші, маски
