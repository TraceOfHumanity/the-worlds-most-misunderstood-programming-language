// 12.1. Степінь двійки?
const isPowerOfTwo = (n) => n > 0 && (n & (n - 1)) === 0;
console.log(isPowerOfTwo(16), isPowerOfTwo(18), isPowerOfTwo(1)); // true false true
// n - 1 інвертує молодші біти до першої одиниці: 1000 & 0111 = 0

// 12.2. Підрахунок одиничних бітів (popcount) — алгоритм Кернігана
function popcount(n) {
  let count = 0;
  while (n) {
    n &= n - 1; // прибирає найправішу одиницю
    count++;
  }
  return count;
}
console.log(popcount(0b1011_0110)); // 5
console.log(popcount(255)); // 8

// 12.3. Найправіший встановлений біт (lowest set bit)
const lowestBit = (n) => n & -n;
console.log(lowestBit(0b101000)); // 8 (1000)

// 12.4. Позиція найстаршого біта через Math.clz32 (count leading zeros)
console.log(Math.clz32(1)); // 31
console.log(Math.clz32(0b1000)); // 28
const highestBitIndex = (n) => 31 - Math.clz32(n);
console.log(highestBitIndex(0b1000)); // 3
console.log(Math.clz32(0)); // 32
// (Math — common/math.js: clz32, imul, fround)

// 12.5. Math.imul — коректне 32-бітне множення
console.log(Math.imul(0xffffffff, 5)); // -5 — як у C з int32 (-1 * 5)
// Звичайне (a * b) | 0 для великих чисел дає НЕПРАВИЛЬНІ молодші біти:
// добуток перевищує 2⁵³, double його округлює ДО зведення до int32.
const bigA = 0xdeadbeef;
const bigB = 0xcafebabd;
console.log((bigA * bigB) | 0); // -1440636928 — втрачена точність
console.log(Math.imul(bigA, bigB)); // -1440637837 — правильні молодші 32 біти
// imul гарантує точний результат mod 2³², тому хеші (FNV, murmur)
// пишуть саме з Math.imul.

// 12.6. Простий хеш рядка (FNV-1a, 32 біти)
function fnv1a(str) {
  let hash = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    hash ^= str.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0; // у беззнакове
}
console.log(fnv1a("hello").toString(16)); // 4f9f2cab

// 12.7. Генератор псевдовипадкових чисел xorshift32
function xorshift32(seed) {
  let s = seed | 0;
  return () => {
    s ^= s << 13;
    s ^= s >>> 17;
    s ^= s << 5;
    return (s >>> 0) / 2 ** 32; // число в [0, 1)
  };
}
const rand = xorshift32(2463534242);
console.log(rand() === xorshift32(2463534242)()); // true — детермінований за seed
// (Math.random не можна "засіяти"; для відтворюваних тестів такі
// генератори корисні.)


// ==========================================================================
// 13. BITSET: МНОЖИНА ЧИСЕЛ У МАСИВІ БІТІВ
// ==========================================================================

// Uint32Array (common/data-structures/Array/TypedArray.js) як компактний
// масив бітів: 1 біт на елемент замість Set/Boolean[] (у 8–64 рази менше).

class BitSet {
  #words;
  constructor(size) {
    this.#words = new Uint32Array(Math.ceil(size / 32));
  }
  add(i) {
    this.#words[i >>> 5] |= 1 << (i & 31); // i >>> 5 = ⌊i/32⌋, i & 31 = i % 32
  }
  delete(i) {
    this.#words[i >>> 5] &= ~(1 << (i & 31));
  }
  has(i) {
    return (this.#words[i >>> 5] & (1 << (i & 31))) !== 0;
  }
  get count() {
    let total = 0;
    for (const w of this.#words) total += popcount(w | 0);
    return total;
  }
}

const bits = new BitSet(100);
