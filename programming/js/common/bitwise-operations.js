// ==========================================================================
// 9. ЗСУВИ: <<, >>, >>>
// ==========================================================================

// 9.1. Зсув вліво (<<): множення на 2ⁿ
console.log(3 << 1); // 6
console.log(3 << 2); // 12
console.log(1 << 10); // 1024
console.log(bin32(1 << 31)); // 10000000_00000000_00000000_00000000
console.log(1 << 31); // -2147483648 — потрапило в знаковий біт!
console.log(1 << 32); // 1 — кількість зсуву береться за модулем 32 (32 % 32 = 0)
console.log(1 << 33); // 2 — 33 % 32 = 1

// 9.2. Арифметичний зсув вправо (>>): ділення на 2ⁿ з округленням вниз,
// знак зберігається (старші біти заповнюються знаковим бітом)
console.log(20 >> 2); // 5
console.log(7 >> 1); // 3 — дробова частина відкинута
console.log(-20 >> 2); // -5
console.log(-7 >> 1); // -4 — округлення вниз (до −∞), а не до нуля!
console.log(bin32(-8)); // 11111111_11111111_11111111_11111000
console.log(bin32(-8 >> 1)); // 11111111_11111111_11111111_11111100 — старший біт 1 залишився

// 9.3. Логічний зсув вправо (>>>): заповнює нулями, результат БЕЗ ЗНАКУ
console.log(-8 >>> 1); // 2147483644
console.log(bin32(-8 >>> 1)); // 01111111_11111111_11111111_11111100
console.log(-1 >>> 0); // 4294967295 — спосіб отримати uint32
console.log(-1 >>> 31); // 1 — витягнути лише знаковий біт
console.log(5 >>> 0); // 5

// >>> 0 — стандартний спосіб перетворити на БЕЗЗНАКОВЕ 32-бітне число:
console.log((-1 >>> 0).toString(16)); // ffffffff
console.log(0xffffffff | 0); // -1 — знову знакове

// 9.4. Швидке ділення/множення — чи варто?
// Раніше `n >> 1` замість `n / 2 | 0` вважали оптимізацією. Сучасні
// рушії (V8) оптимізують і ділення, тож вигода мізерна, а читабельність
// гірша. Використовуйте зсуви, коли працюєте з БІТАМИ, а не для
