// ==========================================================================
// BITWISE OPERATIONS — БІТОВІ ОПЕРАЦІЇ В JAVASCRIPT ДЕТАЛЬНО
// ==========================================================================

// 1. ЩО ТАКЕ БІТОВІ ОПЕРАЦІЇ ТА НАВІЩО ВОНИ
// -----------------------------------------------------
// Бітові (bitwise) операції працюють з окремими БІТАМИ числа (0 і 1),
// а не з числом як цілим. Навіщо вони потрібні:
//   - ПРАПОРЦІ (flags): десятки булевих значень в одному числі
//     (права доступу, налаштування, стани);
//   - ШВИДКІ ОБЧИСЛЕННЯ: ділення/множення на степені двійки,
//     перевірка парності, цілочисельне відсікання;
//   - БІНАРНІ ДАНІ: протоколи, файлові формати, кольори RGBA, хеші,
//     криптографія, Buffer/TypedArray (node/core-concepts/buffers/index.js,
//     common/data-structures/Array/TypedArray.js);
//   - КОМПАКТНІ СТРУКТУРИ: bitset, маски, Bloom-фільтри;
//   - алгоритмічні задачі (XOR-трюки, підрахунок бітів).
//
// Оператори:
//   &   AND        1, лише якщо ОБИДВА біти 1
//   |   OR         1, якщо ХОЧА Б ОДИН біт 1
//   ^   XOR        1, якщо біти РІЗНІ
//   ~   NOT        інверсія всіх бітів
//   <<  зсув вліво (множення на 2ⁿ)
//   >>  зсув вправо ЗІ ЗБЕРЕЖЕННЯМ ЗНАКУ (арифметичний)
//   >>> зсув вправо БЕЗ ЗНАКУ (логічний, заповнює нулями)


// ==========================================================================
// 2. ЯК JS ПРЕДСТАВЛЯЄ ЧИСЛА — ГОЛОВНА ПАСТКА
// ==========================================================================

// Усі звичайні числа в JS — 64-бітні дробові (double, IEEE 754;
// common/math.js). Але бітові оператори працюють НЕ з ними, а так:
//   1) число перетворюється на 32-бітне ЦІЛЕ зі знаком (ToInt32);
//   2) операція виконується над цими 32 бітами;
//   3) результат — знову звичайне число (ціле зі знаком, 32 біти).
//
// Наслідки:
//   - працюємо лише з діапазоном −2 147 483 648 … 2 147 483 647;
//   - дробова частина ВІДКИДАЄТЬСЯ;
//   - старші біти великих чисел ВТРАЧАЮТЬСЯ;
//   - для 64-бітних значень потрібен BigInt (розділ 11).

console.log(5.9 | 0); // 5 — дробову частину відкинуто
console.log(-5.9 | 0); // -5 — відсікання до нуля (не floor!)
console.log(2 ** 32 | 0); // 0 — 2³² не вмістилось у 32 біти
console.log((2 ** 32 + 5) | 0); // 5 — старші біти втрачено
console.log(2 ** 31 | 0); // -2147483648 — старший біт став знаковим
console.log("7" | 0); // 7 — рядок спершу приводиться до числа
console.log(NaN | 0); // 0
console.log(undefined | 0); // 0
console.log(Infinity | 0); // 0
// (правила приведення — common/type-coercion.js)


// ==========================================================================
// 3. ЗАПИС ЧИСЕЛ У ДВІЙКОВІЙ СИСТЕМІ
// ==========================================================================

// 3.1. Літерали
console.log(0b1010); // 10 — двійковий літерал
console.log(0o17); // 15 — вісімковий
console.log(0xff); // 255 — шістнадцятковий
console.log(0b1111_0000); // 240 — роздільники _ для читабельності

// 3.2. Число → рядок у системі числення
console.log((10).toString(2)); // "1010"
console.log((255).toString(16)); // "ff"
console.log((255).toString(8)); // "377"

// 3.3. Рядок → число
console.log(parseInt("1010", 2)); // 10
