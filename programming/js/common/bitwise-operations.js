// 10. БІТОВІ ПРАПОРЦІ (FLAGS) — НАЙПОШИРЕНІШЕ ЗАСТОСУВАННЯ
// ==========================================================================

// Кожен прапорець — окремий біт. Один Number зберігає до 31 (безпечних)
// булевих значень. Так влаштовані права файлів Unix (fs.constants,
// node/core-concepts/file-system/), опції regex, стани в ядрі.

const READ = 1 << 0; // 0001
const WRITE = 1 << 1; // 0010
const EXECUTE = 1 << 2; // 0100
const ADMIN = 1 << 3; // 1000

let permissions = READ | WRITE; // видати два права
console.log(b8(permissions)); // 00000011

// Перевірка наявності
const has = (perms, flag) => (perms & flag) === flag;
console.log(has(permissions, READ)); // true
console.log(has(permissions, EXECUTE)); // false

// Додати
permissions |= EXECUTE;
console.log(b8(permissions)); // 00000111

// Прибрати
permissions &= ~WRITE;
console.log(b8(permissions)); // 00000101

// Перемкнути
permissions ^= ADMIN;
console.log(b8(permissions)); // 00001101

// Перевірка "хоч одне з"
console.log((permissions & (READ | WRITE)) !== 0); // true — є READ

// Перевірка "всі з" — тільки через (x & mask) === mask, а не просто (x & mask)
console.log(Boolean(permissions & (READ | WRITE))); // true — ⚠️ але WRITE немає!
console.log(has(permissions, READ | WRITE)); // false — правильна перевірка

// Приклад з fs: прапорці файлових режимів
const fs = require("node:fs");
const mode = fs.constants.S_IRUSR | fs.constants.S_IWUSR; // читання+запис власником
console.log(mode.toString(8)); // 600 — знайомий chmod 600

// Приклад з RegExp: прапорці, що поєднуються
console.log(/a/gi.flags); // "gi"

// Зручніше через enum-подібний об'єкт (TypeScript: typescript/enums.ts —
// flags-enums з `1 << n` — стандартна практика):
const Perm = Object.freeze({ READ: 1, WRITE: 2, EXECUTE: 4 });
const describe = (p) =>
  Object.entries(Perm)
    .filter(([, bit]) => p & bit)
    .map(([name]) => name)
    .join("|") || "NONE";
console.log(describe(Perm.READ | Perm.EXECUTE)); // READ|EXECUTE
console.log(describe(0)); // NONE


