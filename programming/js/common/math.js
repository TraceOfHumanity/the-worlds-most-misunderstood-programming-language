// 6. ВИПАДКОВІ ЧИСЛА: Math.random()
// ==========================================================================

// Math.random() — ЄДИНИЙ метод Math, що НЕ Є чистою функцією: щоразу
// повертає ІНШЕ псевдовипадкове число з ПІВВІДКРИТОГО діапазону
// [0, 1) — 0 включно, 1 НІКОЛИ не включається.
console.log(Math.random()); // наприклад, 0.7834521...

// НАЙПОШИРЕНІШИЙ ПАТЕРН: випадкове ЦІЛЕ число в діапазоні [min, max]
// (включно з обома кінцями):
function randomInt(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}
console.log(randomInt(1, 6)); // "кидок кубика" — ціле число від 1 до 6

// ЧОМУ САМЕ floor(), а не round(): round() дав би НЕРІВНОМІРНИЙ
// розподіл — межові значення (min і max) випадали б приблизно ВДВІЧІ
// РІДШЕ за середні, бо для них "влучає" лише половина інтервалу
// округлення, а не ціла.

// Math.random() НЕ придатний для криптографії/безпеки — для цього
// існує спеціальний API crypto.getRandomValues() (поза Math).


