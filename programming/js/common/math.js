// Math — це НЕ конструктор і НЕ клас: це ЗВИЧАЙНИЙ, ГОТОВИЙ ОБ'ЄКТ
// (singleton), який існує в глобальному просторі одразу. У нього
// НЕМАЄ конструктора — new Math() кине TypeError. Усі методи —
// СТАТИЧНІ (викликаються напряму через Math.method(), а не через
// екземпляр), і всі вони — ЧИСТІ ФУНКЦІЇ (крім Math.random()) —
// не мають стану і не залежать ні від чого, окрім своїх аргументів.

console.log(typeof Math); // "object"
