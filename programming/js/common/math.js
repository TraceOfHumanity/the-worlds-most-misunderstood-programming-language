// Math.clz32(x) — CouLeading Zero: кількість НУЛІВ на початку 32-бітного
// (беззнакового) представлення числа:
console.log(Math.clz32(1));          // 31 — 1 у 32-біт: 00000000000000000000000000000001
console.log(Math.clz32(0));          // 32 — усі 32 біти нульові
console.log(Math.clz32(2147483648)); // 0  — старший біт уже одиниця, нулів немає
// Використовується у низькорівневих оптимізаціях (наприклад, швидке
// обчислення log2 для цілих степенів двійки).

// Math.imul(a, b) — 32-бітне ЦІЛОЧИСЕЛЬНЕ множення (як у C/Java int*int),
// з КОРЕКТНИМ переповненням (overflow), на відміну від звичайного *,
// який працює через double і втрачає точність на дуже великих числах:
console.log(Math.imul(2, 3));                 // 6 — для малих чисел як звичайне *
console.log(Math.imul(0xffffffff, 5));        // -5 — коректне 32-бітне переповнення
console.log(0xffffffff * 5);                   // 21474836475 — звичайне * тут НЕ переповнюється,
                                                  // бо working через double, інший результат

// Math.fround(x) — округлює число до найближчого 32-бітного
// float-значення (замість "рідного" для JS 64-бітного double):
console.log(Math.fround(1.5));            // 1.5   — точно представляється й у 32-бітах
console.log(Math.fround(1.1));            // 1.100000023841858 — втрата точності через 32-біт округлення
console.log(Math.fround(1.1) === 1.1);    // false — видно різницю
// Застосовується при роботі з Float32Array — щоб проміжні обчислення
// відповідали точності, яку РЕАЛЬНО матиме значення після запису
// в 32-бітний типізований масив.


// ==========================================================================
// 11. ЧОМУ Math НЕ ЗАВЖДИ ДАЄ "МАТЕМАТИЧНО ІДЕАЛЬНИЙ" РЕЗУЛЬТАТ
// ==========================================================================

// Усі числа в JS — це IEEE 754 double (64-біт число з плаваючою
// комою) — і Math просто ОПЕРУЄ цим самим представленням. Звідси —
// класичні "неточності", що НЕ є багом самого Math, а властивістю
// представлення дробових чисел узагалі:

console.log(0.1 + 0.2);              // 0.30000000000000004 — класична пастка
console.log(Math.abs(0.1 + 0.2 - 0.3) < Number.EPSILON); // true — правильний спосіб
                                                             // порівнювати дробові числа "з допуском"

// Number.EPSILON — НАЙМЕНША різниця між 1 і наступним представленим
// числом з плаваючою комою — стандартний "допуск" для порівняння:
console.log(Number.EPSILON); // 2.220446049250313e-16


// ==========================================================================
// 12. НАЙЧАСТІШІ ПРАКТИЧНІ ПАТЕРНИ
// ==========================================================================

// а) обмеження значення в межах діапазону (clamp) — теж часто через
// Math.min/Math.max разом (детально розглянуто з погляду branch
// prediction в performance/08-branch-prediction.js):
function clamp(value, min, max) {
  return Math.min(Math.max(value, min), max);
}
console.log(clamp(150, 0, 100)); // 100
console.log(clamp(-10, 0, 100)); // 0
console.log(clamp(50, 0, 100));  // 50

// б) округлення числа до N знаків після коми (БЕЗ рядкового toFixed,
// повертає саме ЧИСЛО, а не рядок):
function roundTo(value, decimals) {
  const factor = 10 ** decimals;
  return Math.round(value * factor) / factor;
}
console.log(roundTo(3.14159, 2)); // 3.14 (число, не рядок)

// в) сума/середнє масиву чисел (Math тут дає лише max/min/hypot;
// саму суму рахують через reduce, Math у цьому не бере участі
// напряму — наведено для контрасту з тим, чого Math НЕ вміє):
const values = [4, 8, 15, 16, 23, 42];
const sum = values.reduce((acc, n) => acc + n, 0);
const average = sum / values.length;
console.log(sum, average.toFixed(2));

// г) відстань між двома точками на площині — типове застосування hypot():
function distance(x1, y1, x2, y2) {
  return Math.hypot(x2 - x1, y2 - y1);
}
console.log(distance(0, 0, 3, 4)); // 5


// ПІДСУМОК:
// - Math — готовий, статичний об'єкт-набір утиліт, НЕ конструктор;
//   усі методи, крім random(), — чисті функції
// - константи (PI, E, LN2...) — властивості, не методи, і незмінні
// - round/floor/ceil/trunc — ЧОТИРИ РІЗНІ стратегії округлення,
//   що дають РІЗНІ результати саме на від'ємних числах
// - pow()/** — степінь; sqrt()/cbrt() — корені (cbrt працює й для
//   від'ємних, sqrt — ні); hypot() — довжина гіпотенузи/вектора
// - max()/min() приймають аргументи через кому (не масив — потрібен
//   spread), без аргументів дають -Infinity/Infinity відповідно
// - random() — єдиний нечистий метод, повертає [0, 1); для цілого
//   діапазону — floor(random() * (max - min + 1)) + min
// - усі тригонометричні функції працюють у РАДІАНАХ, не в градусах;
//   atan2(y, x) правильно враховує чверть координатної площини,
//   на відміну від atan(y / x)
// - clz32/imul/fround — низькорівневі бітові утиліти для точної
//   32-бітної арифметики (рідко потрібні поза спеціалізованим кодом)
// - Math працює з тим самим IEEE 754 double, що й усі числа в JS —
//   звідси й класичні неточності (0.1 + 0.2 !== 0.3); для порівняння
//   дробових чисел використовуй допуск через Number.EPSILON