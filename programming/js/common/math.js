// ==========================================================================
// 2. КОНСТАНТИ Math — ГОТОВІ ЧИСЛОВІ ЗНАЧЕННЯ
// ==========================================================================

console.log(Math.PI);      // 3.141592653589793 — довжина півкола одиничного радіуса
console.log(Math.E);       // 2.718281828459045 — основа натурального логарифма
console.log(Math.LN2);     // 0.6931471805599453 — натуральний логарифм від 2
console.log(Math.LN10);    // 2.302585092994046  — натуральний логарифм від 10
console.log(Math.LOG2E);   // 1.4426950408889634 — логарифм від E за основою 2
console.log(Math.LOG10E);  // 0.4342944819032518 — логарифм від E за основою 10
console.log(Math.SQRT2);   // 1.4142135623730951 — квадратний корінь з 2
console.log(Math.SQRT1_2); // 0.7071067811865476 — квадратний корінь з 1/2

// Усі константи Math — це ВЛАСТИВОСТІ, а не методи (звертання БЕЗ дужок).
// Вони non-writable, non-enumerable, non-configurable — спробувати
// змінити Math.PI просто мовчки НЕ спрацює (у нестрогому режимі):
Math.PI = 3;
console.log(Math.PI); // 3.141592653589793 — значення незмінне

// Для округленого відображення числа використовують toFixed()
// (метод Number, не Math — детально нижче, у розділі "округлення"):
console.log(Math.PI.toFixed(2)); // "3.14" — повертає РЯДОК, не число!


// ==========================================================================
// 3. ОКРУГЛЕННЯ: round / floor / ceil / trunc — ЧОТИРИ РІЗНІ СТРАТЕГІЇ
// ==========================================================================

// Math.round(x) — округлення до НАЙБЛИЖЧОГО цілого (за стандартними
// правилами "округлення половини вгору" — .5 ЗАВЖДИ йде до +Infinity,
// це ВАЖЛИВО для від'ємних чисел):
console.log(Math.round(3.5));  // 4
console.log(Math.round(3.4));  // 3
console.log(Math.round(-3.5)); // -3 !!! — округлення "половини ВГОРУ", а не "від нуля"
console.log(Math.round(-3.6)); // -4

// Math.floor(x) — округлення "ВНИЗ" (до -Infinity), незалежно від знаку:
console.log(Math.floor(3.9));  // 3
console.log(Math.floor(-3.1)); // -4 — "вниз" означає "менше", а не "ближче до нуля"

// Math.ceil(x) — округлення "ВГОРУ" (до +Infinity):
console.log(Math.ceil(3.1));  // 4
console.log(Math.ceil(-3.9)); // -3

// Math.trunc(x) (ES6) — просто ВІДКИДАЄ дробову частину, БЕЗ округлення:
console.log(Math.trunc(3.9));  // 3
console.log(Math.trunc(-3.9)); // -3 — на відміну від floor(), який дав би -4!

// ПОРІВНЯЛЬНА ТАБЛИЦЯ на -3.5 і 3.5:
//   round(3.5)  = 4    round(-3.5)  = -3
//   floor(3.5)  = 3    floor(-3.5)  = -4
//   ceil(3.5)   = 4    ceil(-3.5)   = -3
//   trunc(3.5)  = 3    trunc(-3.5) = -3

// НАЙЧАСТІША ПОМИЛКА: використовувати round() там, де насправді
// потрібен trunc() (наприклад, "просто відкинути дробову частину").
// Для ПОЗИТИВНИХ чисел floor() і trunc() дають однаковий результат,
// але для НЕГАТИВНИХ — ні, тож підміна floor() на trunc() (чи навпаки)
// у коді, що працює з від'ємними числами, — джерело "тихих" багів.


// ==========================================================================
// 4. СТЕПЕНІ ТА КОРЕНІ
// ==========================================================================

console.log(Math.pow(2, 3)); // 8 — 2 в степені 3
console.log(2 ** 3);          // 8 — сучасний оператор **, робить те саме (ES2016)
console.log(Math.pow(2, 0.5)); // 1.4142135623730951 — те саме, що sqrt(2)

console.log(Math.sqrt(16));  // 4   — квадратний корінь (лише для x >= 0, інакше NaN)
console.log(Math.sqrt(-1));  // NaN — від'ємне число немає дійсного кореня
console.log(Math.cbrt(8));   // 2   — кубічний корінь (ПРАЦЮЄ і для від'ємних!)
console.log(Math.cbrt(-8));  // -2  — на відміну від sqrt(), приймає від'ємні числа

// Math.hypot(...values) (ES6) — довжина гіпотенузи / евклідова норма
// вектора: sqrt(a² + b² + c² + ...), але математично СТАБІЛЬНІШЕ за
// ручний запис (уникає переповнення/втрати точності на екстремальних
// значеннях):
console.log(Math.hypot(3, 4));       // 5 — класичний "трикутник 3-4-5"
console.log(Math.hypot(3, 4, 12));   // 13 — працює для БУДЬ-ЯКОЇ кількості вимірів


// ==========================================================================
// 5. МІНІМУМ, МАКСИМУМ, ЗНАК, МОДУЛЬ
// ==========================================================================

console.log(Math.max(1, 2, 3, 4, 5)); // 5
console.log(Math.min(1, 2, 3, 4, 5)); // 1

// Math.max()/Math.min() приймають АРГУМЕНТИ ЧЕРЕЗ КОМУ, а не масив —
// для масиву потрібен spread (...):
const numbersForMinMax = [4, 2, 9, 1, 7];
console.log(Math.max(...numbersForMinMax)); // 9
console.log(Math.min(...numbersForMinMax)); // 1

// БЕЗ АРГУМЕНТІВ — "нейтральні" для подальшого порівняння значення:
console.log(Math.max()); // -Infinity — "програє" будь-якому реальному числу
console.log(Math.min()); // Infinity  — те саме навпаки

// ЯКЩО БУДЬ-ЯКИЙ аргумент не приводиться до числа — результат NaN,
// і ЦЕ "ЗАРАЗУЄ" весь виклик (навіть якщо решта — коректні числа):
console.log(Math.max(1, 2, "text")); // NaN

// Math.sign(x) — повертає ЗНАК числа: -1, 0, -0 чи 1 (або NaN, якщо
// вхід не число):
console.log(Math.sign(-3));  // -1
console.log(Math.sign(3));   // 1
console.log(Math.sign(0));   // 0
console.log(Math.sign(-0));  // -0 — зберігає навіть знак нуля!
console.log(Math.sign("x")); // NaN

// Math.abs(x) — модуль (абсолютне значення), завжди >= 0:
console.log(Math.abs(-3));   // 3
console.log(Math.abs(3));    // 3
console.log(Math.abs("-5")); // 5 — рядок неявно приводиться до числа


