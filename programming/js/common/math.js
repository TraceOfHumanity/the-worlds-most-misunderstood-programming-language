// ==========================================================================
// 8. ТРИГОНОМЕТРІЯ (у РАДІАНАХ, НЕ в градусах!)
// ==========================================================================

// ВАЖЛИВО: усі тригонометричні функції Math працюють з РАДІАНАМИ.
// Якщо є градуси — потрібно самостійно конвертувати: radians = degrees * (Math.PI / 180)

function degreesToRadians(deg) {
  return deg * (Math.PI / 180);
}
function radiansToDegrees(rad) {
  return rad * (180 / Math.PI);
}

console.log(Math.sin(Math.PI / 2)); // 1  — синус 90°
console.log(Math.cos(Math.PI));      // -1 — косинус 180°
console.log(Math.tan(Math.PI / 4));  // 0.9999999999999999 — тангенс 45° (майже 1,
                                        // похибка через представлення чисел з плаваючою комою)

console.log(Math.sin(degreesToRadians(90))); // 1 — той самий результат через явну конвертацію

// ОБЕРНЕНІ тригонометричні функції (arc-функції) повертають РАДІАНИ:
console.log(Math.asin(1));  // 1.5707963267948966 (= π/2)
console.log(Math.acos(-1)); // 3.141592653589793  (= π)
console.log(Math.atan(1));  // 0.7853981633974483 (= π/4)

// Math.atan2(y, x) — ОСОБЛИВО ВАЖЛИВА функція: кут (у радіанах) між
// віссю X та точкою (x, y), З УРАХУВАННЯМ знаків ОБОХ координат —
// на відміну від atan(y/x), правильно визначає ЧВЕРТЬ координатної
// площини (критично для геометрії, ігор, навігації):
console.log(Math.atan2(1, 1));   // 0.7853981633974483  (= π/4, перша чверть)
console.log(Math.atan2(1, -1));  // 2.356194490192345   (третя за atan2, друга чверть)
console.log(Math.atan(1 / -1));  // -0.7853981633974483 — atan() "не бачить" різницю
                                    // чвертей, бо (1/-1) === (-1/1) арифметично


