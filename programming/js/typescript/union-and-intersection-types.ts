// ==========================================================================
// UNION & INTERSECTION TYPES — ОБ'ЄДНАННЯ ТА ПЕРЕТИНИ ТИПІВ
// ==========================================================================

// 0. ЗАГАЛЬНА ІДЕЯ
// -----------------------------------------------------
// Union (`|`) і Intersection (`&`) — два способи КОМБІНУВАТИ типи,
// які вже існують, замість того щоб описувати кожну комбінацію
// заново. Це БЕЗПОСЕРЕДНЄ рішення проблеми, яку в чистому JS
// доводиться тримати "в голові": функція/змінна може приймати
// НАБІР МОЖЛИВИХ форм даних, і TS дозволяє записати ЦЕ САМЕ ЯВНО.
//
//   A | B  → значення Є A АБО B (щось одне з двох)
//   A & B  → значення Є ОДНОЧАСНО і A, і B (усі поля з обох)


// ==========================================================================
// 1. UNION TYPES (`|`) — "ЦЕ АБО ТЕ"
// ==========================================================================

// Union позначає, що значення МОЖЕ бути ОДНИМ із кількох перелічених
// типів — саме так у JS ЗАЗВИЧАЙ поводиться змінна, коли розробник
// сам, вручну, тримає в голові "тут або число, або рядок":

let id: number | string;
id = 42;      // ok
id = "abc123"; // ok
// id = true;  // ❌ Type 'boolean' is not assignable to type 'string | number'.

// У ЧИСТОМУ JS цей самий факт ("id — число АБО рядок") ЖИВЕ ЛИШЕ
// В ГОЛОВІ розробника й у назвах/коментарях — компілятора, який
// би це перевірив, немає взагалі:
//   let idJS = 42;
//   idJS = "abc123"; // ok, JS не заперечує НІЧОГО
//   idJS = true;      // теж "ok" для JS — жодного попередження


// 2. UNION У ПАРАМЕТРАХ ФУНКЦІЙ — НАЙЧАСТІШЕ ЗАСТОСУВАННЯ
// -----------------------------------------------------
function formatId(id: number | string): string {
  return `ID-${id}`;
}
console.log(formatId(42));      // "ID-42"
console.log(formatId("abc123")); // "ID-abc123"


// 3. NARROWING — ЗВУЖЕННЯ UNION ДО КОНКРЕТНОГО ТИПУ ПЕРЕД ВИКОРИСТАННЯМ
// -----------------------------------------------------
// Компілятор дозволяє викликати ЛИШЕ ТІ методи/операції, які є
// СПІЛЬНИМИ для ВСІХ варіантів union — інакше він не може гарантувати
// безпеку. Щоб отримати доступ до методів, властивих лише ОДНОМУ з
// варіантів, треба спершу "звузити" (narrow) тип перевіркою:

function printId(id: number | string) {
  // id.toUpperCase(); // ❌ Property 'toUpperCase' does not exist on type 'number'.
  //                      (toUpperCase є лише в string, а не в number)

  if (typeof id === "string") {
    console.log(id.toUpperCase()); // ✅ тут TS ЗНАЄ, що id — саме string
  } else {
    console.log(id.toFixed(2)); // ✅ а тут — що id саме number
  }
}
printId(42);       // "42.00"
printId("abc123"); // "ABC123"

// typeof — найпростіший спосіб звуження ДЛЯ ПРИМІТИВІВ. Для об'єктних
// типів (кілька форм об'єктів в union) використовують ІНШІ техніки —
// детально розглянемо їх в окремому файлі про narrowing/type guards
// (тут — лише побіжний приклад на "дискримінантному" полі):

type SuccessResponse = { status: "success"; data: string[] };
type ErrorResponse = { status: "error"; message: string };
type ApiResponse = SuccessResponse | ErrorResponse; // DISCRIMINATED UNION —
                                                        // об'єднання з "спільним"
                                                        // полем-міткою (тут — status)

function handleResponse(response: ApiResponse) {
  if (response.status === "success") {
    console.log(response.data.join(", ")); // TS звузив до SuccessResponse
  } else {
    console.log(`Помилка: ${response.message}`); // TS звузив до ErrorResponse
  }
}
handleResponse({ status: "success", data: ["a", "b"] }); // "a, b"
handleResponse({ status: "error", message: "не знайдено" }); // "Помилка: не знайдено"


// 4. LITERAL TYPES У UNION — "ENUM-ПОДІБНИЙ" НАБІР ДОЗВОЛЕНИХ ЗНАЧЕНЬ
// -----------------------------------------------------
// Union МОЖЕ складатися не лише з "широких" типів (string, number),
// а й з КОНКРЕТНИХ, ЛІТЕРАЛЬНИХ значень — тоді дозволені ЛИШЕ САМЕ
// ЦІ значення, і жодні інші рядки/числа:

type Direction = "up" | "down" | "left" | "right";
function move(direction: Direction) {
  console.log(`рух: ${direction}`);
}
move("up");   // ok
// move("north"); // ❌ Argument of type '"north"' is not assignable
                    // to parameter of type 'Direction'.

// У ЧИСТОМУ JS для того самого замінника "enum" зазвичай пишуть
// об'єкт зі СТАЛИМИ значеннями (детально в common/data-structures/Symbol/Symbol.js,
// приклад Direction через Object.freeze + Symbol) — але це ЛИШЕ
// РАНТАЙМ-захист від колізій, а НЕ перевірка на етапі компіляції.
// Literal union у TS — це саме та compile-time перевірка, якої в
// чистому JS-підході немає взагалі.

type HttpMethod = "GET" | "POST" | "PUT" | "DELETE";
function request(url: string, method: HttpMethod = "GET") {
  console.log(`${method} ${url}`);
}
request("/users");             // "GET /users"
request("/users", "POST");     // "POST /users"
// request("/users", "PATCH"); // ❌ не входить у HttpMethod


// ==========================================================================
// 5. INTERSECTION TYPES (`&`) — "ЦЕ Й ТЕ ОДНОЧАСНО"
// ==========================================================================

// Intersection ОБ'ЄДНУЄ КІЛЬКА типів у ОДИН, що МАЄ мати УСІ поля
// з КОЖНОГО з них одночасно — це протилежність union:

type Named = { name: string };
type Aged = { age: number };
type Person = Named & Aged; // МАЄ мати і name, І age

const person: Person = { name: "Ірина", age: 30 }; // обидва поля обов'язкові
// const incomplete: Person = { name: "Ірина" }; // ❌ Property 'age' is missing


// 6. НАЙЧАСТІШЕ ЗАСТОСУВАННЯ INTERSECTION: "ДОДАВАННЯ" ПОВЕДІНКИ/ПОЛІВ
// -----------------------------------------------------
// Intersection зручний для комбінування "базових" типів у більш
// специфічні, БЕЗ повторного опису спільних полів (аналог міксинів
// із common/prototypal-inheritance.js, але на рівні системи типів,
// а не рантайм-об'єктів):

type Timestamped = { createdAt: Date };
type Identifiable = { id: number };

type Entity = Identifiable & Timestamped; // спільна "база" для будь-якої сутності
type User = Entity & { email: string };   // User = id + createdAt + email
type Product = Entity & { price: number }; // Product = id + createdAt + price

const newUser: User = {
  id: 1,
  createdAt: new Date(),
  email: "user@example.com",
};
const newProduct: Product = {
  id: 100,
  createdAt: new Date(),
  price: 29.99,
};
console.log(newUser.email, newProduct.price);


// 7. INTERSECTION ІЗ ПРИМІТИВАМИ — ЧАСТО ДАЄ `never` (ПОШИРЕНА ПАСТКА)
// -----------------------------------------------------
// На відміну від union, intersection ДВОХ НЕСУМІСНИХ примітивних
// типів не має жодного реального значення, яке відповідало б ОБОМ
// одночасно — TS зводить такий тип до never (детально never — у
// typescript/basic-types.ts):

type ImpossibleType = string & number; // немає значення, що є ОДНОЧАСНО
                                          // і рядком, і числом → тип never
// let impossible: ImpossibleType = "текст"; // ❌ Type 'string' is not
                                                // assignable to type 'never'.

// ЦЕ ЛОГІЧНО: & працює природно для ОБ'ЄКТНИХ типів (просто "додає"
// поля одне до одного), але для примітивів немає "перетину" —
// значення не може бути одночасно і числом, і рядком.


// ==========================================================================
// 8. UNION VS INTERSECTION НА МАСИВАХ/ФУНКЦІЯХ — НЕОЧЕВИДНА РІЗНИЦЯ
// ==========================================================================

// Об'єднання (`|`) МАСИВІВ — це масив, елементи якого можуть бути
// БУДЬ-ЯКОГО з перелічених типів (той самий принцип, що й у
// typescript/basic-types.ts, п. 4):
let unionArray: (number | string)[] = [1, "два", 3, "чотири"];

// Перетин (`&`) ФУНКЦІЙ — рідкісний, але цікавий випадок: функція,
// що відповідає ОБОМ сигнатурам одночасно (застосовується для
// "перевантаження" функцій-об'єктів, callable + додаткові властивості):
type Loggable = { log: (msg: string) => void };
type Callable = (msg: string) => void;
type LoggerFunction = Callable & Loggable; // функція, яка ТАКОЖ має метод .log

function makeLogger(): LoggerFunction {
  const fn = ((msg: string) => console.log(msg)) as LoggerFunction;
  fn.log = (msg: string) => console.log(`[LOG] ${msg}`);
  return fn;
}
const logger = makeLogger();
logger("звичайний виклик");   // "звичайний виклик"
logger.log("через метод log"); // "[LOG] через метод log"


// ==========================================================================
// 9. UNION VS INTERSECTION — ШПАРГАЛКА-ПОРІВНЯННЯ
// ==========================================================================

// | Критерій                     | Union (`\|`)                        | Intersection (`&`)                    |
// |---------------------------------|----------------------------------------|-------------------------------------------|
// | Сенс                           | "ОДНЕ з перелічених"                  | "УСІ перелічені одночасно"              |
// | Кількість дозволених полів     | лише СПІЛЬНІ для всіх варіантів       | ВСІ поля з КОЖНОГО типу разом            |
// | Типове застосування            | параметр, що приймає кілька форм      | комбінування "базових" типів у складніший |
// | З примітивами                  | природно (number \| string)          | часто дає never (string & number)       |
// | Потрібне звуження (narrowing)  | ТАК — перед використанням специфічних полів | НІ — усі поля вже доступні одразу |


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - Union (A | B) — значення МОЖЕ бути одним із перелічених типів;
//   доступні напряму лише операції, СПІЛЬНІ для ВСІХ варіантів —
//   для решти потрібне звуження (typeof, дискримінантне поле тощо)
// - Intersection (A & B) — значення МАЄ відповідати ВСІМ перелученим
//   типам одночасно; для об'єктів це означає "має всі поля з обох";
//   для примітивів найчастіше зводиться до never
// - literal types у union (`"up" | "down"`) — compile-time аналог
//   enum-подібного набору дозволених значень, якого в чистому JS
//   немає взагалі (лише рантайм-угоди типу Object.freeze)
// - discriminated union (об'єднання з "полем-міткою", напр. `status`)
//   — найпоширеніший практичний патерн: TS автоматично звужує тип
//   усередині if/switch за значенням цього поля
// - у чистому JS еквівалент union/intersection існує ЛИШЕ як усна
//   домовленість чи коментар — жодної перевірки компілятора немає,
//   і помилка виявляється тільки під час реального виконання коду