// ==========================================================================
// INLINE CACHING & PREDICTABILITY — V8 OPTIMIZATION
// ==========================================================================

// 0. ЗАГАЛЬНА ІДЕЯ
// -----------------------------------------------------
// V8 запам'ятовує, ЯКУ ФОРМУ об'єкта очікує функція, і КЕШУЄ доступ до
// властивостей (детально механіка Shape/offset розібрана в
// 01-hidden-classes.js). Якщо форми непередбачувані — кеш РОЗШИРЮЄТЬСЯ
// і стає неефективним.
//
// Основне правило: функція повинна очікувати ОДИН набір типів об'єктів.
// Уникай мегаморфізму (>4 різних форм).


// ==========================================================================
// 1. ЯК ПРАЦЮЄ INLINE CACHE (IC) — КОРОТКИЙ ПОВТОР МЕХАНІКИ
// ==========================================================================

// Коли функція звертається до obj.prop, V8 НЕ хоче щоразу шукати offset
// властивості "з нуля" — натомість кешує ПАРУ (Shape → offset) прямо
// в місці виклику (тому і "inline" — кеш "вбудований" у сам байткод
// виклику, а не десь окремо):

function getX(obj) {
  return obj.x;
}

// ПЕРШИЙ виклик — V8 "вчиться":
getX({ x: 1, y: 2 }); // Shape 1 → x на offset 8. Записано в IC: [Shape1 → 8]

// ДРУГИЙ виклик з ТІЄЮ Ж ФОРМОЮ — IC "влучає" (cache hit), швидко:
getX({ x: 3, y: 4 }); // Shape 1 знову → офсет береться з кешу, без пошуку


// ==========================================================================
// 2. МОНОМОРФНИЙ, ПОЛІМОРФНИЙ, МЕГАМОРФНИЙ IC — СТАНИ КЕШУ
// ==========================================================================

// MONOMORPHIC IC (1 форма в кеші) — найшвидший стан:
function getXMono(obj) {
  return obj.x;
}
const createPoint = (x, y) => ({ x, y }); // ЗАВЖДИ той самий порядок → та сама форма
getXMono(createPoint(1, 2));
getXMono(createPoint(3, 4));
getXMono(createPoint(5, 6));
// V8 бачить ЗАВЖДИ ОДНУ форму → IC monomorphic → maximally fast path

// POLYMORPHIC IC (2-4 форми в кеші) — досі прийнятно:
getXMono({ x: 1, y: 2 });      // Shape A
getXMono({ y: 2, x: 1 });      // Shape B — ІНШИЙ порядок! IC розширюється до [A, B]
// V8 перевіряє форму по черзі серед запам'ятованих (до 4) — усе ще
// швидко, але вже трохи більше інструкцій, ніж monomorphic

// MEGAMORPHIC IC (>4 форм) — крах оптимізацій:
function getXMega(obj) {
  return obj.x;
}
getXMega({ x: 1, y: 2 });          // Shape A
getXMega({ y: 2, x: 1 });          // Shape B
getXMega({ x: 1, y: 2, z: 3 });    // Shape C
getXMega({ x: 1 });                // Shape D
getXMega({ a: 1, x: 2, b: 3 });    // Shape E ← Megamorphic!
// V8: "Забудь про детальний кеш, просто інтерпретуй" — lookup(obj, "x")
// у ЗАГАЛЬНІЙ таблиці замість прямого offset — 10-20x повільніше


// ==========================================================================
// 3. ЧОМУ ЦЕ НАСПРАВДІ ВАЖЛИВО: IC — ОСНОВА БАГАТЬОХ ІНШИХ ОПТИМІЗАЦІЙ
// ==========================================================================

// Inline Caching — це "клей", що зв'язує Hidden Classes (форма об'єкта)
// з реальним машинним кодом доступу до властивості. Саме через IC:
//   - property access стає O(1) замість O(log n)/O(n)
//   - TurboFan може ІНЛАЙНИТИ доступ до властивості прямо в код функції,
//     ЯКЩО впевнений (monomorphic), що форма завжди одна й та сама
//   - будь-яка нестабільність форми ЗМЕНШУЄ ефективність IC пропорційно
//     до кількості різних форм, що проходять через один і той самий
//     виклик властивості


// ==========================================================================
// ПРАВИЛА ДЛЯ ПЕРЕДБАЧУВАНИХ IC
// ==========================================================================

// ПРАВИЛО 1: Одна "фабрика" на один тип об'єкта
// -----------------------------------------------------
// ❌ Неправильно: різні функції створюють об'єкти з РІЗНИМ порядком
// властивостей, а потім усі проходять через ОДНУ функцію-споживач:
function createUserA(name, age) {
  return { name, age };
}
function createUserB(name, age) {
  return { age, name }; // інший порядок → інша форма!
}
function greetUser(user) {
  return `Привіт, ${user.name}!`;
}
greetUser(createUserA("Ірина", 30)); // Shape A
greetUser(createUserB("Олег", 25));  // Shape B ← IC розширюється

// ✅ Правильно: одна фабрика гарантує ОДНУ форму для всіх користувачів
function createUser(name, age) {
  return { name, age };
}
greetUser(createUser("Ірина", 30));
greetUser(createUser("Олег", 25));
// обидва виклики — Shape A → IC лишається monomorphic


// ПРАВИЛО 2: Не змінюй набір/тип властивостей ПІСЛЯ створення
// -----------------------------------------------------
// (детально в 01-hidden-classes.js — тут коротко в контексті IC:
// кожна зміна форми ПІСЛЯ створення — це НОВИЙ Shape, і функції,
// які вже кешували стару форму, отримають cache miss на цьому об'єкті)


// ПРАВИЛО 3: Обмежуй кількість "форм", що проходять через одну функцію
// -----------------------------------------------------
// Якщо функція ПРИНЦИПОВО повинна працювати з РІЗНИМИ типами об'єктів
// (>4 форм) — розглянь розділення на кілька спеціалізованих функцій
// замість однієї "універсальної", яка неминуче стане megamorphic.

// ❌ Одна універсальна функція для геометричних фігур різної форми:
function getAreaBad(shape) {
  if (shape.kind === "circle") return Math.PI * shape.radius ** 2;
  if (shape.kind === "rectangle") return shape.width * shape.height;
  if (shape.kind === "triangle") return 0.5 * shape.base * shape.height;
  // ще 2+ форми — і getAreaBad стає megamorphic
}

// ✅ Спеціалізовані функції для кожної форми — кожна лишається monomorphic:
function getCircleArea(circle) {
  return Math.PI * circle.radius ** 2;
}
function getRectangleArea(rect) {
  return rect.width * rect.height;
}
function getTriangleArea(triangle) {
  return 0.5 * triangle.base * triangle.height;
}


// ==========================================================================
// ВПЛИВ НА ПРОДУКТИВНІСТЬ — БЕНЧМАРК
// ==========================================================================

const { performance } = require("perf_hooks");

function readX(obj) {
  return obj.x;
}

// Monomorphic: 100000 об'єктів, УСІ однієї форми
const monoObjects = Array.from({ length: 100000 }, () => ({ x: 1, y: 2 }));
let t0 = performance.now();
for (let i = 0; i < 10000000; i++) {
  readX(monoObjects[i % monoObjects.length]);
}
console.log(`Monomorphic IC:  ${(performance.now() - t0).toFixed(0)}ms`);

// Megamorphic: 100000 об'єктів, ЧЕРГУЮТЬСЯ 5 РІЗНИХ форм
const megaObjects = Array.from({ length: 100000 }, (_, i) => {
  const variant = i % 5;
  if (variant === 0) return { x: 1, y: 2 };
  if (variant === 1) return { y: 2, x: 1 };
  if (variant === 2) return { x: 1, y: 2, z: 3 };
  if (variant === 3) return { x: 1 };
  return { a: 1, x: 2, b: 3 };
});
t0 = performance.now();
for (let i = 0; i < 10000000; i++) {
  readX(megaObjects[i % megaObjects.length]);
}
console.log(`Megamorphic IC:  ${(performance.now() - t0).toFixed(0)}ms`);

// Орієнтовний результат: monomorphic у кілька разів швидший за
// megamorphic на тому самому обсязі викликів (конкретні цифри залежать
// від версії V8 і заліза, але напрям завжди той самий).


// ==========================================================================
// ПІДСУМОК
// ==========================================================================
// - Inline Cache (IC) — механізм, що запам'ятовує ЯКУ форму (Shape)
//   очікує конкретне місце виклику obj.prop, і кешує offset для неї
// - monomorphic IC (1 форма) — найшвидший стан, дає V8 змогу навіть
//   інлайнити доступ до властивості прямо в машинний код
// - polymorphic IC (2-4 форми) — досі прийнятно, V8 перевіряє форми
//   по черзі серед невеликого списку запам'ятованих
// - megamorphic IC (>4 форм) — крах: V8 переходить на повільний,
//   загальний lookup замість прямого offset (10-20x повільніше)
// - IC — це та причина, чому Hidden Classes (форма об'єкта) настільки
//   важливі: саме IC перетворює стабільну форму на реальний приріст
//   швидкості коду
//
// ПРАКТИЧНІ ПРАВИЛА:
// - використовуй ОДНУ фабричну функцію/клас для кожного типу об'єкта,
//   щоб гарантувати однакову форму всюди, де цей тип споживається
// - не змінюй набір чи типи властивостей об'єкта ПІСЛЯ його створення
// - якщо функція ПРИНЦИПОВО повинна обробляти багато різних форм —
//   розділяй її на спеціалізовані функції під кожну форму окремо