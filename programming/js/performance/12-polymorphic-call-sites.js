// - поліморфізм СТОСУЄТЬСЯ не лише ФОРМИ об'єктів (Hidden Classes), а й
//   САМОГО МІСЦЯ ВИКЛИКУ функції/методу (call site) — якщо один і той
//   самий рядок коду постійно викликає РІЗНІ конкретні функції
// - polymorphic call site (2-4 варіанти) зазвичай дешевший за
//   megamorphic property access, але ВСЕ ОДНО заважає inlining
// - якщо кількість варіантів зростає (>4) — деградує до мегаморфного
//   виклику з відповідними штрафами
// - практичне правило: групуй однотипні виклики РАЗОМ (окремі цикли/
//   функції для кожного типу), а не чергуй їх у одному гарячому шляху;
//   уникай передачі РІЗНИХ функцій-колбеків в один і той самий
//   call site в гарячому коді
// - для невеликої, стабільної кількості варіантів команд — явний
//   switch часто передбачуваніший за динамічний виклик з таблиці
//   обробників