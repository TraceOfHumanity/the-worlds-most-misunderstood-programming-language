// 0. ЗАГАЛЬНА ІДЕЯ
// -----------------------------------------------------
// 01-hidden-classes.js та 04-inline-caching.js розглядали мономорфізм
// ФОРМИ ОБ'ЄКТА (obj.prop). Але є ще ОДИН, окремий вид поліморфізму —
// поліморфізм САМОГО МІСЦЯ ВИКЛИКУ (call site) функції/методу, коли
// РІЗНІ виклики того самого рядка коду фактично викликають РІЗНІ
// функції (наприклад, через різні класи з одним і тим самим методом,
// або через передачу різних колбеків в один і той самий пайплайн).
//
// Це ОКРЕМА причина деоптимізації, не пов'язана напряму з формою
// властивостей об'єкта.


// ==========================================================================
// 1. МОНОМОРФНИЙ VS ПОЛІМОРФНИЙ ВИКЛИК МЕТОДУ
// ==========================================================================

// Коли викликаєш obj.method(), V8 кешує НЕ ЛИШЕ offset властивості
// "method", а й САМУ ФУНКЦІЮ, яку знайшов там востаннє. Якщо наступного
// разу за тим самим call site знаходиться ІНША функція (навіть з тим
// самим ім'ям методу, але з іншого класу/прототипу) — це still МОЖЕ
// призводити до polymorphic/megamorphic call site, аналогічно
// property access.

class Circle {
  constructor(radius) {
    this.radius = radius;
  }
  area() {
    return Math.PI * this.radius ** 2;
  }
}
class Square {
  constructor(side) {
    this.side = side;
  }
  area() {
    return this.side * this.side;
  }
}

function computeArea(shape) {
  return shape.area(); // call site, що бачить РІЗНІ area() залежно від типу shape
}

const shapes = [new Circle(2), new Square(3), new Circle(4), new Square(5)];
// ЧЕРГУВАННЯ Circle/Square у ОДНОМУ й тому самому виклику computeArea() —
// класичний приклад поліморфного call site: V8 бачить ≥2 різних
// "цільових" функцій за одним викликом shape.area()
let totalArea = 0;
for (const shape of shapes) {
  totalArea += computeArea(shape);
}
console.log(totalArea.toFixed(2));


// ==========================================================================
// 2. ЧОМУ ЦЕ "ДЕШЕВШЕ", НІЖ MEGAMORPHIC PROPERTY ACCESS, АЛЕ ВСЕ ОДНО ВАЖЛИВО
// ==========================================================================

// На відміну від мегаморфної форми об'єкта (10-20x штраф), поліморфний
// виклик методу (2-4 різні "цілі") зазвичай ДЕШЕВШИЙ — сучасні рушії
// добре тримають polymorphic call sites для НЕВЕЛИКОЇ кількості
// варіантів. АЛЕ:
//   - це ЗАВАЖАЄ inlining (V8 не може "вбудувати" тіло методу прямо в
//     місце виклику, якщо не впевнений, ЯКИЙ САМЕ метод там опиниться) —
//     а саме inlining відкриває двері для подальших оптимізацій
//     (детально в 06-function-size.js)
//   - якщо кількість варіантів РОСТЕ (>4 різних класів з тим самим
//     методом, що проходять через один call site) — це деградує до
//     мегаморфного виклику, з тими самими штрафами, що й для властивостей


// ==========================================================================
// ПРАВИЛА
// ==========================================================================

// ПРАВИЛО 1: Групуй однотипні виклики разом, а не чергуй їх
// -----------------------------------------------------
// ❌ Чергування типів через один call site (як у прикладі вище)
function computeTotalMixed(shapes) {
  let total = 0;
  for (const shape of shapes) {
    total += shape.area(); // call site бачить Circle/Square по черзі
  }
  return total;
}

// ✅ Розділи за типом — кожен call site бачить ОДИН тип
function computeTotalGrouped(circles, squares) {
  let total = 0;
  for (const c of circles) total += c.area(); // цей call site — тільки Circle
  for (const s of squares) total += s.area(); // цей call site — тільки Square
  return total;
}

const circles = shapes.filter((s) => s instanceof Circle);
const squares = shapes.filter((s) => s instanceof Square);
console.log(computeTotalGrouped(circles, squares).toFixed(2));


// ПРАВИЛО 2: Обережно з callback-параметрами, що постійно змінюються
// -----------------------------------------------------
// Кожен виклик array.map(callback)/array.forEach(callback) — це ТЕЖ
// call site. Якщо в ОДНОМУ й тому самому місці коду ти постійно
// передаєш РІЗНІ функції (наприклад, різні стрілкові функції, створені
// щоразу наново, залежно від умови) — V8 бачить це як окремі "цілі"
// виклику для внутрішнього виклику callback(item) всередині .map().

// ❌ Різна функція-колбек залежно від умови, той самий call site всередині pipeline
function transformBad(items, useDouble) {
  const fn = useDouble ? (x) => x * 2 : (x) => x + 1; // РІЗНІ функції!
  return items.map(fn); // call site всередині map викликає то одну, то іншу
}

// ✅ Розділи на дві явні, стабільні функції
function double(x) {
  return x * 2;
}
function incrementByOne(x) {
  return x + 1;
}
function transformDouble(items) {
  return items.map(double); // цей call site завжди бачить ОДНУ функцію
}
function transformIncrement(items) {
  return items.map(incrementByOne); // і цей теж
}


// ПРАВИЛО 3: Уникай "універсальних" диспетчерів з великою кількістю гілок
// -----------------------------------------------------
// ❌ Один диспетчер для БАГАТЬОХ типів команд — call site handlers[cmd.type]()
// стає megamorphic, коли типів команд багато й вони чергуються часто
function executeCommandBad(cmd, handlers) {
  return handlers[cmd.type](cmd.payload); // виклик "невідомо якої" функції з мапи
}

// ✅ Якщо типів мало (2-4) і вони стабільні в межах "гарячого" пайплайна —
// залиш явний диспетчер через switch (передбачувані branch, див.
// 08-branch-prediction.js) замість динамічного виклику з таблиці
function executeCommand(cmd) {
  switch (cmd.type) {
    case "move":
      return `move to ${cmd.payload}`;
    case "attack":
      return `attack ${cmd.payload}`;
    default:
      return "unknown command";
  }
}
console.log(executeCommand({ type: "move", payload: "north" }));


